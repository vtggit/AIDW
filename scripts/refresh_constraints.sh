#!/usr/bin/env bash
# Regenerate backend/constraints.txt from a fresh resolve of backend/requirements.txt.
#
# The backend image and CI install with `-c backend/constraints.txt`, so the exact
# versions that ship are the ones in that file. Nothing upgrades by accident. To take
# upgrades on purpose:
#
#   1. scripts/refresh_constraints.sh
#   2. review `git diff backend/constraints.txt`
#   3. open a pull request; CI runs the suite and the dependency audit on the new set
#
# It resolves inside the same base image the Dockerfile builds from, so the result is
# what a fresh image would get. Needs docker.
set -euo pipefail

cd "$(dirname "$0")/.."

base="$(sed -n 's/^FROM \([^ ]*\).*/\1/p' backend/Dockerfile | head -n 1)"
if [ -z "$base" ]; then
  echo "could not read the base image from backend/Dockerfile" >&2
  exit 2
fi

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

docker run --rm -v "$PWD/backend/requirements.txt:/requirements.txt:ro" "$base" sh -c \
  'pip install --no-cache-dir --quiet --root-user-action=ignore -r /requirements.txt >&2 && pip freeze --exclude-editable' \
  > "$tmp"

if ! grep -q '==' "$tmp"; then
  echo "the resolve produced no pinned versions; backend/constraints.txt is unchanged" >&2
  exit 1
fi

{
  echo "# Exact versions of every package the backend image installs."
  echo "# Generated by scripts/refresh_constraints.sh from backend/requirements.txt."
  echo "# Do not edit by hand: run the script, review the diff, open a pull request."
  LC_ALL=C sort -f "$tmp"
} > backend/constraints.txt

echo "backend/constraints.txt: $(grep -c '==' backend/constraints.txt) packages pinned"
