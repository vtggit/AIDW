/**
 * Mock every /api/** request for upcoming page loads: auth endpoints for
 * `me`, the retention endpoints with the given policies and no runs, 30
 * sources, and every other API call an empty JSON array (the Studio boot
 * fetches many lists on startup).
 */
async function mockApi(page, me, policies) {
  await page.unrouteAll();
  await page.route('**/api/**', (route) => {
    const url = route.request().url();
    if (url.includes('/api/auth/config')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(AUTH_CONFIG) });
    }
    if (url.includes('/api/auth/me')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(me) });
    }
    if (url.includes('/api/retention-policies')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(policies) });
    }
    if (url.includes('/api/retention-runs')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
    }
    if (url.includes('/api/sources')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(SOURCES) });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
  });
}

test('issue803 freeform', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await mockApi(page, ADMIN_ME, POLICIES_3);
  await page.goto('/studio.html?panel=retention');

  const policyRows = page.locator('[data-testid="retention-policy-row"]');
  await expect(policyRows).toHaveCount(3);
  await expect(page.locator('[data-testid="retention-policy-table"]')).toBeVisible();

  // Choose the first policy.
  await policyRows.first().click();
  await expect(page.locator('[data-testid="retention-policy-row"][data-id="pol-0"]')).toHaveAttribute('aria-selected', 'true');

  // Every colour below is read as a plain string with getComputedStyle.
  const colors = await page.evaluate(() => {
    const row = document.querySelector('[data-testid="retention-policy-row"][aria-selected="true"]');
    const unchosen = document.querySelector('[data-testid="retention-policy-row"][data-id="pol-1"]');
    const style = (el) => getComputedStyle(el);
    const nameOf = (el) => el.querySelector('[data-testid="retention-policy-name"]');
    const buttons = Array.from(row.querySelectorAll('button')).map((btn) => ({
      testid: btn.getAttribute('data-testid'),
      bg: style(btn).backgroundColor,
      color: style(btn).color,
    }));
    const root = getComputedStyle(document.documentElement);
    return {
      chosenBg: style(row).backgroundColor,
      unchosenBg: style(unchosen).backgroundColor,
      chosenNameColor: style(nameOf(row)).color,
      unchosenNameColor: style(nameOf(unchosen)).color,
      enabledLabelColor: style(row.querySelector('[data-testid="retention-policy-enabled-label"]')).color,
      firstCellShadow: style(row.querySelector('td:first-child')).boxShadow,
      rowDirection: style(row).direction,
      buttons,
      accentToken: root.getPropertyValue('--color-accent').trim(),
      surfaceToken: root.getPropertyValue('--color-surface').trim(),
      inkToken: root.getPropertyValue('--color-ink').trim(),
    };
  });

  // The chosen row's background (a color-mix tint) differs from an
  // unchosen row's...
  expect(parseColor(colors.chosenBg), 'the chosen row background parses as a colour').not.toBeNull();
  expect(parseColor(colors.unchosenBg), 'the unchosen row background parses as a colour').not.toBeNull();
  expect(
    JSON.stringify(parseColor(colors.chosenBg)),
    'the chosen row is tinted differently from an unchosen row'
  ).not.toBe(JSON.stringify(parseColor(colors.unchosenBg)));
  // ...and the chosen row's text keeps the unchosen row's ink colour.
  expect(colors.chosenNameColor, 'the chosen row text keeps the ink colour').toBe(colors.unchosenNameColor);

  // WCAG contrast of the chosen row's text against its own background:
  // the policy's text and the enabled label each reach at least 4.5.
  expect(
    contrastRatio(colors.chosenNameColor, colors.chosenBg),
    'the chosen row name cell contrast is at least 4.5'
  ).toBeGreaterThanOrEqual(4.5);
  expect(
    contrastRatio(colors.enabledLabelColor, colors.chosenBg),
    'the chosen row enabled label contrast is at least 4.5'
  ).toBeGreaterThanOrEqual(4.5);

  // The row's start edge carries the accent colour (the 3 px bar).
  const barMatch = colors.firstCellShadow.match(/(rgba?\([^)]*\)|color\(srgb[^)]*\)|#[0-9a-f]{3,8})/i);
  expect(barMatch, 'the chosen row carries a bar at its start edge').not.toBeNull();
  expect(colors.firstCellShadow, 'the bar is an inset shadow at the row start').toContain('inset');
  expect(
    JSON.stringify(parseColor(barMatch[1])),
    'the bar is the accent colour'
  ).toBe(JSON.stringify(parseColor(colors.accentToken)));

  // ...and the bar points at the row's START edge: in LTR an inset shadow
  // paints its bar on the left only with a positive horizontal offset and
  // a zero vertical offset - a negative x would bar the end edge, and any
  // non-zero y would bar a top or bottom edge instead.
  const bar = parseBoxShadow(colors.firstCellShadow);
  expect(bar, 'the chosen row start-edge bar parses as a box-shadow').not.toBeNull();
  expect(bar.inset, 'the bar is an inset shadow at the row start').toBe(true);
  const barStartX = colors.rowDirection === 'rtl' ? -bar.x : bar.x;
  expect(barStartX, 'the bar sits at the row start edge (left in LTR), not the end edge').toBe(3);
  expect(bar.y, 'the bar spans the full row height (not a top or bottom edge)').toBe(0);
  expect(bar.blur, 'the bar is crisp (no blur)').toBe(0);
  expect(bar.spread, 'the bar width comes from its start-edge offset alone').toBe(0);

  // The row's buttons (Edit, Delete, Run sweep now and the
  // Enable/Disable toggle) each keep their own surface background and
  // ink text on the tinted row.
  const buttonIds = colors.buttons.map((btn) => btn.testid);
  for (const testid of [
    'retention-policy-edit',
    'retention-policy-delete',
    'retention-policy-sweep-now',
    'retention-policy-toggle',
  ]) {
    expect(buttonIds, 'the chosen row carries its ' + testid + ' button').toContain(testid);
  }
  for (const btn of colors.buttons) {
    expect(
      JSON.stringify(parseColor(btn.bg)),
      'the row button "' + btn.testid + '" keeps the surface background'
    ).toBe(JSON.stringify(parseColor(colors.surfaceToken)));
    expect(
      JSON.stringify(parseColor(btn.color)),
      'the row button "' + btn.testid + '" keeps the ink text'
    ).toBe(JSON.stringify(parseColor(colors.inkToken)));
  }

  // "Delete" pressed in the chosen row: the confirmation text's contrast
  // against the row's background is at least 4.5.
  await page.locator('[data-testid="retention-policy-row"][data-id="pol-0"] [data-testid="retention-policy-delete"]').click();
  const deleteText = page.locator('[data-testid="retention-policy-delete-text"]');
  await expect(deleteText).toBeVisible();
  await expect(deleteText).toHaveText('Delete Purge policy 0?');
  const deleteColor = await page.evaluate(() =>
    getComputedStyle(document.querySelector('[data-testid="retention-policy-delete-text"]')).color
  );
  expect(
    contrastRatio(deleteColor, colors.chosenBg),
    'the delete confirmation text contrast is at least 4.5'
  ).toBeGreaterThanOrEqual(4.5);

  // Cancel restores the row's actions...
  await page.locator('[data-testid="retention-policy-delete-cancel"]').click();
  await expect(page.locator('[data-testid="retention-policy-row"][data-id="pol-0"] [data-testid="retention-policy-delete"]')).toBeVisible();

  // ...and "Run sweep now" pressed in the chosen row: the sweep
  // confirmation text's contrast against the row's background is at
  // least 4.5.
  await page.locator('[data-testid="retention-policy-row"][data-id="pol-0"] [data-testid="retention-policy-sweep-now"]').click();
  const sweepText = page.locator('[data-testid="retention-sweep-confirm-text"]');
  await expect(sweepText).toBeVisible();
  await expect(sweepText).toHaveText('This permanently deletes runs records older than 30 days. Type the policy name to confirm.');
  const sweepColor = await page.evaluate(() =>
    getComputedStyle(document.querySelector('[data-testid="retention-sweep-confirm-text"]')).color
  );
  expect(
    contrastRatio(sweepColor, colors.chosenBg),
    'the sweep confirmation text contrast is at least 4.5'
  ).toBeGreaterThanOrEqual(4.5);
  await page.locator('[data-testid="retention-sweep-cancel"]').click();
  await expect(page.locator('[data-testid="retention-sweep-confirm"]')).toHaveCount(0);

  // Hovering the chosen row leaves its background unchanged...
  await policyRows.first().hover();
  const hoveredChosenBg = await page.evaluate(() =>
    getComputedStyle(document.querySelector('[data-testid="retention-policy-row"][aria-selected="true"]')).backgroundColor
  );
  expect(hoveredChosenBg, 'hovering the chosen row leaves its background unchanged').toBe(colors.chosenBg);
  // ...and hovering an unchosen row gives a background different from
  // the chosen row's.
  await policyRows.nth(1).hover();
  const hoveredUnchosenBg = await page.evaluate(() =>
    getComputedStyle(document.querySelector('[data-testid="retention-policy-row"][data-id="pol-1"]')).backgroundColor
  );
  expect(hoveredUnchosenBg, 'a hovered unchosen row differs from the chosen row').not.toBe(colors.chosenBg);
  expect(
    JSON.stringify(parseColor(hoveredUnchosenBg)),
    'a hovered unchosen row differs from the chosen row'
  ).not.toBe(JSON.stringify(parseColor(colors.chosenBg)));

  // With 200 policies at 1440x900: still no document scroll and no
  // main-region scroll (issue #800's fit survives the new tint).
  await mockApi(page, ADMIN_ME, POLICIES_200);
  await page.goto('/studio.html?panel=retention');
  await expect(page.locator('[data-testid="retention-policy-row"]')).toHaveCount(POLICY_COUNT);
  const locked = await page.evaluate(() => {
    const region = document.querySelector('[data-testid="main-content"]');
    return {
      doc: document.scrollingElement.scrollHeight - document.scrollingElement.clientHeight,
      body: document.body.scrollHeight - document.body.clientHeight,
      region: region.scrollHeight - region.clientHeight,
    };
  });
  expect(locked.doc, 'no document scroll').toBeLessThanOrEqual(0);
  expect(locked.body, 'no document scroll').toBeLessThanOrEqual(0);
  expect(locked.region, 'no main-region scroll').toBeLessThanOrEqual(0);
});

test('issue803 freeform (viewer)', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });

  // Boot the production way for a role 'user' identity: the token rides
  // the URL hash (#access_token=...), /api/auth/config and /api/auth/me
  // are mocked for that user, and the hash token must reach
  // /api/auth/me as a Bearer header.
  const meAuthorizations = [];
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = request.url();
    if (url.includes('/api/auth/config')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(AUTH_CONFIG) });
    }
    if (url.includes('/api/auth/me')) {
      const auth = request.headers()['authorization'];
      if (auth) meAuthorizations.push(auth);
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(VIEWER_ME) });
    }
    if (url.includes('/api/retention-policies')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(POLICIES_3) });
    }
    if (url.includes('/api/retention-runs')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
    }
    if (url.includes('/api/sources')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(SOURCES) });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
  });

  await page.goto('/studio.html?panel=retention#access_token=' + encodeURIComponent(VIEWER_TOKEN));
  await expect.poll(() => meAuthorizations).toContain('Bearer ' + VIEWER_TOKEN);

  // The page still renders for the non-admin...
  await expect(page.locator('[data-testid="sidebar"]')).toBeVisible();
  await expect(page.locator('.aidw-page-title')).toHaveText('Studio \u00b7 Data retention');
  await expect(page.locator('[data-testid="retention-policy-row"]')).toHaveCount(3);
  // ...while no admin-only control survives (fail-closed removal).
  await expect(page.locator('[data-requires-role="admin"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="retention-add-policy"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="retention-policy-delete"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="retention-policy-sweep-now"]')).toHaveCount(0);

  // The chosen row is still marked for the non-admin: tinted, with the
  // accent bar at its start edge and readable ink text.
  await page.locator('[data-testid="retention-policy-row"][data-id="pol-0"]').click();
  await expect(page.locator('[data-testid="retention-policy-row"][data-id="pol-0"]')).toHaveAttribute('aria-selected', 'true');
  const marks = await page.evaluate(() => {
    const row = document.querySelector('[data-testid="retention-policy-row"][aria-selected="true"]');
    const unchosen = document.querySelector('[data-testid="retention-policy-row"][data-id="pol-1"]');
    return {
      chosenBg: getComputedStyle(row).backgroundColor,
      unchosenBg: getComputedStyle(unchosen).backgroundColor,
      nameColor: getComputedStyle(row.querySelector('[data-testid="retention-policy-name"]')).color,
      shadow: getComputedStyle(row.querySelector('td:first-child')).boxShadow,
    };
  });
  expect(
    JSON.stringify(parseColor(marks.chosenBg)),
    'the chosen row is tinted for the non-admin too'
  ).not.toBe(JSON.stringify(parseColor(marks.unchosenBg)));
  expect(marks.shadow, 'the chosen row keeps its start-edge bar').not.toBe('none');
  expect(contrastRatio(marks.nameColor, marks.chosenBg), 'the chosen row text stays readable').toBeGreaterThanOrEqual(4.5);
});
