async function installRoutes(page) {
    const requests = [];   // every /api request: { method, path, auth, body }
    const responses = [];  // every mocked /api response: { method, path, status, body }
    let piiListRequests = 0;

    // The web fonts are aborted too, so the proof needs no external network.
    await page.route('**/fonts.googleapis.com/**', (route) => route.abort());
    await page.route('**/fonts.gstatic.com/**', (route) => route.abort());

    const record = (request) => {
        let body = null;
        const raw = request.postData();
        if (raw) {
            try { body = JSON.parse(raw); } catch { body = raw; }
        }
        requests.push({
            method: request.method(),
            path: new URL(request.url()).pathname,
            auth: request.headers()['authorization'] || null,
            body,
        });
    };

    const fulfill = (route, status, payload) => {
        const request = route.request();
        responses.push({
            method: request.method(),
            path: new URL(request.url()).pathname,
            status,
            body: payload,
        });
        return route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(payload) });
    };

    await page.route('**/api/**', (route) => {
        const request = route.request();
        const url = new URL(request.url());
        record(request);

        if (url.pathname === '/api/auth/config') return fulfill(route, 200, AUTH_CONFIG);
        if (url.pathname === '/api/auth/me') {
            if (request.headers()['authorization'] !== `Bearer ${TOKEN}`)
                return fulfill(route, 401, { detail: 'Not authenticated' });
            return fulfill(route, 200, ADMIN_ME);
        }
        if (request.method() === 'POST') {
            const m = url.pathname.match(/^\/api\/pii-flags\/([^/]+)\/(confirm|dismiss)$/);
            if (m) {
                const f = flags.find((x) => x.id === decodeURIComponent(m[1]));
                if (!f) return fulfill(route, 404, { detail: 'pii_flag not found' });
                f.status = m[2] === 'confirm' ? 'confirmed' : 'dismissed';
                f.updated_at = NOW;
                return fulfill(route, 200, f);
            }
        }
        if (url.pathname === '/api/pii-flags') {
            piiListRequests += 1;
            return fulfill(route, 200, flags);
        }
        if (url.pathname === '/api/datasets') return fulfill(route, 200, DATASETS);
        if (url.pathname === '/api/discovered-fields') return fulfill(route, 200, FIELDS);
        return fulfill(route, 200, []);
    });

    return { flags, requests, responses, get piiListRequests() { return piiListRequests; } };
}

test('issue783 freeform', async ({ page }) => {
    const mock = await installRoutes(page);
    await page.addInitScript((t) => { window.sessionStorage.setItem('aicrm_token', t); }, TOKEN);
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto('/studio.html?panel=pii');

    const pii = page.getByTestId('pii-inbox');
    // Only the seven pending flags render (the confirmed one is decided).
    await expect(pii.locator('[data-testid="pii-flag"]')).toHaveCount(7);
    await expect(page.locator('#pii-count')).toHaveText('7');
    expect(mock.piiListRequests, 'one list request so far').toBe(1);

    // ------------------------------------------------------------------
    // A flag with confidence, tier and rationale shows all three in its
    // row; the confidence sits before the buttons.
    // ------------------------------------------------------------------
    const emailRow = pii.locator(`[data-testid="pii-flag"][data-id="${FLAG_EMAIL}"]`);
    const conf = emailRow.locator('[data-testid="pii-confidence"]');
    // label, class and the value in the title — all from Warehouse._confidence
    await expect(conf).toHaveText('High');
    await expect(conf).toHaveClass('wh-conf wh-conf-high');
    await expect(conf).toHaveAttribute('title', 'score 0.80');
    // tier and rationale under the column name, on the muted line
    await expect(emailRow.locator('[data-testid="pii-field"]')).toHaveText('EmailAddress');
    await expect(emailRow.locator('[data-testid="pii-tier"]')).toHaveText('schema');
    await expect(emailRow.locator('[data-testid="pii-rationale"]')).toHaveText(RATIONALE_EMAIL);
    expect(await emailRow.locator('[data-testid="pii-detail"]').getAttribute('title'))
        .toBe(RATIONALE_EMAIL);
    // the confidence chip is the first child of the actions cell, i.e. before
    // Confirm and Dismiss — in DOM order and on screen
    const actionOrder = await page.evaluate((id) => {
        const row = document.querySelector(`[data-testid="pii-flag"][data-id="${id}"]`);
        const actions = row.querySelector('.wh-pii-actions');
        return Array.from(actions.children).map((c) => c.getAttribute('data-testid') || c.getAttribute('data-action'));
    }, FLAG_EMAIL);
    expect(actionOrder).toEqual(['pii-confidence', 'pii-confirm', 'pii-dismiss']);
    const geo = await page.evaluate((id) => {
        const row = document.querySelector(`[data-testid="pii-flag"][data-id="${id}"]`);
        const confBox = row.querySelector('[data-testid="pii-confidence"]').getBoundingClientRect();
        const confirmBox = row.querySelector('[data-action="pii-confirm"]').getBoundingClientRect();
        return { confRight: confBox.right, confirmLeft: confirmBox.left };
    }, FLAG_EMAIL);
    expect(geo.confRight).toBeLessThanOrEqual(geo.confirmLeft + 1);

    // ------------------------------------------------------------------
    // A long rationale stays on ONE line (ellipsis), and its row is no
    // taller than the short-rationale row.
    // ------------------------------------------------------------------
    const longLine = pii.locator(`[data-testid="pii-flag"][data-id="${FLAG_LONG}"] [data-testid="pii-detail"]`);
    const shortLine = pii.locator(`[data-testid="pii-flag"][data-id="${FLAG_EMAIL}"] [data-testid="pii-detail"]`);
    const longLineStyle = await longLine.evaluate((el) => {
        const cs = getComputedStyle(el);
        return { ws: cs.whiteSpace, te: cs.textOverflow, sw: el.scrollWidth, cw: el.clientWidth, h: el.getBoundingClientRect().height };
    });
    expect(longLineStyle.ws, 'the line is a single line').toBe('nowrap');
    expect(longLineStyle.te, 'it ends in an ellipsis when too long').toBe('ellipsis');
    expect(longLineStyle.sw, 'the long rationale overflows its cell').toBeGreaterThan(longLineStyle.cw);
    expect(longLineStyle.h, 'the line stays one text line tall').toBeLessThan(26);
    const shortLineStyle = await shortLine.evaluate((el) => {
        const cs = getComputedStyle(el);
        return { sw: el.scrollWidth, cw: el.clientWidth };
    });
    expect(shortLineStyle.sw, 'the short rationale fits (the overflow above is length, not layout)')
        .toBeLessThanOrEqual(shortLineStyle.cw);
    const rowHeights = await page.evaluate(({ longId, shortId }) => {
        const h = (id) => document.querySelector(`[data-testid="pii-flag"][data-id="${id}"]`).getBoundingClientRect().height;
        return { long: h(longId), short: h(shortId) };
    }, { longId: FLAG_LONG, shortId: FLAG_EMAIL });
    expect(rowHeights.long, 'a long-rationale row is no taller than a short one')
        .toBeLessThanOrEqual(rowHeights.short + 1);
    expect(rowHeights.short, 'every row stays at least 52 px tall').toBeGreaterThanOrEqual(52);

    // ------------------------------------------------------------------
    // A flag with no rationale and no tier shows no second line.
    // ------------------------------------------------------------------
    const bareRow = pii.locator(`[data-testid="pii-flag"][data-id="${FLAG_BARE}"]`);
    await expect(bareRow.locator('[data-testid="pii-field"]')).toHaveText('Notes');
    await expect(bareRow.locator('[data-testid="pii-detail"]')).toHaveCount(0);
    await expect(bareRow.locator('[data-testid="pii-tier"]')).toHaveCount(0);
    await expect(bareRow.locator('[data-testid="pii-rationale"]')).toHaveCount(0);
    await expect(bareRow.locator('[data-testid="pii-confidence"]')).toHaveText('Low');
    await expect(bareRow.locator('[data-action="pii-confirm"]')).toHaveCount(1);

    // ------------------------------------------------------------------
    // Two flags with no category (one missing, one empty) count under ONE
    // chip labelled "Uncategorised", whose filter key and testids are
    // non-empty. The no-category state must also never swallow a real
    // category: a flag whose category literally is 'uncategorised' is a
    // REAL category — its own chip, its own label — and must never
    // collect under the no-category one.
    // ------------------------------------------------------------------
    const chipRows = await page.evaluate(() => Array.from(
        document.querySelectorAll('[data-testid="pii-filters"] .wh-pii-chip'))
        .map((c) => ({
            key: c.getAttribute('data-pii-filter'),
            testid: c.getAttribute('data-testid'),
            count: c.querySelector('.wh-filter-count').textContent,
            label: c.textContent.replace(/\s+\d+$/, ''),
        })));
    expect(chipRows.length, 'All + contact + no-category + the literal category').toBe(4);

    const nocat = chipRows.find((c) => c.label === 'Uncategorised');
    expect(nocat, 'the no-category chip is labelled Uncategorised').toBeTruthy();
    // AC-3: the no-category state needs a non-empty filter key and a
    // non-empty data-pii-filter/testid — the empty string is the one
    // forbidden key (and 'all' would re-select the whole list); which
    // non-empty key the implementation picks, and in which format it
    // builds the testid, is its choice, so the proof checks non-emptiness
    // only and pins no format and no word.
    expect(nocat.key, 'the no-category chip uses a non-empty filter key (not the empty string)')
        .toEqual(expect.any(String));
    expect(nocat.key.length, 'the filter key is non-empty').toBeGreaterThan(0);
    expect(nocat.key, 'the key is not the All filter').not.toBe('all');
    expect(nocat.testid, 'the chip testid is a non-empty string (no format pinned)')
        .toEqual(expect.any(String));
    expect(nocat.testid.length, 'the chip testid is non-empty').toBeGreaterThan(0);
    expect(nocat.count, 'only the missing and the empty category count').toBe('2');

    const litcat = chipRows.find((c) => c.key === 'uncategorised');
    expect(litcat, 'a literal uncategorised category gets its own chip').toBeTruthy();
    expect(litcat.label, 'and it is labelled by its own category').toBe('uncategorised');
    expect(litcat.count, 'the literal-category flag does not join the no-category chip').toBe('1');
    expect(chipRows.find((c) => c.key === 'contact').count).toBe('4');

    const chip = page.locator('[data-testid="pii-filters"] .wh-pii-chip')
        .nth(chipRows.findIndex((c) => c.key === nocat.key));
    const listGetsBefore = mock.piiListRequests;
    // Client-side narrowing: choosing the chip must send no request to
    // ANY endpoint — the count spans every recorded /api request, not
    // just the flag list.
    const anyRequestsBefore = mock.requests.length;
    await chip.click();
    expect(mock.requests.length, 'choosing the chip must not send any request (any endpoint)')
        .toBe(anyRequestsBefore);
    await expect(pii.locator('[data-testid="pii-flag"]')).toHaveCount(2);
    const visibleIds = await page.evaluate(() => Array.from(document.querySelectorAll('[data-testid="pii-flag"]'))
        .map((r) => r.getAttribute('data-id')));
    expect(visibleIds.sort()).toEqual([FLAG_MISS, FLAG_EMPTY].sort());
    const catTexts = await page.locator('[data-testid="pii-flag"] [data-testid="pii-category"]').allTextContents();
    expect(catTexts, 'each no-category row reads Uncategorised').toEqual(['Uncategorised', 'Uncategorised']);
    await expect(chip).toHaveAttribute('aria-pressed', 'true');
    await expect(page.locator('[data-testid="pii-filter-all"]')).toHaveAttribute('aria-pressed', 'false');

    // And the literal 'uncategorised' chip narrows to its one row only —
    // the two states never merge.
    const litChip = page.locator('[data-testid="pii-filters"] .wh-pii-chip')
        .nth(chipRows.findIndex((c) => c.key === 'uncategorised'));
    await litChip.click();
    expect(mock.piiListRequests, 'choosing the literal chip must not send a request').toBe(listGetsBefore);
    await expect(pii.locator('[data-testid="pii-flag"]')).toHaveCount(1);
    await expect(pii.locator(`[data-testid="pii-flag"][data-id="${FLAG_LITCAT}"]`)).toHaveCount(1);
    await expect(pii.locator('[data-testid="pii-flag"] [data-testid="pii-category"]')).toHaveText('uncategorised');
    await expect(litChip).toHaveAttribute('aria-pressed', 'true');

    // Back to All: the full list is back, still without a request.
    await page.click('[data-testid="pii-filter-all"]');
    await expect(pii.locator('[data-testid="pii-flag"]')).toHaveCount(7);
    expect(mock.piiListRequests, 'choosing All must not send a request either').toBe(listGetsBefore);

    // ------------------------------------------------------------------
    // A hostile rationale renders as text — in the row and in the line's
    // title — and executes nothing.
    // ------------------------------------------------------------------
    const xssRow = pii.locator(`[data-testid="pii-flag"][data-id="${FLAG_XSS}"]`);
    await expect(xssRow.locator('[data-testid="pii-rationale"]')).toHaveText(XSS_RATIONALE);
    expect(await xssRow.locator('img').count(), 'no image is created by the rationale').toBe(0);
    expect(await xssRow.locator('[data-testid="pii-detail"]').getAttribute('title')).toBe(XSS_RATIONALE);
    expect(await page.evaluate(() => window.__pwned), 'nothing from the rationale executed').toBeUndefined();

    // ------------------------------------------------------------------
    // Confirm still sends its request for the right id and the row leaves.
    // ------------------------------------------------------------------
    await emailRow.locator('[data-action="pii-confirm"]').click();
    await expect(pii.locator(`[data-testid="pii-flag"][data-id="${FLAG_EMAIL}"]`)).toHaveCount(0);
    const confirmReq = mock.requests.find((r) => r.path === `/api/pii-flags/${FLAG_EMAIL}/confirm`);
    expect(confirmReq, 'confirm request for the right id').toBeTruthy();
    expect(confirmReq.method).toBe('POST');
    expect(confirmReq.auth).toBe(`Bearer ${TOKEN}`);
    expect(confirmReq.body).toBeNull();
    const confirmResp = mock.responses.find((r) => r.method === 'POST' && r.path === `/api/pii-flags/${FLAG_EMAIL}/confirm`);
    expect(confirmResp.status).toBe(200);
    expect(confirmResp.body).toMatchObject({ id: FLAG_EMAIL, status: 'confirmed' });
    await expect(page.locator('#pii-count')).toHaveText('6');
    expect(mock.piiListRequests, 'confirming re-fetches the list').toBe(listGetsBefore + 1);
});
