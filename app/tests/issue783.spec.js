// Proof for issue #783 — each PII flag row shows a reviewer what they need to
// decide: the confidence (the Warehouse._confidence chip, before the buttons)
// and one muted line under the column name with the detection tier and the
// rationale.
//
// Boots /studio.html?panel=pii against mocked /api/** responses (no backend,
// no data creation): a stateful mock answers the flag list, the dataset and
// field name maps and the POST /api/pii-flags/<id>/confirm | /dismiss
// decision endpoints, and records every request (method, path, Authorization
// header, JSON body). Proves:
//   * a flag with confidence, tier and rationale shows all three in its row —
//     the confidence chip carries the helper's label, class and a title with
//     the value, sits before the Confirm and Dismiss buttons, and the muted
//     line's title is the full rationale
//   * a long rationale stays on ONE line (nowrap + ellipsis, overflowing its
//     cell) and its row is no taller than a row with a short rationale
//   * a flag with no rationale and no tier shows no second line
//   * two flags with no category (one missing, one empty string) count under
//     one "Uncategorised" chip whose filter key and testids are non-empty;
//     choosing it narrows the list to exactly those two rows — which read
//     "Uncategorised" as their category — with no request sent
//   * the no-category state never swallows a real category: a flag whose
//     category literally is 'uncategorised' is a real category — its own
//     chip, its own 'uncategorised' label — and never collects under the
//     no-category one
//   * a rationale of <img src=x onerror=window.__pwned=1> renders as text in
//     the row and in the line's title, with window.__pwned undefined
//   * Confirm still sends its request for the right id and the row leaves
//
// Every value the mock answers with is hostile on purpose (HTML, empty,
// missing, the no-category word used as a real category) and the page
// escapes all of it through Warehouse._esc/_attr.

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


