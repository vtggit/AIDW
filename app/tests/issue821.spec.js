// Proof for issue #821 — the Feed keys panel (app/js/feed_keys.js on
// /studio.html) shows each credential's created and last-used times as
// readable UTC stamps (TimeFormat, issue #810) with the server's
// original value in the cell's title, and flags keys not used for 90
// days.
//
// Boots /studio.html?panel=feedkeys as an admin (roles: ["admin"])
// against mocked /api/** responses (no backend) with the clock fixed by
// Playwright's clock at 2026-10-14 12:00 UTC, and proves:
//   AC-1  a key created 2026-10-01 07:30 UTC and last used
//         2026-10-13 09:15 UTC shows "2026-10-01 07:30 UTC" and
//         "2026-10-13 09:15 UTC" (the server's original value in each
//         cell's title) and is not marked stale; a key that was never
//         used shows "Never" with an empty title; a key last used
//         2026-06-01 (more than 90 days before the fixed clock) carries
//         data-stale="true" on its row and the label "Not used for 90
//         days" in its Last used cell; a never-used key created
//         2026-05-01 is marked the same way (the stale check falls back
//         to created_at); a never-used key created 2026-10-01 is not
//         marked; a revoked key last used 2026-01-01 is never marked;
//         a response with no last_used_at field at all (an older
//         server) shows "Never" and no page error; a last_used_at of
//         <img src=x onerror=window.__pwned=1> is shown as inert text
//         with window.__pwned undefined; the new "Last used" column
//         heads the table after "Created"
//   Identity  the criteria concern roles, so the proof also runs a
//         non-admin pass (role 'user') booted the production way: the
//         token in the URL hash (#access_token=...), /api/auth/config
//         and /api/auth/me mocked for that user, the hash token
//         reaching /api/auth/me as a Bearer header, the page still
//         rendering while the admin-only Feed keys control is absent
//         and no request reaches /api/feed-credentials

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

