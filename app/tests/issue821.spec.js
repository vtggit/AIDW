/**
 * Mock every /api/** request for upcoming page loads: the auth endpoints
 * for the given me body (the token rides the URL hash), the
 * feed-credentials list, and every other API call the Studio boot makes
 * an empty JSON array (no backend).  A matching entry in
 * feedCredentialFailures (method + path) gets a mocked 500 instead.
 */
let feedCredentialFailures = [];

async function mockApi(page, meBody, authHeaders, feedCredentialRequests) {
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = request.url();
    let path = url;
    try {
      path = new URL(url).pathname;
    } catch (_) {
      // non-absolute URL: fall back to the raw string below
    }
    const fulfill = (body) =>
      route.fulfill({ status: 200, contentType: 'application/json', body: typeof body === 'string' ? body : JSON.stringify(body) });
    if (path === '/api/auth/config' || url.includes('/api/auth/config')) return fulfill(AUTH_CONFIG);
    if (path === '/api/auth/me' || url.includes('/api/auth/me')) {
      const auth = request.headers()['authorization'];
      if (auth) authHeaders.push(auth);
      return fulfill(meBody);
    }
    if (path === '/api/feed-credentials' || path.startsWith('/api/feed-credentials/')) {
      const method = request.method();
      feedCredentialRequests.push({ method, url });
      const failure = feedCredentialFailures.find(
        (entry) => entry.method === method && entry.path === path
      );
      if (failure) {
        return route.fulfill({
          status: 500,
          contentType: 'application/json',
          body: JSON.stringify({ detail: 'mocked row-action failure' }),
        });
      }
      return fulfill(CREDENTIALS);
    }
    return fulfill('[]');
  });
}

test('issue821 freeform', async ({ page }) => {
  const pageErrors = [];
  const meAuthorization = [];
  const feedCredentialRequests = [];
  feedCredentialFailures.length = 0;
  page.on('pageerror', (err) => {
    pageErrors.push(err && err.message ? err.message : String(err));
  });

  await page.setViewportSize({ width: 1440, height: 900 });
  await mockApi(page, ADMIN_ME, meAuthorization, feedCredentialRequests);

  // The clock is fixed at 2026-10-14 12:00 UTC before the page boots,
  // so every new Date() the page makes is that instant.
  await page.clock.install({ time: new Date(FIXED_TIME) });

  await page.goto('/studio.html?panel=feedkeys#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  // the hash token was picked up the production way and sent on /auth/me
  await expect.poll(() => meAuthorization).toContain('Bearer ' + ADMIN_TOKEN);

  // the module is loaded and defines const FeedKeys with an init()
  expect(
    await page.evaluate(
      () => typeof window.FeedKeys !== 'undefined' && typeof window.FeedKeys.init === 'function'
    )
  ).toBe(true);

  const section = page.locator('[data-panel="feedkeys"]');
  await expect(section).toBeVisible();
  await expect(section).toHaveAttribute('data-requires-role', 'admin');

  const table = page.locator('[data-testid="feedkeys-table"]');
  await expect(table).toBeVisible();
  await expect(table.locator('[data-testid="feedkeys-row"]')).toHaveCount(CREDENTIALS.length);

  // the new "Last used" column heads the table after "Created"
  expect(await table.locator('thead th').allInnerTexts()).toEqual([
    'Name',
    'Principal',
    'Key',
    'Status',
    'Created',
    'Last used',
    'Actions',
  ]);

  const rowByName = (name) =>
    table
      .locator('[data-testid="feedkeys-row"]')
      .filter({ has: page.locator('[data-testid="feedkeys-name"]', { hasText: name }) });

  // ------------------------------------------------------------------
  // AC-1: created 2026-10-01 07:30 UTC, used 2026-10-13 09:15 UTC —
  // both stamps, the server's values in their titles, no stale mark
  // ------------------------------------------------------------------
  const recent = rowByName('BI export');
  await expect(recent.locator('[data-testid="feedkeys-created"]')).toHaveText('2026-10-01 07:30 UTC');
  await expect(recent.locator('[data-testid="feedkeys-created"]')).toHaveAttribute(
    'title',
    '2026-10-01T07:30:00+00:00'
  );
  await expect(recent.locator('[data-testid="feedkeys-last-used"]')).toHaveText('2026-10-13 09:15 UTC');
  await expect(recent.locator('[data-testid="feedkeys-last-used"]')).toHaveAttribute(
    'title',
    '2026-10-13 09:15:00+00'
  );
  expect(await recent.getAttribute('data-stale'), 'the recent key is not marked stale').toBeNull();
  await expect(recent.locator('[data-testid="feedkeys-stale"]')).toHaveCount(0);

  // ------------------------------------------------------------------
  // AC-1: a key that was never used — "Never", an empty title
  // ------------------------------------------------------------------
  const never = rowByName('Quarterly report');
  await expect(never.locator('[data-testid="feedkeys-last-used"]')).toHaveText('Never');
  await expect(never.locator('[data-testid="feedkeys-last-used"]')).toHaveAttribute('title', '');
  expect(
    await never.getAttribute('data-stale'),
    'a never-used key created within 90 days is not marked'
  ).toBeNull();
  await expect(never.locator('[data-testid="feedkeys-stale"]')).toHaveCount(0);

  // ------------------------------------------------------------------
  // AC-1: last used 2026-06-01, more than 90 days before the fixed
  // clock — the row is marked and the label is in the Last used cell
  // ------------------------------------------------------------------
  const staleUsed = rowByName('Stale used key');
  await expect(staleUsed).toHaveAttribute('data-stale', 'true');
  // the cell also carries the stale label, so the stamp is checked by
  // containment
  expect(
    await staleUsed.locator('[data-testid="feedkeys-last-used"]').textContent()
  ).toContain('2026-06-01 09:00 UTC');
  await expect(staleUsed.locator('[data-testid="feedkeys-last-used"]')).toHaveAttribute(
    'title',
    '2026-06-01T09:00:00+00:00'
  );
  await expect(staleUsed.locator('[data-testid="feedkeys-stale"]')).toHaveText('Not used for 90 days');

  // ------------------------------------------------------------------
  // AC-1: never used and created 2026-05-01 — the stale check falls
  // back to created_at and the row is marked
  // ------------------------------------------------------------------
  const staleNever = rowByName('Stale never-used key');
  await expect(staleNever).toHaveAttribute('data-stale', 'true');
  // the cell also carries the stale label, so "Never" is checked by
  // containment
  expect(
    await staleNever.locator('[data-testid="feedkeys-last-used"]').textContent()
  ).toContain('Never');
  await expect(staleNever.locator('[data-testid="feedkeys-created"]')).toHaveText('2026-05-01 00:00 UTC');
  await expect(staleNever.locator('[data-testid="feedkeys-stale"]')).toHaveText('Not used for 90 days');

  // ------------------------------------------------------------------
  // AC-1: never used and created 2026-10-01 — not marked
  // ------------------------------------------------------------------
  const freshNever = rowByName('Fresh never-used key');
  await expect(freshNever.locator('[data-testid="feedkeys-last-used"]')).toHaveText('Never');
  expect(
    await freshNever.getAttribute('data-stale'),
    'a never-used key created within 90 days is not marked'
  ).toBeNull();
  await expect(freshNever.locator('[data-testid="feedkeys-stale"]')).toHaveCount(0);

  // ------------------------------------------------------------------
  // AC-1: a revoked key last used 2026-01-01 is never marked
  // ------------------------------------------------------------------
  const revoked = rowByName('Retired ETL');
  await expect(revoked.locator('[data-testid="feedkeys-status"]')).toHaveText('Revoked');
  await expect(revoked.locator('[data-testid="feedkeys-last-used"]')).toHaveText('2026-01-01 00:00 UTC');
  await expect(revoked.locator('[data-testid="feedkeys-last-used"]')).toHaveAttribute(
    'title',
    '2026-01-01T00:00:00+00:00'
  );
  expect(await revoked.getAttribute('data-stale'), 'a revoked key is never marked stale').toBeNull();
  await expect(revoked.locator('[data-testid="feedkeys-stale"]')).toHaveCount(0);

  // ------------------------------------------------------------------
  // AC-1: a response with no last_used_at field at all (an older
  // server) — "Never" and no page error
  // ------------------------------------------------------------------
  const noField = rowByName('Older server key');
  await expect(noField.locator('[data-testid="feedkeys-last-used"]')).toHaveText('Never');
  await expect(noField.locator('[data-testid="feedkeys-last-used"]')).toHaveAttribute('title', '');

  // ------------------------------------------------------------------
  // AC-1: a hostile last_used_at is shown as inert text and runs
  // nothing
  // ------------------------------------------------------------------
  const xss = rowByName('Hostile last used');
  await expect(xss.locator('[data-testid="feedkeys-last-used"]')).toHaveText(XSS_LAST_USED);
  expect(await xss.locator('img').count(), 'no <img> is injected').toBe(0);
  expect(await page.evaluate(() => window.__pwned), 'window.__pwned stays undefined').toBeUndefined();

  // the boot made exactly one request to /api/feed-credentials (the
  // list) and no page error occurred in any of the cases above
  expect(feedCredentialRequests, 'one GET /api/feed-credentials per boot').toHaveLength(1);
  expect(feedCredentialRequests[0].method).toBe('GET');
  expect(pageErrors, 'no page error with the mocked responses (incl. the older-server row)').toEqual([]);

  // ------------------------------------------------------------------
  // Defect fix (independent review): the one-line row-action error
  // written by _rowActionError() after a failed revoke or delete takes
  // its colour from the design tokens (css/tokens.css) -- never a raw
  // colour value.  Proven through a failed revoke of the recent key:
  // the mock 500s the PUT, the row keeps its buttons, and the error
  // line's computed colour equals the computed colour of a probe
  // styled with the token itself.
  // ------------------------------------------------------------------
  feedCredentialFailures.push({ method: 'PUT', path: '/api/feed-credentials/fc-821-recent' });

  await recent.locator('[data-testid="feedkeys-revoke-btn"]').click();
  await expect(recent.locator('[data-testid="feedkeys-revoke-confirm"]')).toBeVisible();
  await recent.locator('[data-testid="feedkeys-revoke-confirm-ok"]').click();
  await expect(recent.locator('[data-testid="feedkeys-revoke-error"]')).toHaveText('Could not revoke the key.');
  // the row's buttons stay visible so the action can be retried
  await expect(recent.locator('[data-testid="feedkeys-revoke-btn"]')).toBeVisible();

  // the error line's computed colour equals the token's computed
  // colour: a raw hex written by the script (or a missing rule)
  // cannot pass
  const [errorColor, tokenColor] = await page.evaluate(() => {
    const err = document.querySelector('[data-testid="feedkeys-revoke-error"]');
    const probe = document.createElement('span');
    probe.style.color = 'var(--color-risk)';
    probe.style.visibility = 'hidden';
    probe.textContent = ' ';
    document.body.appendChild(probe);
    const colors = [
      window.getComputedStyle(err).color,
      window.getComputedStyle(probe).color,
    ];
    probe.remove();
    return colors;
  });
  expect(tokenColor, 'the risk design token resolves to a colour').not.toBe('');
  expect(errorColor, 'the row-action error colour is the design token value, not a raw one').toBe(tokenColor);

  // and the served script carries no raw hex colour value at all
  const scriptSource = await page.evaluate(
    async () => (await fetch('js/feed_keys.js', { cache: 'no-store' })).text()
  );
  expect(scriptSource, 'no raw hex colour value in js/feed_keys.js').not.toMatch(
    /#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b/
  );
});

test('issue821 freeform (viewer)', async ({ page }) => {
  // Identity: the criteria concern roles, so the proof also runs as a
  // non-admin (role 'user') booted the production way: the token in the
  // URL hash, /api/auth/config and /api/auth/me mocked for that user.
  const meAuthorization = [];
  const feedCredentialRequests = [];
  feedCredentialFailures.length = 0;

  await page.setViewportSize({ width: 1440, height: 900 });
  await mockApi(page, USER_ME, meAuthorization, feedCredentialRequests);
  await page.clock.install({ time: new Date(FIXED_TIME) });

  // A fragment-only URL change would be a same-document navigation and
  // Auth.init() would not re-run; this is a fresh page, so the hash
  // token is picked up the production way.
  await page.goto('/studio.html?panel=feedkeys#access_token=' + encodeURIComponent(USER_TOKEN));
  // the hash token was picked up the production way and sent on /auth/me
  await expect.poll(() => meAuthorization).toContain('Bearer ' + USER_TOKEN);

  // the admin-only Feed keys control is absent ...
  await expect(page.locator('[data-panel="feedkeys"]')).toBeHidden();
  await expect(page.locator('[data-testid="feedkeys-table"]')).toHaveCount(0);
  // ... while the page still renders its other panels ...
  await expect(page.locator('[data-panel="sources"]')).toBeVisible();
  // ... and no request reached /api/feed-credentials
  expect(feedCredentialRequests, 'no /api/feed-credentials request as a non-admin').toHaveLength(0);
});
