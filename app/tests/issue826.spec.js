'use strict';

// Proof for issue #826 — in Studio the Data sources tool fits the window and
// reads clearly: the form stays at the top, the source list (#sources) is the
// ONE region that scrolls, one line per source (name, type badge, endpoint,
// dataset count, Discover at the row's right edge) with ellipsis + full-text
// titles, labelled Name / Endpoint URL / OData version fields, and a
// non-rendered (count 0) admin-only Discover button for a non-admin.
//
// Boots /studio.html against mocked /api/** responses (no backend) with
// 200 mocked sources and proves:
//   * at 1440x900 as an admin: neither the document nor the main region
//     scrolls, #sources scrolls in its own region, and the form is still in
//     view after the list is scrolled to its end
//   * a source with a 300-character name and endpoint: the row is still one
//     line, the Discover button sits inside the row's right edge, and the
//     titles carry the full texts
//   * each of the three form fields has a visible <label for=...> found by
//     getByLabel ("Name", "Endpoint URL", "OData version"); the placeholders
//     are kept
//   * as an admin: every row carries the Discover button
//     (data-requires-role="admin"); a source with no connection is disabled
//     with its title, and clicking an enabled one sends
//     POST /api/sources/<id>/discover and shows the toast
//   * the add-source flow keeps its button text: after a full submit
//     the button reads "Add source" again (no "Adding…" / "Add & discover"
//     residue) and is enabled
//   * the error notice after GET /api/sources fails carries no inline style
//     (the risk colour token, applied through a class)
//   * a source named <img src=x onerror=window.__pwned=1> renders as inert
//     text (no injected element, no on* attribute, window.__pwned undefined);
//     the same hostile value inside a title attribute is inert, not a failure
//   * at 390x844 the row wraps onto two lines and there is no horizontal
//     page scroll
//   Identity  the criteria concern roles, so the proof also runs a NON-ADMIN
//         pass (role 'user') in the same test after a full reload: the page
//         is booted the production way (the token in the URL hash as
//         #access_token=..., /api/auth/config and /api/auth/me mocked for
//         that user, the hash token reaching /api/auth/me as a Bearer
//         header) — the page still renders the list, while no Discover
//         button exists in the DOM (query count 0) and no discover request
//         is sent

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

test.setTimeout(60 * 1000); // full studio boot + 200-row list + four passes

const TOTAL = 200;
const LONG_ROW = 100;   // 300-character name and endpoint
const XSS_ROW = 150;    // hostile name
const NOCONN_ROW = 50;  // no connection: Discover disabled with its title

const ADMIN_ME = { authenticated: true, user: { id: 1, username: 'admin', roles: ['admin'] } };
const VIEWER_ME = { authenticated: true, user: { id: 9, username: 'user', roles: ['user'] } };
const ADMIN_TOKEN = 'issue826-admin-token';
const VIEWER_TOKEN = 'issue826-viewer-token';

const idOf = (i) => 'src-' + String(i).padStart(4, '0');
const LONG_ID = idOf(LONG_ROW);
const XSS_ID = idOf(XSS_ROW);
const NOCONN_ID = idOf(NOCONN_ROW);

const LONG_NAME = ('long-name-' + 'a'.repeat(300)).slice(0, 300);
const LONG_ENDPOINT = ('https://odata/' + 'e'.repeat(300)).slice(0, 300);
const XSS_NAME = '<img src=x onerror=window.__pwned=1>';

const SOURCES = [];
for (let i = 1; i <= TOTAL; i += 1) {
  SOURCES.push({
    id: idOf(i),
    name: i === XSS_ROW ? XSS_NAME : (i === LONG_ROW ? LONG_NAME : 'Source ' + i),
    type: 'odata',
  });
}

const CONNS = [];
for (let i = 1; i <= TOTAL; i += 1) {
  if (i === NOCONN_ROW) continue; // this source has no connection
  CONNS.push({
    id: 'conn-' + i,
    name: 'connection ' + i,
    source_id: idOf(i),
    endpoint: i === LONG_ROW ? LONG_ENDPOINT : 'https://odata.example.com/svc/' + i,
    protocol_version: 'v4',
    verify_tls: true,
    timeout_seconds: 30,
  });
}

const DATASETS = [];
for (let i = 1; i <= TOTAL; i += 1) {
  const n = i === LONG_ROW ? 2 : (i === NOCONN_ROW ? 0 : 1);
  for (let k = 1; k <= n; k += 1) {
    DATASETS.push({ id: 'ds-' + i + '-' + k, name: 'dataset ' + i + '-' + k, source_id: idOf(i) });
  }
}

test('issue826 freeform', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });

  // ------------------------------------------------------------------
  // Pass 1 — admin, 1440x900, 200 sources: boot the production way (the
  // token rides the URL hash; /api/auth/config and /api/auth/me mocked).
  // ------------------------------------------------------------------
  const meAuthorizations = [];
  const state = { failSources: false };
  const discoverPosts = [];
  await page.route('**/api/**', (route) => {
    const req = route.request();
    const url = req.url();
    const json = (body, status) => route.fulfill({
      status: status || 200,
      contentType: 'application/json',
      body: JSON.stringify(body),
    });
    if (url.includes('/api/auth/config')) {
      return json({ authEnabled: true, authMode: 'development' });
    }
    if (url.includes('/api/auth/me')) {
      const auth = req.headers()['authorization'];
      if (auth) meAuthorizations.push(auth);
      return json(ADMIN_ME);
    }
    if (req.method() === 'POST') {
      discoverPosts.push(url);
      if (url.includes('/discover')) {
        return json({ datasets_discovered: 3, fields_discovered: 12, suggestions_created: 2, pii_flags_created: 1 });
      }
      return json({ id: 'created' });
    }
    if (url.includes('/api/source-connections')) return json(CONNS);
    if (url.includes('/api/datasets')) return json(DATASETS);
    if (url.includes('/api/sources')) {
      if (state.failSources) return json({ detail: 'database down' }, 500);
      return json(SOURCES);
    }
    return json([]);
  });

  await page.goto('/studio.html#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  await expect.poll(() => meAuthorizations).toContain('Bearer ' + ADMIN_TOKEN);
  await expect(page.locator('#sources .src-row')).toHaveCount(TOTAL);
  await expect(page.locator('#sources-count')).toHaveText(String(TOTAL));

  // ------------------------------------------------------------------
  // AC-1: one region scrolls — the document and the main region do not;
  // #sources does.  The form stays at the top.
  // ------------------------------------------------------------------
  const scrollState = await page.evaluate(() => {
    const doc = document.scrollingElement;
    const main = document.querySelector('[data-testid="main-content"]');
    const list = document.getElementById('sources');
    return {
      doc: doc.scrollHeight - doc.clientHeight,
      main: main.scrollHeight - main.clientHeight,
      list: list.scrollHeight - list.clientHeight,
      listClientHeight: list.clientHeight,
    };
  });
  expect(scrollState.doc, 'the document does not scroll at 1440x900').toBeLessThanOrEqual(0);
  expect(scrollState.main, 'the main region does not scroll at 1440x900').toBeLessThanOrEqual(0);
  expect(scrollState.list, 'the source list scrolls in its own region').toBeGreaterThan(0);
  expect(scrollState.listClientHeight, 'the list region has a real height').toBeGreaterThan(100);

  // ------------------------------------------------------------------
  // AC-1: one line per source — name, type badge, endpoint, dataset
  // count, Discover at the row's right edge; a 300-character name and
  // endpoint cut with an ellipsis, the titles carry the full texts.
  // ------------------------------------------------------------------
  const longRow = await page.evaluate((id) => {
    const row = document.querySelector('.src-row[data-id="' + id + '"]');
    const box = (selector) => {
      const r = row.querySelector(selector).getBoundingClientRect();
      return { top: r.top, bottom: r.bottom, right: r.right, center: r.top + r.height / 2 };
    };
    return {
      name: box('.src-name'),
      badge: box('.src-type'),
      endpoint: box('.src-endpoint'),
      count: box('.src-ds-count'),
      button: box('.src-discover'),
      countText: row.querySelector('.src-ds-count').textContent,
      rowRight: row.getBoundingClientRect().right,
      nameTitle: row.querySelector('.src-name').getAttribute('title'),
      endpointTitle: row.querySelector('.src-endpoint').getAttribute('title'),
    };
  }, LONG_ID);
  const centres = [longRow.name, longRow.badge, longRow.endpoint, longRow.count, longRow.button].map((b) => b.center);
  const spread = Math.max(...centres) - Math.min(...centres);
  expect(spread, 'every cell of the 300-character row sits on one line').toBeLessThan(2);
  expect(longRow.button.right, 'the Discover button is inside the row').toBeLessThanOrEqual(longRow.rowRight + 1);
  expect(longRow.rowRight - longRow.button.right, 'the Discover button sits at the row right edge').toBeLessThanOrEqual(24);
  expect(longRow.nameTitle, 'the name title carries the full text').toBe(LONG_NAME);
  expect(longRow.endpointTitle, 'the endpoint title carries the full text').toBe(LONG_ENDPOINT);
  expect(longRow.countText, 'the dataset count renders').toBe('2 datasets');

  // ------------------------------------------------------------------
  // AC-2: XSS — a source named <img src=x onerror=window.__pwned=1>
  // renders as inert text; the same value inside a title attribute is
  // inert, not a failure.
  // ------------------------------------------------------------------
  const xss = await page.evaluate((id) => {
    const row = document.querySelector('.src-row[data-id="' + id + '"]');
    let onAttrs = 0;
    const all = [row].concat(Array.from(row.querySelectorAll('*')));
    for (const el of all) {
      for (const a of el.attributes) {
        if (a.name.startsWith('on')) onAttrs += 1;
      }
    }
    const nameEl = row.querySelector('.src-name');
    return {
      imgs: row.querySelectorAll('img').length,
      onAttrs,
      pwned: typeof window.__pwned,
      title: nameEl ? nameEl.getAttribute('title') : null,
      text: row.textContent,
    };
  }, XSS_ID);
  expect(xss.imgs, 'no element is injected through the name').toBe(0);
  expect(xss.onAttrs, 'no attribute whose name starts with "on"').toBe(0);
  expect(xss.pwned, 'window.__pwned stays undefined').toBe('undefined');
  expect(xss.title, 'the hostile name is inert text inside the title attribute').toBe(XSS_NAME);
  expect(xss.text, 'the hostile name is shown as text').toContain(XSS_NAME);

  // ------------------------------------------------------------------
  // AC-1: labelled fields — visible <label for=...> for each of the
  // three inputs, found by getByLabel; the placeholders are kept.
  // ------------------------------------------------------------------
  const panel = page.locator('section.wh-panel[data-panel="sources"]');
  for (const [labelText, inputId] of [
    ['Name', 'src-name'],
    ['Endpoint URL', 'src-endpoint'],
    ['OData version', 'src-version'],
  ]) {
    const control = panel.getByLabel(labelText);
    await expect(control, 'getByLabel("' + labelText + '")').toHaveCount(1);
    await expect(control, 'the label for ' + inputId + ' is visible').toBeVisible();
    expect(await control.first().getAttribute('id'), 'the label for matches the field id').toBe(inputId);
    const labelEl = panel.locator('label[for="' + inputId + '"]');
    await expect(labelEl).toBeVisible();
    await expect(labelEl).toHaveText(labelText);
  }
  await expect(page.locator('#src-name')).toHaveAttribute('placeholder', 'Source name');
  await expect(page.locator('#src-endpoint')).toHaveAttribute('placeholder', 'Endpoint URL');

  // ------------------------------------------------------------------
  // AC-1/AC-3: Discover is admin-only — for an admin every row carries
  // it (with data-requires-role="admin"); a source without a connection
  // is disabled with its title; a click sends the discovery request and
  // shows the toast.
  // ------------------------------------------------------------------
  await expect(page.locator('#sources .src-discover')).toHaveCount(TOTAL);
  const longBtn = page.locator('#sources .src-row[data-id="' + LONG_ID + '"] .src-discover');
  await expect(longBtn).toHaveAttribute('data-requires-role', 'admin');
  await expect(longBtn).toBeVisible();
  await expect(longBtn).toBeEnabled();
  const noConnBtn = page.locator('#sources .src-row[data-id="' + NOCONN_ID + '"] .src-discover');
  await expect(noConnBtn).toBeDisabled();
  await expect(noConnBtn).toHaveAttribute('title', 'add a connection first');

  const formBefore = await page.evaluate(() => {
    const r = document.getElementById('source-form').getBoundingClientRect();
    return { top: r.top, left: r.left, width: r.width };
  });
  await page.evaluate(() => {
    const list = document.getElementById('sources');
    list.scrollTop = list.scrollHeight;
  });
  const afterScroll = await page.evaluate(() => {
    const form = document.getElementById('source-form');
    const r = form.getBoundingClientRect();
    const main = document.querySelector('[data-testid="main-content"]');
    return {
      top: r.top,
      left: r.left,
      width: r.width,
      listScrollTop: document.getElementById('sources').scrollTop,
      mainScrollTop: main.scrollTop,
      docScrollY: window.scrollY,
      inView: r.height > 0 && r.top >= 0 && r.top < window.innerHeight,
    };
  });
  expect(afterScroll.top - formBefore.top, 'the form stays at the top').toBeLessThan(1);
  expect(afterScroll.left - formBefore.left, 'the form stays at the top').toBeLessThan(1);
  expect(afterScroll.width, 'the form is still visible').toBe(formBefore.width);
  expect(afterScroll.inView, 'the form is in view after the list scrolled to its end').toBe(true);
  expect(afterScroll.listScrollTop, 'the list scrolled to its end').toBeGreaterThan(0);
  expect(afterScroll.mainScrollTop, 'the main region did not scroll').toBe(0);
  expect(afterScroll.docScrollY, 'the document did not scroll').toBe(0);

  const [discoverReq] = await Promise.all([
    page.waitForRequest((req) => req.method() === 'POST' && req.url().includes('/api/sources/' + LONG_ID + '/discover')),
    longBtn.click(),
  ]);
  expect(discoverReq.url(), 'the discovery request goes to the source id').toContain('/api/sources/' + LONG_ID + '/discover');
  const toast = page.locator('#toast');
  await expect(toast).toBeVisible();
  await expect(toast).toContainText('Discovered 3 datasets / 12 fields');

  // ------------------------------------------------------------------
  // AC-1 (unchanged): the add-source flow keeps its button text —
  // after a full submit (source -> connection -> OData config ->
  // discovery) the button reads "Add source" again and is enabled,
  // with no "Adding…" / "Add & discover" residue.
  // ------------------------------------------------------------------
  const submitDiscover = page.waitForRequest(
    (req) => req.method() === 'POST' && req.url().includes('/api/sources/created/discover'),
  );
  await expect(page.locator('#src-submit'), 'the add-source button starts as "Add source"')
    .toHaveText('Add source');
  await page.locator('#src-name').fill('Proof server');
  await page.locator('#src-endpoint').fill('https://proof.example.com/svc');
  await page.locator('#src-submit').click();
  await submitDiscover;
  await expect(toast, 'the submit chains the discovery request')
    .toContainText('Discovered 3 datasets / 12 fields');
  await expect(page.locator('#src-submit'), 'the add-source button keeps its text after the submit')
    .toHaveText('Add source');
  await expect(page.locator('#src-submit'), 'the add-source button is enabled again after the submit')
    .toBeEnabled();

  // ------------------------------------------------------------------
  // AC-1: the error notice after GET /api/sources fails — no inline
  // style; the risk colour token applied through a class.
  // ------------------------------------------------------------------
  state.failSources = true;
  await page.goto('/studio.html');
  const notice = page.locator('#sources .src-notice-error');
  await expect(notice).toBeVisible();
  await expect(notice).toHaveText('Could not load sources.');
  await expect(notice, 'the error notice carries no inline style').not.toHaveAttribute('style');
  expect(
    await notice.evaluate((el) => getComputedStyle(el).color),
    'the error notice uses the risk colour token',
  ).toBe('rgb(138, 59, 5)');

  // ------------------------------------------------------------------
  // AC-1: at 900 px and below the row wraps onto two lines, and at
  // 390x844 there is no horizontal page scroll.
  // ------------------------------------------------------------------
  state.failSources = false;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/studio.html');
  await expect(page.locator('#sources .src-row')).toHaveCount(TOTAL);
  const narrow = await page.evaluate(() => {
    window.scrollTo(100, 0);
    const doc = document.documentElement;
    return {
      scrollX: window.scrollX,
      doc: doc.scrollWidth - doc.clientWidth,
      body: document.body.scrollWidth - document.body.clientWidth,
    };
  });
  expect(narrow.scrollX, 'no horizontal page scroll at 390x844').toBe(0);
  expect(narrow.doc, 'no horizontal page scroll at 390x844').toBeLessThanOrEqual(0);
  expect(narrow.body, 'no horizontal page scroll at 390x844').toBeLessThanOrEqual(0);

  const wrap = await page.evaluate((id) => {
    const row = document.querySelector('.src-row[data-id="' + id + '"]');
    const box = (selector) => {
      const r = row.querySelector(selector).getBoundingClientRect();
      return { top: r.top, bottom: r.bottom, right: r.right, center: r.top + r.height / 2 };
    };
    return {
      name: box('.src-name'),
      badge: box('.src-type'),
      endpoint: box('.src-endpoint'),
      count: box('.src-ds-count'),
      button: box('.src-discover'),
      rowRight: row.getBoundingClientRect().right,
      viewport: window.innerWidth,
    };
  }, LONG_ID);
  expect(Math.abs(wrap.name.center - wrap.badge.center), 'name and badge share the first line').toBeLessThan(2);
  expect(Math.abs(wrap.endpoint.center - wrap.count.center), 'endpoint and count share the second line').toBeLessThan(2);
  expect(Math.abs(wrap.endpoint.center - wrap.button.center), 'endpoint and Discover share the second line').toBeLessThan(2);
  expect(wrap.name.center < wrap.endpoint.center, 'the row wraps onto two lines').toBe(true);
  expect(wrap.rowRight, 'the row stays inside the viewport').toBeLessThanOrEqual(wrap.viewport + 1);

  // ------------------------------------------------------------------
  // Identity — a NON-ADMIN pass (role 'user') after a full reload: the
  // page is booted the production way (the token in the URL hash,
  // /api/auth/config and /api/auth/me mocked for that user) and still
  // renders the list — while the admin-only Discover button is absent
  // from the DOM entirely (count 0, not hidden) and no discover request
  // is sent.
  // ------------------------------------------------------------------
  await page.unrouteAll();
  const viewerAuthorizations = [];
  const viewerPosts = [];
  await page.route('**/api/**', (route) => {
    const req = route.request();
    const url = req.url();
    const json = (body, status) => route.fulfill({
      status: status || 200,
      contentType: 'application/json',
      body: JSON.stringify(body),
    });
    if (url.includes('/api/auth/config')) {
      return json({ authEnabled: true, authMode: 'development' });
    }
    if (url.includes('/api/auth/me')) {
      const auth = req.headers()['authorization'];
      if (auth) viewerAuthorizations.push(auth);
      return json(VIEWER_ME);
    }
    if (req.method() === 'POST') {
      viewerPosts.push(url);
      return json({ id: 'ignored' });
    }
    if (url.includes('/api/source-connections')) return json(CONNS);
    if (url.includes('/api/datasets')) return json(DATASETS);
    if (url.includes('/api/sources')) return json(SOURCES);
    return json([]);
  });
  await page.setViewportSize({ width: 1440, height: 900 });
  // A fragment-only URL change would be a same-document navigation and
  // Auth.init() would not re-run; go through about:blank so this boot is
  // a full page load, the production way.
  await page.goto('about:blank');
  await page.goto('/studio.html#access_token=' + encodeURIComponent(VIEWER_TOKEN));
  await expect.poll(() => viewerAuthorizations).toContain('Bearer ' + VIEWER_TOKEN);

  // The page still renders for a non-admin: the shell is up, the tool is
  // shown, and the read-only list is there...
  await expect(page.locator('[data-testid="sidebar"]')).toBeVisible();
  await expect(page.locator('.aidw-page-title')).toHaveText('Studio · Data sources');
  await expect(page.locator('#sources')).toBeVisible();
  await expect(page.locator('#sources .src-row')).toHaveCount(TOTAL);
  // ...with the admin-only control absent from the DOM (not hidden via
  // CSS — the query count is 0).
  await expect(page.locator('#sources .src-discover'), 'no Discover button for a non-admin').toHaveCount(0);
  await expect(page.locator('.src-discover'), 'no Discover button anywhere in the DOM').toHaveCount(0);
  await expect(page.locator('#source-form'), 'the add form is admin-only and leaves the DOM').toHaveCount(0);
  await expect(page.locator('[data-requires-role="admin"]'), 'no role-gated element survives for a non-admin').toHaveCount(0);
  // The list still renders its cells (name, badge, endpoint, count).
  const viewerLong = page.locator('#sources .src-row[data-id="' + LONG_ID + '"]');
  await expect(viewerLong).toContainText('2 datasets');
  expect(
    viewerPosts.filter((u) => u.includes('/discover')).length,
    'no discover request for a non-admin',
  ).toBe(0);
});
