// A minimal BPMN projection per sequence (the row click fetches it).
function bpmnFor(id) {
  return {
    process_key: 'proc_' + id,
    bpmn_xml:
      '<?xml version="1.0" encoding="UTF-8"?>' +
      '<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL" id="def_' + id + '">' +
      '<bpmn:process id="proc_' + id + '" isExecutable="false">' +
      '<bpmn:serviceTask name="Step one"/>' +
      '<bpmn:serviceTask name="Step two"/>' +
      '</bpmn:process>' +
      '</bpmn:definitions>',
  };
}

