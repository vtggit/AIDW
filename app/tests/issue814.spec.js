/**
 * Mock every /api/** request for upcoming page loads: the auth
 * endpoints for an admin (the token rides the URL hash), the two
 * tools' endpoints with the mocked lists, and every other API call an
 * empty JSON array (the Studio boot fetches many lists on startup).
 */
async function mockApi(page, authHeaders) {
  await page.unrouteAll();
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = request.url();
    let path = url;
    try {
      path = new URL(url).pathname;
    } catch (_) {
      // non-absolute URL: fall back to the raw string below
    }
    const fulfill = (body) =>
      route.fulfill({ status: 200, contentType: 'application/json', body: typeof body === 'string' ? body : JSON.stringify(body) });
    if (path === '/api/auth/config' || url.includes('/api/auth/config')) return fulfill(AUTH_CONFIG);
    if (path === '/api/auth/me' || url.includes('/api/auth/me')) {
      const auth = request.headers()['authorization'];
      if (auth) authHeaders.push(auth);
      return fulfill(ADMIN_ME);
    }
    if (path === '/api/load-sequences') return fulfill(SEQUENCES);
    if (path === '/api/sequence-runs') return fulfill(RUNS);
    if (path.startsWith('/api/load-sequences/') && path.endsWith('/bpmn')) {
      return fulfill(bpmnFor(decodeURIComponent(path.split('/')[3])));
    }
    if (path === '/api/pipelines') return fulfill(PIPELINES);
    if (path === '/api/datasets') return fulfill(DATASETS);
    if (path === '/api/runs') return fulfill(INGESTION_RUNS);
    return fulfill('[]');
  });
}

/** The document does not scroll (neither the root scroller nor the body). */
async function assertNoDocumentScroll(page, tool) {
  const scroll = await page.evaluate(() => {
    const scroller = document.scrollingElement;
    return {
      doc: scroller.scrollHeight - scroller.clientHeight,
      body: document.body.scrollHeight - document.body.clientHeight,
    };
  });
  expect(scroll.doc, tool + ': the document does not scroll').toBeLessThanOrEqual(0);
  expect(scroll.body, tool + ': the document does not scroll').toBeLessThanOrEqual(0);
}

test('issue814 freeform', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });

  const authHeaders = [];
  await mockApi(page, authHeaders);

  // The clock is fixed at 2026-10-13 12:00 UTC before the page boots;
  // after install it tracks real time, so the assertions below stay
  // robust to a few seconds of drift (ages are expressed in hour
  // units; the durations sit between two fixed server stamps).
  await page.clock.install({ time: new Date(FIXED_TIME) });

  // --------------------------------------------------------------------
  // AC-1: the Load sequences run history.
  // --------------------------------------------------------------------
  await page.goto('/studio.html?panel=sequences#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  await expect.poll(() => authHeaders).toContain('Bearer ' + ADMIN_TOKEN);

  await page.locator('[data-testid="sequence-row"][data-id="seq-814"]').click();
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(4);

  // The failed run with both stamps: "took 42 s", whatever its status.
  const failedRow = page.locator('[data-testid="run-row"][data-id="run-814-failed"]');
  await expect(failedRow.locator('[data-testid="run-status"]')).toHaveText('failed');
  await expect(failedRow.locator('[data-testid="run-duration"]')).toHaveText('took 42 s');

  // The completed run still shows its duration.
  const doneRow = page.locator('[data-testid="run-row"][data-id="run-814-completed"]');
  await expect(doneRow.locator('[data-testid="run-status"]')).toHaveText('completed');
  await expect(doneRow.locator('[data-testid="run-duration"]')).toHaveText('took 5 min 30 s');

  // The failed run without a finish time: no duration, no "took".
  const failedOpenRow = page.locator('[data-testid="run-row"][data-id="run-814-failed-open"]');
  await expect(failedOpenRow.locator('[data-testid="run-status"]')).toHaveText('failed');
  await expect(failedOpenRow.locator('[data-testid="run-duration"]')).toHaveCount(0);
  await expect(failedOpenRow).not.toContainText('took');

  // The running run: "running for" its age — three hours at the fixed
  // 12:00 UTC clock — and no "took".
  const runningRow = page.locator('[data-testid="run-row"][data-id="run-814-running"]');
  await expect(runningRow.locator('[data-testid="run-age"]')).toHaveText('running for 3 h 0 min');
  await expect(runningRow.locator('[data-testid="run-duration"]')).toHaveCount(0);
  await expect(runningRow).not.toContainText('took');

  // The Load sequences tool fits 1440x900: the document does not scroll.
  await assertNoDocumentScroll(page, 'Load sequences');

  // --------------------------------------------------------------------
  // AC-1: the Ingestion runs.
  // --------------------------------------------------------------------
  await page.goto('/studio.html?panel=ingestion#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  const pipelineRow = page.locator('[data-testid="ingestion-pipeline-row"][data-id="pipe-814"]');
  await expect(pipelineRow).toBeVisible();
  await pipelineRow.click();
  await expect(page.locator('[data-testid="ingestion-runs"] [data-testid="ingestion-run-row"]')).toHaveCount(3);

  // The failed run with both stamps: "took 42 s", whatever its status.
  const ingFailedRow = page.locator('[data-testid="ingestion-run-row"][data-id="ing-814-failed"]');
  await expect(ingFailedRow.locator('[data-testid="ingestion-run-status"]')).toHaveText('failed');
  await expect(ingFailedRow.locator('[data-testid="ingestion-run-duration"]')).toHaveText('took 42 s');

  // The completed run still shows its duration.
  const ingDoneRow = page.locator('[data-testid="ingestion-run-row"][data-id="ing-814-completed"]');
  await expect(ingDoneRow.locator('[data-testid="ingestion-run-status"]')).toHaveText('completed');
  await expect(ingDoneRow.locator('[data-testid="ingestion-run-duration"]')).toHaveText('took 5 min 30 s');

  // The failed run without a finish time: no duration, no "took".
  const ingFailedOpenRow = page.locator('[data-testid="ingestion-run-row"][data-id="ing-814-failed-open"]');
  await expect(ingFailedOpenRow.locator('[data-testid="ingestion-run-status"]')).toHaveText('failed');
  await expect(ingFailedOpenRow.locator('[data-testid="ingestion-run-duration"]')).toHaveCount(0);
  await expect(ingFailedOpenRow).not.toContainText('took');

  // The Ingestion tool fits 1440x900: the document does not scroll.
  await assertNoDocumentScroll(page, 'Ingestion');
});
