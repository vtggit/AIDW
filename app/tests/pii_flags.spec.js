// End-to-end: the PII flags review loop in the browser — against MOCKED /api/** responses,
// no backend. Every /api/** request the page makes is intercepted with page.route BEFORE
// page.goto (the same pattern suggestions.spec.js and issue767.spec.js use), so the spec
// never talks to a live API: it drives the real UI on /studio.html?panel=pii against a
// stateful in-memory mock of GET /api/pii-flags, GET /api/datasets, GET
// /api/discovered-fields and the POST /api/pii-flags/<id>/confirm | /dismiss decision
// endpoints, and records every request (method, path, Authorization header, JSON body)
// and every response (status, shape). Proven:
//   • the PII panel renders pending flags grouped by dataset — the dataset name, the
//     column (field name) and the category for each flag, one group per dataset;
//   • Confirm sends its request for the right flag id — POST /api/pii-flags/<id>/confirm
//     with the Bearer admin token and no JSON body — and removes that flag from the panel
//     (status -> 'confirmed');
//   • Dismiss sends its request for the right flag id — POST /api/pii-flags/<id>/dismiss —
//     and removes that flag from the panel (status -> 'dismissed');
//   • the decisions persist with the right statuses: after each action the panel
//     re-fetches GET /api/pii-flags and renders from it, and the mock's stored statuses —
//     the same status values the live-stack proof checked against the backend — are what
//     that re-render reflects.
// Auth is the development admin token seeded into sessionStorage (as in the original
// proof); the mocked /api/auth/config and /api/auth/me only answer for that Bearer
// header, so every request this spec asserts on carries it.
const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


const TOKEN = 'dev-secret-token:admin';
const MARK = `PII-${Date.now()}`; // unique per run so assertions never collide with existing rows
const NOW = '2026-10-11T00:00:00+00:00';

const AUTH_CONFIG = { authEnabled: true, authMode: 'development' };
const ADMIN_ME = { authenticated: true, user: { id: 1, username: 'admin', roles: ['admin'] } };

const DS_ID = 'ds-775-customers';
const DS_ORDERS_ID = 'ds-775-orders';
const EMAIL_FIELD_ID = 'fld-775-email';
const KEY_FIELD_ID = 'fld-775-key';
const ORDER_FIELD_ID = 'fld-775-orderid';
const CONFIRM_ID = 'flag-775-confirm';
const DISMISS_ID = 'flag-775-dismiss';
const ORDERS_FLAG_ID = 'flag-775-orders';

const DATASETS = [
    { id: DS_ID, name: `${MARK} Customers`, object_type: 'EntitySet', created_at: NOW },
    { id: DS_ORDERS_ID, name: `${MARK} Orders`, object_type: 'EntitySet', created_at: NOW },
];

const FIELDS = [
    { id: EMAIL_FIELD_ID, name: 'EmailAddress', dataset_id: DS_ID, created_at: NOW },
    { id: KEY_FIELD_ID, name: 'CustomerID', dataset_id: DS_ID, created_at: NOW },
    { id: ORDER_FIELD_ID, name: 'OrderID', dataset_id: DS_ORDERS_ID, created_at: NOW },
];

const flag = (id, name, datasetId, fieldId, category, confidence) => ({
    id,
    name,
    dataset_id: datasetId,
    discovered_field_id: fieldId,
    category,
    detection_tier: 'schema',
    status: 'flagged',
    confidence,
    rationale: `name token '${category}'`,
    fingerprint: `${MARK}-${category}-${fieldId}`,
    created_at: NOW,
    updated_at: NOW,
});

async function installRoutes(page) {
    // Stateful pending inbox: confirm/dismiss flip the row's status (sticky, like the real
    // endpoints) and the panel re-fetches this list after every action, so a decided flag
    // drops out of the render.
    const flags = [
        flag(CONFIRM_ID, `${MARK} email`, DS_ID, EMAIL_FIELD_ID, 'contact', 0.8),
        flag(DISMISS_ID, `${MARK} key`, DS_ID, KEY_FIELD_ID, 'direct_identifier', 0.9),
        flag(ORDERS_FLAG_ID, `${MARK} order key`, DS_ORDERS_ID, ORDER_FIELD_ID, 'direct_identifier', 0.7),
    ];
    const requests = [];  // every /api request:  { method, path, auth, body }
    const responses = []; // every mocked /api response: { method, path, status, body }

    const record = (request) => {
        let body = null;
        const raw = request.postData();
        if (raw) {
            try { body = JSON.parse(raw); } catch { body = raw; }
        }
        requests.push({
            method: request.method(),
            path: new URL(request.url()).pathname,
            auth: request.headers()['authorization'] || null,
            body,
        });
    };

    const fulfill = (route, status, payload) => {
        const request = route.request();
        responses.push({
            method: request.method(),
            path: new URL(request.url()).pathname,
            status,
            body: payload,
        });
        return route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(payload) });
    };

    const decide = (route, flagId, newStatus) => {
        const f = flags.find((x) => x.id === flagId);
        if (!f) return fulfill(route, 404, { detail: 'pii_flag not found' });
        f.status = newStatus;
        f.updated_at = NOW;
        return fulfill(route, 200, f);
    };

    await page.route('**/api/**', (route) => {
        const request = route.request();
        const url = new URL(request.url());
        record(request);

        if (url.pathname === '/api/auth/config') return fulfill(route, 200, AUTH_CONFIG);
        if (url.pathname === '/api/auth/me') {
            if (request.headers()['authorization'] !== `Bearer ${TOKEN}`)
                return fulfill(route, 401, { detail: 'Not authenticated' });
            return fulfill(route, 200, ADMIN_ME);
        }
        if (request.method() === 'POST') {
            const m = url.pathname.match(/^\/api\/pii-flags\/([^/]+)\/(confirm|dismiss)$/);
            if (m) return decide(route, m[1], m[2] === 'confirm' ? 'confirmed' : 'dismissed');
        }
        if (url.pathname === '/api/pii-flags') return fulfill(route, 200, flags);
        if (url.pathname === '/api/datasets') return fulfill(route, 200, DATASETS);
        if (url.pathname === '/api/discovered-fields') return fulfill(route, 200, FIELDS);
        return fulfill(route, 200, []);
    });

    return { flags, requests, responses };
}

test('PII panel renders pending flags grouped by dataset; confirm and dismiss clear them', async ({ page }) => {
    const mock = await installRoutes(page);
    await page.addInitScript((t) => { window.sessionStorage.setItem('aicrm_token', t); }, TOKEN);
    await page.goto('/studio.html?panel=pii');

    const pii = page.getByTestId('pii-inbox');
    // the flags render, grouped under their dataset, showing the field name + category
    const group = pii.locator(`[data-testid="pii-group"][data-id="${DS_ID}"]`);
    await expect(group.getByText(`${MARK} Customers`)).toBeVisible();
    await expect(group.getByText('EmailAddress')).toBeVisible();
    await expect(group.locator(`[data-testid="pii-flag"][data-id="${CONFIRM_ID}"]`)).toContainText('contact');
    await expect(group.locator(`[data-testid="pii-flag"][data-id="${DISMISS_ID}"]`)).toContainText('direct identifier');

    // the second dataset renders as its own group: grouping is per dataset, not one flat list
    const ordersGroup = pii.locator(`[data-testid="pii-group"][data-id="${DS_ORDERS_ID}"]`);
    await expect(ordersGroup.getByText(`${MARK} Orders`)).toBeVisible();
    await expect(ordersGroup.getByText('OrderID')).toBeVisible();
    await expect(ordersGroup.locator(`[data-testid="pii-flag"][data-id="${ORDERS_FLAG_ID}"]`)).toContainText('direct identifier');
    await expect(page.locator('#pii-count')).toHaveText('3');

    // Confirm -> the flag leaves the pending panel (status becomes 'confirmed')
    await page.locator(`[data-testid="pii-flag"][data-id="${CONFIRM_ID}"] [data-action="pii-confirm"]`).click();
    await expect(pii.locator(`[data-testid="pii-flag"][data-id="${CONFIRM_ID}"]`)).toHaveCount(0);

    // the request went out for the right flag id: POST, the Bearer admin token, no JSON
    // body; the response is the updated flag row (status 'confirmed')
    const confirmReq = mock.requests.find((r) => r.path === `/api/pii-flags/${CONFIRM_ID}/confirm`);
    expect(confirmReq).toBeTruthy();
    expect(confirmReq.method).toBe('POST');
    expect(confirmReq.auth).toBe(`Bearer ${TOKEN}`);
    expect(confirmReq.body).toBeNull();
    const confirmResp = mock.responses.find((r) => r.method === 'POST' && r.path === `/api/pii-flags/${CONFIRM_ID}/confirm`);
    expect(confirmResp.status).toBe(200);
    expect(confirmResp.body).toMatchObject({ id: CONFIRM_ID, status: 'confirmed' });
    await expect(page.locator('#pii-count')).toHaveText('2');

    // Dismiss -> the flag leaves the pending panel (status becomes 'dismissed')
    await page.locator(`[data-testid="pii-flag"][data-id="${DISMISS_ID}"] [data-action="pii-dismiss"]`).click();
    await expect(pii.locator(`[data-testid="pii-flag"][data-id="${DISMISS_ID}"]`)).toHaveCount(0);

    const dismissReq = mock.requests.find((r) => r.path === `/api/pii-flags/${DISMISS_ID}/dismiss`);
    expect(dismissReq).toBeTruthy();
    expect(dismissReq.method).toBe('POST');
    expect(dismissReq.auth).toBe(`Bearer ${TOKEN}`);
    expect(dismissReq.body).toBeNull();
    const dismissResp = mock.responses.find((r) => r.method === 'POST' && r.path === `/api/pii-flags/${DISMISS_ID}/dismiss`);
    expect(dismissResp.status).toBe(200);
    expect(dismissResp.body).toMatchObject({ id: DISMISS_ID, status: 'dismissed' });

    // the decisions persisted with the right statuses (the mock state the panel re-fetched
    // after each action — the same status values the live-stack proof read back)
    const byId = Object.fromEntries(mock.flags.map((f) => [f.id, f.status]));
    expect(byId[CONFIRM_ID]).toBe('confirmed');
    expect(byId[DISMISS_ID]).toBe('dismissed');
    expect(byId[ORDERS_FLAG_ID]).toBe('flagged');
    await expect(page.locator('#pii-count')).toHaveText('1');
    // the untouched pending flag still renders in its dataset group
    await expect(ordersGroup.locator(`[data-testid="pii-flag"][data-id="${ORDERS_FLAG_ID}"]`)).toBeVisible();
});
