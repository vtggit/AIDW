// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

// ---- WCAG contrast helpers (plain string colours from getComputedStyle) --

// Parses a computed colour string into [r, g, b] in 0-255. Handles the
// legacy "rgb(r, g, b)" / "rgba(r, g, b, a)" forms, "#rrggbb" tokens and
// the "color(srgb <r> <g> <b>[/ <a>])" form; a background given by
// color-mix may serialize as either the rgb or the color(srgb ...) value,
// so both are accepted. srgb components are 0-1 numbers (or percentages).
function parseColor(value) {
  const text = String(value === null || value === undefined ? '' : value).trim().toLowerCase();
  if (text === '') return null;
  if (text.startsWith('#')) {
    let hex = text.slice(1);
    if (hex.length === 3) hex = hex.split('').map((c) => c + c).join('');
    if (hex.length === 6) {
      return [
        parseInt(hex.slice(0, 2), 16),
        parseInt(hex.slice(2, 4), 16),
        parseInt(hex.slice(4, 6), 16),
      ];
    }
    return null;
  }
  let match = text.match(/^rgba?\(([^)]+)\)$/);
  if (match) {
    const parts = match[1].split(/[\s,/]+/).filter((part) => part !== '');
    if (parts.length < 3) return null;
    return [Number(parts[0]), Number(parts[1]), Number(parts[2])].map((v) => Math.round(v));
  }
  match = text.match(/^color\(srgb\s+([^)]+)\)$/);
  if (match) {
    const parts = match[1].trim().split(/\s+/);
    if (parts.length < 3) return null;
    const to255 = (part) => {
      if (part.endsWith('%')) return Math.round((Number(part.slice(0, -1)) / 100) * 255);
      const num = Number(part);
      return Math.round(num > 1 ? num : num * 255);
    };
    return [to255(parts[0]), to255(parts[1]), to255(parts[2])];
  }
  return null;
}

// WCAG 2.x relative luminance of an [r, g, b] triple in 0-255.
function relativeLuminance(rgb) {
  const channels = rgb.map((channel) => {
    const c = channel / 255;
    return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2];
}

// WCAG contrast ratio between two plain colour strings (1 to 21).
function contrastRatio(foreground, background) {
  const a = relativeLuminance(parseColor(foreground));
  const b = relativeLuminance(parseColor(background));
  const hi = Math.max(a, b);
  const lo = Math.min(a, b);
  return (hi + 0.05) / (lo + 0.05);
}

// Parses a computed box-shadow string into { x, y, blur, spread, inset }
// with the lengths in px (null for '' or 'none'). The computed value may
// serialize the colour first or last, so the colour and the inset keyword
// are stripped and the four remaining lengths are read as x, y, blur,
// spread in order.
function parseBoxShadow(value) {
  const text = String(value === null || value === undefined ? '' : value).trim().toLowerCase();
  if (text === '' || text === 'none') return null;
  const inset = /\binset\b/.test(text);
  const lengths = text
    .replace(/rgba?\([^)]*\)/g, ' ')
    .replace(/color\([^)]*\)/g, ' ')
    .replace(/#[0-9a-f]{3,8}/g, ' ')
    .replace(/\binset\b/g, ' ')
    .split(/\s+/)
    .filter((part) => part !== '')
    .map((part) => Number(part.replace(/px$/, '')))
    .filter((num) => Number.isFinite(num));
  if (lengths.length < 2) return null;
  return {
    x: lengths[0],
    y: lengths[1],
    blur: lengths[2] === undefined ? 0 : lengths[2],
    spread: lengths[3] === undefined ? 0 : lengths[3],
    inset,
  };
}

