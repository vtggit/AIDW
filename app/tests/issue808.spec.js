/**
 * Mock every /api/** request for upcoming page loads: auth endpoints for
 * `me`, the ingestion endpoints with the 200 pipelines and the 150 runs
 * (exact path matches, so /api/sequence-runs never hits the /api/runs
 * mock), 30 sources, and every other API call an empty JSON array (the
 * Studio boot fetches many lists on startup).
 */
async function mockApi(page, me) {
  await page.unrouteAll();
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = request.url();
    let path = url;
    try {
      path = new URL(url).pathname;
    } catch (_) {
      // non-absolute URL: fall back to the raw string below
    }
    const fulfill = (body) =>
      route.fulfill({ status: 200, contentType: 'application/json', body: typeof body === 'string' ? body : JSON.stringify(body) });
    if (path === '/api/auth/config' || url.includes('/api/auth/config')) return fulfill(AUTH_CONFIG);
    if (path === '/api/auth/me' || url.includes('/api/auth/me')) return fulfill(me);
    if (path === '/api/pipelines') return fulfill(PIPELINES);
    if (path === '/api/datasets') return fulfill(DATASETS);
    if (path === '/api/runs') return fulfill(RUNS);
    if (path === '/api/sources') return fulfill(SOURCES);
    return fulfill('[]');
  });
}

