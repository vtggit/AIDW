'use strict';

// Proof for issue #800 — in Studio, the Data retention tool fits the
// window: the policy region (#retention-policy-table-wrap) on top, the
// runs region (#retention-runs) under it, each scrolling on its own.
//
// Boots /studio.html?panel=retention against mocked /api/** responses
// (no backend) with 200 policies and, for the first policy, 150 sweep
// runs, and proves:
//   AC-1  at 1440x900 neither the document nor the main region scrolls;
//         the policy region (about three fifths of the height) scrolls
//         with its table's header row and the admin's "Add policy"
//         button still inside the region's visible area after it is
//         scrolled to its end; the chosen policy's row carries
//         aria-selected="true" with a background different from an
//         unchosen row's, and its 150 runs are listed in the runs
//         region; the runs region scrolls with the "Sweep runs" heading
//         (in studio.html, above and outside #retention-runs) still in
//         view after it is scrolled to its end, and the policy region
//         does not move when the runs scroll; the runs region sits
//         below the policy region, both inside the tool's box; a delete
//         confirmation shown in a row stays inside the tool's box;
//         "Add policy" shows the policy form inside the policy region
//         with its Save button reachable, no document scroll; opening
//         another Studio tool afterwards scrolls the main region as it
//         did before this change
//   AC-2  at 390x844 the regions stack at their natural height and the
//         page scrolls vertically, the table (wider than its region)
//         scrolls sideways inside the region, and there is no
//         horizontal page scroll
//   Identity  the criteria concern roles, so the proof also runs as a
//         NON-ADMIN (role 'user'): the page is booted the production
//         way (the token in the URL hash as #access_token=...,
//         /api/auth/config and /api/auth/me mocked for that user) and
//         the admin-only "Add policy" control is asserted absent while
//         the table and the runs still render

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

const AUTH_CONFIG = { authEnabled: true, authMode: 'development' };
const ADMIN_ME = { authenticated: true, user: { id: 1, username: 'admin', roles: ['admin'] } };
const VIEWER_ME = { authenticated: true, user: { id: 9, username: 'user', roles: ['user'] } };
const VIEWER_TOKEN = 'viewer-token-800';

// 200 policies: the policy region must scroll for them. The first one
// (pol-0) is enabled; the rest alternate.
const POLICY_COUNT = 200;
const POLICIES = Array.from({ length: POLICY_COUNT }, (_, i) => ({
  id: 'pol-' + i,
  name: 'Purge policy ' + i,
  dataset_id: null,
  table_class: 'runs',
  action: 'purge',
  retention_period_days: 30,
  scope: 'class',
  is_enabled: i % 2 === 0,
  created_at: '2026-01-01T00:00:00',
  updated_at: '2026-01-01T00:00:00',
}));

// The first policy's 150 sweep runs, newest created_at first: the runs
// region must scroll for them.
const RUN_COUNT = 150;
const RUNS = Array.from({ length: RUN_COUNT }, (_, i) => ({
  id: 'run-' + i,
  policy_id: 'pol-0',
  name: 'Sweep ' + i,
  trigger: 'schedule',
  status: 'completed',
  records_purged: i + 1,
  records_anonymized: 0,
  error_detail: null,
  created_at: new Date(1759200000000 - i * 3600000).toISOString(),
  updated_at: '2026-09-30T00:00:00',
}));

// 30 sources: the Data sources tool stays taller than the main region,
// so "another tool scrolls as before" is measurable.
const SOURCE_COUNT = 30;
const SOURCES = Array.from({ length: SOURCE_COUNT }, (_, i) => ({
  id: 'src-' + (i + 1),
  name: 'Source ' + (i + 1),
  type: 'odata',
}));

/**
 * Mock every /api/** request for upcoming page loads: auth endpoints
 * for `me`, the retention endpoints with the 200 policies and the 150
 * runs, 30 sources, and every other API call an empty JSON array (the
 * Studio boot fetches many lists on startup).
 */
async function mockApi(page, me) {
  await page.unrouteAll();
  await page.route('**/api/**', (route) => {
    const url = route.request().url();
    if (url.includes('/api/auth/config')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(AUTH_CONFIG) });
    }
    if (url.includes('/api/auth/me')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(me) });
    }
    if (url.includes('/api/retention-policies')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(POLICIES) });
    }
    if (url.includes('/api/retention-runs')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(RUNS) });
    }
    if (url.includes('/api/sources')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(SOURCES) });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
  });
}

test('issue800 freeform', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await mockApi(page, ADMIN_ME);
  await page.goto('/studio.html?panel=retention');

  // The module's init() ran on boot: the policy table renders all 200
  // policies, the admin's "Add policy" button is in the policy region's
  // toolbar, and the "Sweep runs" heading sits above the runs region.
  const policyRows = page.locator('[data-testid="retention-policy-row"]');
  await expect(policyRows).toHaveCount(POLICY_COUNT);
  await expect(page.locator('[data-testid="retention-policy-table"]')).toBeVisible();
  await expect(page.locator('#retention-policy-table-wrap [data-testid="retention-add-policy"]')).toBeVisible();
  await expect(page.locator('[data-testid="retention-runs-head"]')).toHaveText('Sweep runs');

  // The tool fits the window: neither the document nor the main region
  // scrolls.
  const locked = await page.evaluate(() => {
    const region = document.querySelector('[data-testid="main-content"]');
    return {
      doc: document.scrollingElement.scrollHeight - document.scrollingElement.clientHeight,
      body: document.body.scrollHeight - document.body.clientHeight,
      region: region.scrollHeight - region.clientHeight,
    };
  });
  expect(locked.doc, 'no document scroll').toBeLessThanOrEqual(0);
  expect(locked.body, 'no document scroll').toBeLessThanOrEqual(0);
  expect(locked.region, 'no main-region scroll').toBeLessThanOrEqual(0);

  // Two regions, one above the other, both inside the tool's box; the
  // policy region takes about three fifths of the height.
  const geo = await page.evaluate(() => {
    const rect = (el) => {
      const r = el.getBoundingClientRect();
      return { top: r.top, left: r.left, width: r.width, height: r.height, bottom: r.bottom, right: r.right };
    };
    const section = document.querySelector('section[data-panel="retention"]');
    const policy = document.querySelector('#retention-policy-table-wrap');
    const runs = document.querySelector('#retention-runs');
    const heading = document.querySelector('[data-testid="retention-runs-head"]');
    return {
      section: rect(section),
      policy: rect(policy),
      runs: rect(runs),
      heading: rect(heading),
    };
  });
  expect(geo.runs.top, 'the runs region sits below the policy region').toBeGreaterThanOrEqual(geo.policy.bottom);
  expect(geo.heading.bottom, 'the heading sits above the runs region').toBeLessThanOrEqual(geo.runs.top);
  for (const region of [geo.policy, geo.runs]) {
    expect(region.top, 'the region is inside the tool box').toBeGreaterThanOrEqual(geo.section.top);
    expect(region.left, 'the region is inside the tool box').toBeGreaterThanOrEqual(geo.section.left);
    expect(region.bottom, 'the region is inside the tool box').toBeLessThanOrEqual(geo.section.bottom);
    expect(region.right, 'the region is inside the tool box').toBeLessThanOrEqual(geo.section.right);
  }
  const ratio = geo.policy.height / (geo.policy.height + geo.runs.height);
  expect(ratio, 'the policy region takes about three fifths of the height').toBeGreaterThan(0.55);
  expect(ratio).toBeLessThan(0.65);

  // The policy region scrolls on its own for the mocked volume: 200
  // rows do not fit in its three-fifths of the tool.
  const policyScrollable = await page.evaluate(() => {
    const policy = document.querySelector('#retention-policy-table-wrap');
    return policy.scrollHeight - policy.clientHeight;
  });
  expect(policyScrollable, 'the policy region scrolls').toBeGreaterThan(0);

  // Choose the first policy: its row is marked selected and tinted, and
  // its 150 runs are listed in the runs region.
  await policyRows.first().click();
  const selection = await page.evaluate(() => {
    const selected = document.querySelector('[data-testid="retention-policy-row"][aria-selected="true"]');
    const unselected = document.querySelector('[data-testid="retention-policy-row"][data-id="pol-1"]');
    return {
      selectedCount: document.querySelectorAll('[data-testid="retention-policy-row"][aria-selected="true"]').length,
      selectedId: selected ? selected.getAttribute('data-id') : null,
      selectedBg: selected ? getComputedStyle(selected).backgroundColor : null,
      unselectedBg: unselected ? getComputedStyle(unselected).backgroundColor : null,
    };
  });
  expect(selection.selectedCount).toBe(1);
  expect(selection.selectedId).toBe('pol-0');
  expect(selection.selectedBg, 'the chosen row is tinted').not.toBe(selection.unselectedBg);
  const runsRegion = page.locator('#retention-runs');
  await expect(runsRegion.locator('[data-testid="retention-run-row"]')).toHaveCount(RUN_COUNT);
  // The runs region scrolls on its own for the chosen policy's runs:
  // 150 rows do not fit in its two-fifths of the tool.
  const runsScrollable = await page.evaluate(() => {
    const runs = document.querySelector('#retention-runs');
    return runs.scrollHeight - runs.clientHeight;
  });
  expect(runsScrollable, 'the runs region scrolls').toBeGreaterThan(0);

  // A delete confirmation shown in a row stays inside the tool's box;
  // Cancel restores the row's actions.
  const firstRow = policyRows.first();
  await firstRow.locator('[data-testid="retention-policy-delete"]').click();
  const deleteText = page.locator('[data-testid="retention-policy-delete-text"]');
  await expect(deleteText).toBeVisible();
  await expect(deleteText).toHaveText('Delete Purge policy 0?');
  const confirmInBox = await page.evaluate(() => {
    const section = document.querySelector('section[data-panel="retention"]');
    const confirm = document.querySelector('[data-testid="retention-policy-delete-text"]');
    const s = section.getBoundingClientRect();
    const c = confirm.getBoundingClientRect();
    return c.left >= s.left && c.right <= s.right && c.top >= s.top && c.bottom <= s.bottom;
  });
  expect(confirmInBox, 'the delete confirmation stays inside the tool box').toBe(true);
  await firstRow.locator('[data-testid="retention-policy-delete-cancel"]').click();
  await expect(firstRow.locator('[data-testid="retention-policy-edit"]')).toBeVisible();

  // The policy region scrolled to its end: the table's header row and
  // the "Add policy" button are still inside the region's visible area,
  // and the runs region did not move.
  await page.evaluate(() => {
    const el = document.querySelector('#retention-policy-table-wrap');
    el.scrollTop = el.scrollHeight;
  });
  const pinned = await page.evaluate(() => {
    const region = document.querySelector('#retention-policy-table-wrap');
    // The pinned box is the header row's sticky cell: the row's own
    // table-layout box does not carry the sticky offset, so the cell's
    // rect is what proves the header row stays put (the same element the
    // dashboards drilldown proof pins on).
    const headerCell = document.querySelector('[data-testid="retention-policy-table"] thead th');
    const toolbar = document.querySelector('.wh-retention-toolbar');
    const addButton = document.querySelector('[data-testid="retention-add-policy"]');
    const runs = document.querySelector('#retention-runs');
    const r = region.getBoundingClientRect();
    const h = headerCell.getBoundingClientRect();
    const b = addButton.getBoundingClientRect();
    const t = toolbar.getBoundingClientRect();
    const u = runs.getBoundingClientRect();
    return {
      regionTop: r.top,
      regionBottom: r.bottom,
      headerTop: h.top,
      headerBottom: h.bottom,
      toolbarBottom: t.bottom,
      buttonTop: b.top,
      buttonBottom: b.bottom,
      runsTop: u.top,
      scrolled: region.scrollTop,
    };
  });
  expect(pinned.scrolled, 'the policy region was scrolled to its end').toBeGreaterThan(0);
  expect(pinned.headerTop, 'the header row stays at the top of the region').toBeGreaterThanOrEqual(pinned.regionTop - 1);
  expect(pinned.headerTop, 'the header row stays in view under the pinned toolbar').toBeGreaterThanOrEqual(pinned.toolbarBottom - 1);
  expect(pinned.headerBottom, 'the header row stays inside the region').toBeLessThanOrEqual(pinned.regionBottom);
  expect(pinned.buttonTop, 'the "Add policy" button stays in view above the table').toBeGreaterThanOrEqual(pinned.regionTop - 1);
  expect(pinned.buttonBottom, 'the "Add policy" button stays inside the region').toBeLessThanOrEqual(pinned.regionBottom);
  expect(pinned.runsTop, 'scrolling the policy region does not move the runs region').toBe(geo.runs.top);

  // The runs region scrolled to its end: the "Sweep runs" heading stays
  // in view and the policy region does not move.
  await page.evaluate(() => {
    const el = document.querySelector('#retention-runs');
    el.scrollTop = el.scrollHeight;
  });
  const headingPinned = await page.evaluate(() => {
    const heading = document.querySelector('[data-testid="retention-runs-head"]');
    const policy = document.querySelector('#retention-policy-table-wrap');
    const h = heading.getBoundingClientRect();
    return {
      headingTop: h.top,
      headingBottom: h.bottom,
      policyTop: policy.getBoundingClientRect().top,
      viewport: window.innerHeight,
      scrolled: document.querySelector('#retention-runs').scrollTop,
    };
  });
  expect(headingPinned.scrolled, 'the runs region was scrolled to its end').toBeGreaterThan(0);
  expect(headingPinned.headingTop, 'the "Sweep runs" heading stays in view').toBeGreaterThanOrEqual(0);
  expect(headingPinned.headingBottom, 'the "Sweep runs" heading stays in view').toBeLessThanOrEqual(headingPinned.viewport);
  expect(headingPinned.policyTop, 'the policy region does not move when the runs scroll').toBe(geo.policy.top);

  // "Add policy" shows the policy form inside the policy region; the
  // region scrolls for it, the Save button is reachable, and nothing
  // scrolls the document.
  await page.locator('[data-testid="retention-add-policy"]').click();
  const form = page.locator('#retention-policy-table-wrap [data-testid="retention-policy-form"]');
  await expect(form).toBeVisible();
  await expect(form.locator('[data-testid="retention-form-name"]')).toBeVisible();
  const saveButton = form.locator('[data-testid="retention-form-save"]');
  await expect(saveButton).toBeVisible();
  await saveButton.click(); // scrolls into view inside the policy region
  const formError = page.locator('[data-testid="retention-form-error"]');
  await expect(formError).toBeVisible();
  await expect(formError).toHaveText('Name is required.');
  const formLocked = await page.evaluate(() => {
    const region = document.querySelector('[data-testid="main-content"]');
    return {
      doc: document.scrollingElement.scrollHeight - document.scrollingElement.clientHeight,
      region: region.scrollHeight - region.clientHeight,
    };
  });
  expect(formLocked.doc, 'the form does not scroll the document').toBeLessThanOrEqual(0);
  expect(formLocked.region, 'the form does not scroll the main region').toBeLessThanOrEqual(0);

  // Another Studio tool afterwards: the main region scrolls as it did
  // before this change (a tall tool scrolls it; the document does not).
  await page.click('.aidw-nav-item[data-nav-panel="sources"]');
  await expect(page.locator('#sources .src-row')).toHaveCount(SOURCE_COUNT);
  const tallRegion = await page.evaluate(() => {
    const el = document.querySelector('[data-testid="main-content"]');
    return { scrollHeight: el.scrollHeight, clientHeight: el.clientHeight };
  });
  expect(tallRegion.scrollHeight, 'a tall tool still scrolls the main region').toBeGreaterThan(tallRegion.clientHeight);
  const docStillLocked = await page.evaluate(() => document.scrollingElement.scrollHeight - document.scrollingElement.clientHeight);
  expect(docStillLocked).toBeLessThanOrEqual(0);

  // At 390x844: the regions stack at their natural height, the page
  // scrolls vertically, the table (wider than its region) scrolls
  // sideways inside the region, and there is no horizontal page scroll.
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/studio.html?panel=retention');
  await expect(policyRows).toHaveCount(POLICY_COUNT);
  const narrow = await page.evaluate(() => {
    window.scrollTo(100, 0);
    const doc = document.documentElement;
    const region = document.querySelector('#retention-policy-table-wrap');
    const table = document.querySelector('[data-testid="retention-policy-table"]');
    region.scrollLeft = region.scrollWidth;
    return {
      scrollX: window.scrollX,
      pageHorizontal: doc.scrollWidth - doc.clientWidth,
      bodyHorizontal: document.body.scrollWidth - document.body.clientWidth,
      pageVertical: document.scrollingElement.scrollHeight - document.scrollingElement.clientHeight,
      tableWidth: table.getBoundingClientRect().width,
      regionWidth: region.clientWidth,
      regionScrollable: region.scrollWidth - region.clientWidth,
      regionScrollLeft: region.scrollLeft,
    };
  });
  expect(narrow.scrollX, 'no horizontal page scroll').toBe(0);
  expect(narrow.pageHorizontal, 'no horizontal page scroll').toBeLessThanOrEqual(0);
  expect(narrow.bodyHorizontal, 'no horizontal page scroll').toBeLessThanOrEqual(0);
  expect(narrow.pageVertical, 'the page scrolls vertically for the stacked regions').toBeGreaterThan(0);
  expect(narrow.tableWidth, 'the table is wider than its region').toBeGreaterThan(narrow.regionWidth);
  expect(narrow.regionScrollable, 'the region scrolls sideways for the table').toBeGreaterThan(0);
  expect(narrow.regionScrollLeft, 'the region can be scrolled sideways').toBeGreaterThan(0);
});

test('issue800 freeform (viewer)', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });

  // Boot the production way for a role 'user' identity: the token rides
  // the URL hash (#access_token=...), /api/auth/config and /api/auth/me
  // are mocked for that user, and the hash token must reach
  // /api/auth/me as a Bearer header.
  const meAuthorizations = [];
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = request.url();
    if (url.includes('/api/auth/config')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(AUTH_CONFIG) });
    }
    if (url.includes('/api/auth/me')) {
      const auth = request.headers()['authorization'];
      if (auth) meAuthorizations.push(auth);
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(VIEWER_ME) });
    }
    if (url.includes('/api/retention-policies')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(POLICIES) });
    }
    if (url.includes('/api/retention-runs')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(RUNS) });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
  });

  await page.goto('/studio.html?panel=retention#access_token=' + encodeURIComponent(VIEWER_TOKEN));
  await expect.poll(() => meAuthorizations).toContain('Bearer ' + VIEWER_TOKEN);

  // The page still renders for the non-admin...
  await expect(page.locator('[data-testid="sidebar"]')).toBeVisible();
  await expect(page.locator('.aidw-page-title')).toHaveText('Studio \u00b7 Data retention');
  // ...while no admin-only control survives (fail-closed removal)...
  await expect(page.locator('[data-requires-role="admin"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="retention-add-policy"]')).toHaveCount(0);
  // ...and the table and the runs region render without them.
  await expect(page.locator('[data-testid="retention-policy-table"]')).toBeVisible();
  await expect(page.locator('[data-testid="retention-policy-row"]')).toHaveCount(POLICY_COUNT);
  const runsRegion = page.locator('#retention-runs');
  await expect(runsRegion).toBeVisible();
  await expect(runsRegion).toHaveText('Select a policy to see its runs.');

  // Choosing a policy shows its 150 runs for the non-admin as well,
  // with the chosen row marked...
  await page.locator('[data-testid="retention-policy-row"][data-id="pol-0"]').click();
  await expect(page.locator('[data-testid="retention-policy-row"][data-id="pol-0"]')).toHaveAttribute('aria-selected', 'true');
  await expect(runsRegion.locator('[data-testid="retention-run-row"]')).toHaveCount(RUN_COUNT);
  // ...and the tool still fits the window: no document scroll.
  const doc = await page.evaluate(() => document.scrollingElement.scrollHeight - document.scrollingElement.clientHeight);
  expect(doc).toBeLessThanOrEqual(0);
});
