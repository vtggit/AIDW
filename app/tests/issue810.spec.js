// Proof for issue #810 — Studio's run lists (Load sequences run history,
// Ingestion pipeline runs and Data retention sweep runs) show readable
// UTC stamps instead of the server's raw timestamp strings.
//
// Boots studio.html against mocked /api/** responses (no backend) with
// the clock fixed by Playwright's clock at 2026-10-13 12:00 UTC and
// proves:
//   AC-1  TimeFormat.stamp reads both forms the server sends
//         ("2026-10-13 07:30:17.18781+00" and
//         "2026-10-13T07:30:39.930242+00:00") as "2026-10-13 07:30
//         UTC"; a value with no time zone is read too; an unreadable
//         string is returned unchanged; null is an em dash; a hostile
//         non-string never throws; a valid offset crossing the UTC date
//         is read too; years 0000-0099 are not shifted.
//         TimeFormat.span gives "22 s", "8 min 1 s", "3 h 12 min" and
//         "8 d 4 h" for hand-picked pairs — and keeps the unit next
//         below the largest even when it is zero ("8 d 0 h", "3 h 0
//         min", "8 min 0 s") — plus an empty string for a missing
//         value and for an end before the start.
//   AC-2  a finished sequence run (started 07:30:17, finished
//         07:30:39) shows the stamp "2026-10-13 07:30 UTC", "took 22 s"
//         and the server's original start value in the stamp's title;
//         a sequence run still running since 2026-10-05 21:14 UTC shows
//         "running for 7 d 14 h" and no "took"; a pending run with no
//         start shows "waiting for" plus its age from when it was
//         created, or no age when that is missing, with no "Invalid
//         Date", "NaN" or "undefined" anywhere in the list; an
//         Ingestion run shows both readable stamps and its "took" span;
//         a Data retention run shows its readable created stamp; a run
//         whose start is <img src=x onerror=window.__pwned=1> renders
//         as inert text (window.__pwned stays undefined); the Load
//         sequences, Ingestion and Data retention tools each fit
//         1440x900 with no document scroll.

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

