/**
 * Mock every /api/** request for upcoming page loads: the auth
 * endpoints for an admin (the token rides the URL hash), the three
 * tools' endpoints with the mocked lists, and every other API call an
 * empty JSON array (the Studio boot fetches many lists on startup).
 */
async function mockApi(page, authHeaders) {
  await page.unrouteAll();
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = request.url();
    let path = url;
    try {
      path = new URL(url).pathname;
    } catch (_) {
      // non-absolute URL: fall back to the raw string below
    }
    const fulfill = (body) =>
      route.fulfill({ status: 200, contentType: 'application/json', body: typeof body === 'string' ? body : JSON.stringify(body) });
    if (path === '/api/auth/config' || url.includes('/api/auth/config')) return fulfill(AUTH_CONFIG);
    if (path === '/api/auth/me' || url.includes('/api/auth/me')) {
      const auth = request.headers()['authorization'];
      if (auth) authHeaders.push(auth);
      return fulfill(ADMIN_ME);
    }
    if (path === '/api/load-sequences') return fulfill(SEQUENCES);
    if (path === '/api/sequence-runs') return fulfill(RUNS);
    if (path === '/api/pipelines') return fulfill(PIPELINES);
    if (path === '/api/datasets') return fulfill(DATASETS);
    if (path === '/api/runs') return fulfill(INGESTION_RUNS);
    if (path === '/api/retention-policies') return fulfill(POLICIES);
    if (path === '/api/retention-runs') return fulfill(RETENTION_RUNS);
    if (path.startsWith('/api/load-sequences/') && path.endsWith('/bpmn')) {
      return fulfill(bpmnFor(decodeURIComponent(path.split('/')[3])));
    }
    return fulfill('[]');
  });
}

/** The document does not scroll (neither the root scroller nor the body). */
async function assertNoDocumentScroll(page, tool) {
  const scroll = await page.evaluate(() => {
    const scroller = document.scrollingElement;
    return {
      doc: scroller.scrollHeight - scroller.clientHeight,
      body: document.body.scrollHeight - document.body.clientHeight,
    };
  });
  expect(scroll.doc, tool + ': the document does not scroll').toBeLessThanOrEqual(0);
  expect(scroll.body, tool + ': the document does not scroll').toBeLessThanOrEqual(0);
}

test('issue810 freeform', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });

  const authHeaders = [];
  await mockApi(page, authHeaders);

  // The clock is fixed at 2026-10-13 12:00 UTC before the page boots,
  // so every new Date() the page makes is that instant.
  await page.clock.install({ time: new Date(FIXED_TIME) });

  // --------------------------------------------------------------------
  // AC-1: the TimeFormat module itself — both server forms, a naive
  // value, an unreadable string and null.
  // --------------------------------------------------------------------
  await page.goto('/studio.html?panel=sequences#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  await expect.poll(() => authHeaders).toContain('Bearer ' + ADMIN_TOKEN);

  const unit = await page.evaluate(() => {
    const tf = window.TimeFormat;
    return {
      loaded: typeof tf !== 'undefined' && tf !== null,
      spaceForm: tf.stamp('2026-10-13 07:30:17.18781+00'),
      isoForm: tf.stamp('2026-10-13T07:30:39.930242+00:00'),
      naive: tf.stamp('2026-10-02T00:00:00'),
      unreadable: tf.stamp('not a timestamp'),
      nullValue: tf.stamp(null),
      hostileNullProto: (function () {
        return tf.stamp(Object.create(null));
      })(),
      hostileThrowingToString: (function () {
        const bomb = { toString: () => { throw new Error('boom'); } };
        return tf.stamp(bomb);
      })(),
      offsetCrossForward: tf.stamp('2026-10-13T23:30:00-05:00'),
      offsetCrossBackward: tf.stamp('2026-10-13T01:30:00+05:30'),
      year0005: tf.stamp('0005-01-02T03:04:05Z'),
      year0000: tf.stamp('0000-12-31T23:59:59Z'),
      span22s: tf.span('2026-10-13T07:30:17Z', '2026-10-13T07:30:39Z'),
      spanMin: tf.span('2026-10-13T07:00:00Z', '2026-10-13T07:08:01Z'),
      spanHours: tf.span('2026-10-10T01:00:00Z', '2026-10-10T04:12:00Z'),
      spanDays: tf.span('2026-10-01T00:00:00Z', '2026-10-09T04:00:00Z'),
      spanZeroHour: tf.span('2026-10-01T00:00:00Z', '2026-10-09T00:05:00Z'),
      spanZeroMin: tf.span('2026-10-10T01:00:00Z', '2026-10-10T04:00:45Z'),
      spanZeroSec: tf.span('2026-10-13T07:00:00Z', '2026-10-13T07:08:00Z'),
      spanMissing: tf.span(null, '2026-10-13T07:30:39Z'),
      spanNegative: tf.span('2026-10-13T07:30:39Z', '2026-10-13T07:30:17Z'),
    };
  });
  expect(unit.loaded, 'studio.html loads time_format.js').toBe(true);
  expect(unit.spaceForm, 'the Postgres text form is read').toBe('2026-10-13 07:30 UTC');
  expect(unit.isoForm, 'the ISO form is read').toBe('2026-10-13 07:30 UTC');
  expect(unit.naive, 'a value with no time zone is read as UTC').toBe('2026-10-02 00:00 UTC');
  expect(unit.unreadable, 'an unreadable string is returned unchanged').toBe('not a timestamp');
  expect(unit.nullValue, 'null is an em dash').toBe('\u2014');
  expect(unit.hostileNullProto, 'a hostile non-string without a toString never throws').toBe('[object Object]');
  expect(unit.hostileThrowingToString, 'a non-string whose toString throws never throws').toBe('[object Object]');
  expect(unit.offsetCrossForward, 'a valid offset crossing the UTC date forward is read').toBe('2026-10-14 04:30 UTC');
  expect(unit.offsetCrossBackward, 'a valid offset crossing the UTC date backward is read').toBe('2026-10-12 20:00 UTC');
  expect(unit.year0005, 'years 0000-0099 are not shifted to 1900-1999').toBe('0005-01-02 03:04 UTC');
  expect(unit.year0000, 'year 0000 is not shifted to 1900').toBe('0000-12-31 23:59 UTC');
  expect(unit.span22s).toBe('22 s');
  expect(unit.spanMin).toBe('8 min 1 s');
  expect(unit.spanHours).toBe('3 h 12 min');
  expect(unit.spanDays).toBe('8 d 4 h');
  expect(unit.spanZeroHour, 'a zero hour is kept next to the largest unit').toBe('8 d 0 h');
  expect(unit.spanZeroMin, 'a zero minute is kept next to the largest unit').toBe('3 h 0 min');
  expect(unit.spanZeroSec, 'a zero second is kept next to the largest unit').toBe('8 min 0 s');
  expect(unit.spanMissing, 'a missing value is an empty string').toBe('');
  expect(unit.spanNegative, 'an end before the start is an empty string').toBe('');

  // --------------------------------------------------------------------
  // AC-2: the Load sequences run history.
  // --------------------------------------------------------------------
  const seqRow = page.locator('[data-testid="sequence-row"][data-id="seq-810"]');
  await seqRow.click();
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(5);

  // The finished run: the readable start stamp (the server's original
  // value in its title), "took 22 s", the readable finished stamp.
  const doneRow = page.locator('[data-testid="run-row"][data-id="run-810-done"]');
  await expect(doneRow.locator('[data-testid="run-started"]')).toHaveText('2026-10-13 07:30 UTC');
  await expect(doneRow.locator('[data-testid="run-started"]')).toHaveAttribute('title', SPACE_FORM_START);
  await expect(doneRow.locator('[data-testid="run-duration"]')).toHaveText('took 22 s');
  await expect(doneRow).not.toContainText('running for');

  // The still-running run: "running for 7 d 14 h" from its start, and
  // no "took" anywhere in the row.
  const runningRow = page.locator('[data-testid="run-row"][data-id="run-810-running"]');
  await expect(runningRow.locator('[data-testid="run-age"]')).toHaveText('running for 7 d 14 h');
  await expect(runningRow).not.toContainText('took');
  await expect(runningRow.locator('[data-testid="run-duration"]')).toHaveCount(0);

  // The pending runs: "waiting for" plus the age from when they were
  // created — or just the label when that is missing.
  const waitingRow = page.locator('[data-testid="run-row"][data-id="run-810-waiting"]');
  await expect(waitingRow.locator('[data-testid="run-age"]')).toHaveText(/waiting for 5 min/);
  const bareRow = page.locator('[data-testid="run-row"][data-id="run-810-bare-waiting"]');
  await expect(bareRow.locator('[data-testid="run-age"]')).toHaveText('waiting for');

  // The hostile start value renders as inert text and runs nothing.
  const xssRow = page.locator('[data-testid="run-row"][data-id="run-810-xss"]');
  await expect(xssRow.locator('[data-testid="run-started"]')).toHaveText(XSS_START);
  expect(await xssRow.locator('img').count(), 'no <img> is injected').toBe(0);
  expect(await page.evaluate(() => window.__pwned), 'window.__pwned stays undefined').toBeUndefined();

  // Nowhere in the list: "Invalid Date", "NaN" or "undefined".
  const runsText = await page.locator('[data-testid="sequence-runs"]').textContent();
  expect(runsText).not.toContain('Invalid Date');
  expect(runsText).not.toContain('NaN');
  expect(runsText).not.toContain('undefined');

  // The Load sequences tool fits 1440x900: the document does not scroll.
  await assertNoDocumentScroll(page, 'Load sequences');

  // --------------------------------------------------------------------
  // AC-2: the Ingestion pipeline runs.
  // --------------------------------------------------------------------
  await page.goto('/studio.html?panel=ingestion#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  const pipelineRow = page.locator('[data-testid="ingestion-pipeline-row"][data-id="pipe-810"]');
  await expect(pipelineRow).toBeVisible();
  await pipelineRow.click();
  const ingRow = page.locator('[data-testid="ingestion-run-row"][data-id="ing-run-1"]');
  await expect(ingRow.locator('[data-testid="ingestion-run-started"]')).toHaveText('2026-10-13 06:00 UTC');
  await expect(ingRow.locator('[data-testid="ingestion-run-started"]')).toHaveAttribute('title', '2026-10-13 06:00:00+00');
  await expect(ingRow.locator('[data-testid="ingestion-run-finished"]')).toHaveText('2026-10-13 06:05 UTC');
  await expect(ingRow.locator('[data-testid="ingestion-run-duration"]')).toHaveText('took 5 min 30 s');

  // The Ingestion tool fits 1440x900: the document does not scroll.
  await assertNoDocumentScroll(page, 'Ingestion');

  // --------------------------------------------------------------------
  // AC-2: the Data retention sweep runs.
  // --------------------------------------------------------------------
  await page.goto('/studio.html?panel=retention#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  const policyRow = page.locator('[data-testid="retention-policy-row"][data-id="pol-810"]');
  await expect(policyRow).toBeVisible();
  await policyRow.click();
  const retRow = page.locator('[data-testid="retention-run-row"][data-id="ret-run-1"]');
  await expect(retRow.locator('[data-testid="retention-run-created"]')).toHaveText('2026-10-12 23:45 UTC');
  await expect(retRow.locator('[data-testid="retention-run-created"]')).toHaveAttribute('title', '2026-10-12T23:45:00.123456+00');

  // The Data retention tool fits 1440x900: the document does not scroll.
  await assertNoDocumentScroll(page, 'Data retention');
});
