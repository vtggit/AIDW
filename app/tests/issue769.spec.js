'use strict';

// Proof for issue #769 — Studio shows exactly ONE tool at a time.
//
// Boots studio.html against mocked /api/** responses (no backend) and
// proves:
//   AC-1  each ?panel= value shows only its tool (the Load sequences
//         tool shows BOTH its "Load sequences" section and its "Run
//         history" section, because they are one tool); an absent or
//         unknown ?panel= — and Feed keys for a non-admin — shows Data
//         sources; every other tool's section carries the `hidden`
//         attribute and is not visible; a sidebar item shows its tool
//         without a page load (pushState — a window marker survives),
//         updates aria-current="page" and resets the main region's
//         scroll to the top; Back and forward restore the previous
//         tool; hidden tools keep their state (DOM, ids, data-* hooks,
//         loaded data and form input — switching back shows them as
//         they were); the main header reads "Studio · <tool name>";
//         at 1440x900 the document does not scroll and the main region
//         scrolls only when the shown tool is taller than it; at
//         390x844 there is no horizontal page scroll
//   AC-3  for each tool the controller hides the FULL panel container
//         (the enclosing section.wh-panel): no inactive tool header,
//         layout or inner [data-panel] content remains visible
//   AC-4  the shell owns the .wh-panel visibility mechanism: inactive
//         panels stay hidden even when panel CSS sets an explicit
//         display value (proved with an injected !important rule)
//   Identity  the criteria concern roles, so the proof also runs a
//         non-admin pass (role 'user') booted the production way (the
//         token in the URL hash as #access_token=..., /api/auth/config
//         and /api/auth/me mocked for that user): the admin-only
//         controls are absent while the page still renders, and a
//         ?panel=feedkeys deep link shows Data sources

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

const AUTH_CONFIG = { auth_mode: 'development' };
const ADMIN_ME = { authenticated: true, user: { id: 1, username: 'admin', roles: ['admin'] } };
const VIEWER_ME = { authenticated: true, user: { id: 9, username: 'user', roles: ['user'] } };
const VIEWER_TOKEN = 'viewer-token-769';

// The tools, in sidebar order. `sections` lists the section.wh-panel
// containers each tool occupies; Load sequences is ONE tool with two
// sections (its list and its run history).
const TOOLS = [
  { panel: 'sources', label: 'Data sources', sections: ['sources'] },
  { panel: 'suggestions', label: 'Suggestions', sections: ['suggestions'] },
  { panel: 'pii', label: 'PII flags', sections: ['pii'] },
  { panel: 'wizard', label: 'Process wizard', sections: ['wizard'] },
  { panel: 'sequences', label: 'Load sequences', sections: ['sequences', 'sequence-runs'] },
  { panel: 'retention', label: 'Data retention', sections: ['retention'] },
  { panel: 'ingestion', label: 'Ingestion', sections: ['ingestion'] },
  { panel: 'feedkeys', label: 'Feed keys', sections: ['feedkeys'] },
  { panel: 'audit', label: 'Audit history', sections: ['audit'] },
];

// Mock every /api/** request: auth endpoints for `me`; /api/sources
// answers with `sourceCount` rows so the Data sources tool is taller
// than the main region (it must then scroll, and shorter tools must
// not); every other API call an empty JSON array.
async function mockApi(page, me, sourceCount = 0) {
  await page.unrouteAll();
  const sources = [];
  for (let i = 1; i <= sourceCount; i++) {
    sources.push({ id: 'src-' + i, name: 'Source ' + i, type: 'odata' });
  }
  await page.route('**/api/**', (route) => {
    const url = route.request().url();
    if (url.includes('/api/auth/config')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(AUTH_CONFIG) });
    }
    if (url.includes('/api/auth/me')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(me) });
    }
    if (url.includes('/api/sources')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(sources) });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
  });
}

// The visibility state of every tool's full panel container, plus the
// main header title.  A container is "visible" only when it carries no
// `hidden` attribute and has a non-zero box; the shell's mechanism is
// the `hidden` attribute (plus its display pin).
const toolState = (page) =>
  page.evaluate(() => {
    const state = (el) =>
      el
        ? {
            hidden: el.hasAttribute('hidden'),
            inlineDisplay: el.style.display,
            width: el.getBoundingClientRect().width,
            height: el.getBoundingClientRect().height,
          }
        : null;
    const sectionOf = (panel) => {
      const el = document.querySelector('[data-panel="' + panel + '"]');
      if (!el) return null;
      return el.closest('section.wh-panel') || el;
    };
    const out = { title: document.querySelector('.aidw-page-title').textContent };
    for (const panel of ['sources', 'suggestions', 'pii', 'wizard', 'sequences', 'sequence-runs', 'retention', 'ingestion', 'feedkeys', 'audit']) {
      out[panel] = state(sectionOf(panel));
    }
    return out;
  });

// Exactly `active` (a tool from TOOLS) is shown: its sections are
// visible, and every other tool's section is hidden — the `hidden`
// attribute set, the box zero, and (AC-3) the header/layout/inner
// [data-panel] content of the inactive tool gone with it.
async function expectOnlyTool(page, active) {
  const state = await toolState(page);
  expect(state.title, 'main header title').toBe('Studio \u00b7 ' + active.label);
  const visible = new Set(active.sections);
  for (const tool of TOOLS) {
    for (const section of tool.sections) {
      const s = state[section];
      if (s === null) {
        // A role-hidden container may have left the DOM entirely (the
        // fail-closed removal); that is by definition "not visible".
        expect(visible.has(section), `an ACTIVE tool's section is missing from the DOM: ${section}`).toBe(false);
        continue;
      }
      if (visible.has(section)) {
        expect(s.hidden, `${section} section must not carry the hidden attribute`).toBe(false);
        expect(s.width, `${section} section must be visible`).toBeGreaterThan(0);
        expect(s.height, `${section} section must be visible`).toBeGreaterThan(0);
      } else {
        expect(s.hidden, `${section} section must carry the hidden attribute`).toBe(true);
        expect(s.width, `${section} section must not be visible`).toBe(0);
      }
    }
  }
  // AC-3: nothing of an inactive tool remains visible — its panel head
  // heading and its inner [data-panel] content are all out of the box.
  for (const tool of TOOLS) {
    if (tool === active) continue;
    const leftovers = await page.evaluate((sections) => {
      const out = [];
      for (const section of sections) {
        const el = document.querySelector('[data-panel="' + section + '"]');
        if (!el) continue;
        const container = el.closest('section.wh-panel') || el;
        const head = container.querySelector('.wh-panel-head');
        const r = (node) => (node ? node.getBoundingClientRect() : null);
        if (r(el) && (r(el).width > 0 || r(el).height > 0)) out.push(section + ':inner');
        if (head && r(head) && (r(head).width > 0 || r(head).height > 0)) out.push(section + ':head');
      }
      return out;
    }, tool.sections);
    expect(leftovers, `visible leftovers of the inactive ${tool.panel} tool`).toEqual([]);
  }
}

// AC-1 scrolling: at 1440x900 the document itself never scrolls.
async function expectNoDocumentScroll(page) {
  const m = await page.evaluate(() => ({
    doc: document.scrollingElement.scrollHeight - document.scrollingElement.clientHeight,
    body: document.body.scrollHeight - document.body.clientHeight,
    win: window.scrollY,
  }));
  expect(m.doc).toBeLessThanOrEqual(0);
  expect(m.body).toBeLessThanOrEqual(0);
  expect(m.win).toBe(0);
}

// AC-1 scrolling: at 390x844 there is no horizontal page scroll (the
// sidebar's own top-bar nav may scroll internally; the document must
// not).
async function expectNoHorizontalScroll(page) {
  const m = await page.evaluate(() => {
    window.scrollTo(100, 0);
    const doc = document.documentElement;
    return {
      scrollX: window.scrollX,
      doc: doc.scrollWidth - doc.clientWidth,
      body: document.body.scrollWidth - document.body.clientWidth,
    };
  });
  expect(m.scrollX).toBe(0);
  expect(m.doc).toBeLessThanOrEqual(0);
  expect(m.body).toBeLessThanOrEqual(0);
}

test('issue769 freeform', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  // 30 sources: the Data sources tool is taller than the main region,
  // so the region scrolls for it and not for the short tools.
  await mockApi(page, ADMIN_ME, 30);

  // ------------------------------------------------------------------
  // AC-1/AC-3: each ?panel= value shows only its tool; Load sequences
  // shows both of its sections; absent or unknown ?panel= shows Data
  // sources.
  // ------------------------------------------------------------------
  for (const tool of TOOLS) {
    await page.goto('/studio.html?panel=' + tool.panel);
    await expect
      .poll(async () => (await toolState(page)).title)
      .toBe('Studio \u00b7 ' + tool.label);
    await expectOnlyTool(page, tool);
    await expectNoDocumentScroll(page);
  }

  // An absent ?panel= shows Data sources (and the first tool's nav item
  // is current)...
  await page.goto('/studio.html');
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Data sources');
  await expectOnlyTool(page, TOOLS[0]);
  await expect(page.locator('.aidw-nav-item[data-nav-panel="sources"]')).toHaveAttribute('aria-current', 'page');

  // ...and so does an unknown one.
  await page.goto('/studio.html?panel=bogus');
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Data sources');
  await expectOnlyTool(page, TOOLS[0]);

  // ------------------------------------------------------------------
  // AC-1: the main region scrolls only when the shown tool is taller
  // than it (Data sources with 30 rows is; the empty PII flags tool
  // is not).
  // ------------------------------------------------------------------
  await page.goto('/studio.html?panel=sources');
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Data sources');
  // The 30 rows are rendered: the region's height is final before it is
  // measured (the title is set on DOMContentLoaded, before the list
  // renders).
  await expect(page.locator('#sources .src-row')).toHaveCount(30);
  const tallRegion = await page.evaluate(() => {
    const el = document.querySelector('[data-testid="main-content"]');
    return { scrollHeight: el.scrollHeight, clientHeight: el.clientHeight };
  });
  expect(tallRegion.scrollHeight, 'tall tool: the main region scrolls').toBeGreaterThan(tallRegion.clientHeight);
  await expectNoDocumentScroll(page);

  // Switch to a short tool: the region no longer scrolls.
  await page.click('.aidw-nav-item[data-nav-panel="pii"]');
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 PII flags');
  const shortRegion = await page.evaluate(() => {
    const el = document.querySelector('[data-testid="main-content"]');
    return { scrollHeight: el.scrollHeight, clientHeight: el.clientHeight };
  });
  expect(shortRegion.scrollHeight, 'short tool: the main region does not scroll').toBeLessThanOrEqual(shortRegion.clientHeight);

  // ------------------------------------------------------------------
  // AC-1: switching tools — no page load (pushState), aria-current,
  // scroll reset, title; Back and forward restore the previous tool.
  // ------------------------------------------------------------------
  await page.goto('/studio.html?panel=sources');
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Data sources');
  await page.evaluate(() => { window.__issue769Marker = 'alive'; });
  // The 30 rows are rendered: the region is genuinely scrollable before
  // the proof pushes it away from the top.
  await expect(page.locator('#sources .src-row')).toHaveCount(30);
  // Put the region somewhere other than the top (it is scrollable:
  // 30 sources)...
  await page.evaluate(() => {
    const el = document.querySelector('[data-testid="main-content"]');
    el.scrollTop = 400;
  });
  expect(await page.evaluate(() => document.querySelector('[data-testid="main-content"]').scrollTop)).toBeGreaterThan(0);

  // ...then a sidebar item shows its tool WITHOUT a page load...
  await page.click('.aidw-nav-item[data-nav-panel="retention"]');
  expect(await page.evaluate(() => window.__issue769Marker), 'window state must survive: no page load').toBe('alive');
  // ...the ?panel= deep link is in the URL (a reload re-shows the tool)...
  expect(new URL(page.url()).searchParams.get('panel')).toBe('retention');
  // ...aria-current="page" moved to the item...
  await expect(page.locator('.aidw-nav-item[data-nav-panel="retention"]')).toHaveAttribute('aria-current', 'page');
  await expect(page.locator('.aidw-nav-item[data-nav-panel="sources"]')).not.toHaveAttribute('aria-current');
  // ...the main region is back at the top...
  expect(await page.evaluate(() => document.querySelector('[data-testid="main-content"]').scrollTop)).toBe(0);
  // ...the title reads the tool...
  await expect(page.locator('.aidw-page-title')).toHaveText('Studio \u00b7 Data retention');
  // ...and only that tool is shown.
  await expectOnlyTool(page, TOOLS.find((t) => t.panel === 'retention'));

  // Back restores the previous tool (no reload: the marker survives)...
  await page.goBack();
  expect(await page.evaluate(() => window.__issue769Marker)).toBe('alive');
  expect(new URL(page.url()).searchParams.get('panel')).toBe('sources');
  await expect(page.locator('.aidw-page-title')).toHaveText('Studio \u00b7 Data sources');
  await expectOnlyTool(page, TOOLS[0]);
  await expect(page.locator('.aidw-nav-item[data-nav-panel="sources"]')).toHaveAttribute('aria-current', 'page');
  expect(await page.evaluate(() => document.querySelector('[data-testid="main-content"]').scrollTop)).toBe(0);

  // ...and forward restores the one it came from.
  await page.goForward();
  expect(new URL(page.url()).searchParams.get('panel')).toBe('retention');
  await expect(page.locator('.aidw-page-title')).toHaveText('Studio \u00b7 Data retention');
  await expectOnlyTool(page, TOOLS.find((t) => t.panel === 'retention'));

  // ------------------------------------------------------------------
  // AC-1: hidden tools keep their state — a form value typed in Data
  // sources survives a switch away and back, and loaded data in a
  // hidden tool (the Feed keys table loaded at boot) is already there
  // when the tool is shown.
  // ------------------------------------------------------------------
  await page.goto('/studio.html?panel=sources');
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Data sources');
  await page.fill('#src-name', 'Persisted source');
  await page.click('.aidw-nav-item[data-nav-panel="suggestions"]');
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Suggestions');
  // While hidden, the Data sources form and its hooks are all intact...
  await expect(page.locator('#source-form')).toBeAttached();
  await expect(page.locator('#source-form')).toHaveAttribute('data-requires-role', 'admin');
  await expect(page.locator('#src-submit')).toBeAttached();
  await expect(page.locator('#src-name')).toHaveValue('Persisted source');
  // ...and switching back shows it exactly as it was.
  await page.click('.aidw-nav-item[data-nav-panel="sources"]');
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Data sources');
  await expect(page.locator('#src-name')).toHaveValue('Persisted source');
  await expect(page.locator('#source-form')).toBeVisible();

  // Loaded data: the Feed keys table loaded at boot (while its section
  // was hidden) is already rendered when the tool is switched to.
  await page.click('.aidw-nav-item[data-nav-panel="feedkeys"]');
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Feed keys');
  await expect(page.locator('[data-testid="feedkeys-empty"]')).toHaveText('No feed keys yet.');
  await expectOnlyTool(page, TOOLS.find((t) => t.panel === 'feedkeys'));

  // ------------------------------------------------------------------
  // AC-4: the shell owns the .wh-panel visibility mechanism — an
  // explicit display value set by panel CSS (even !important) does not
  // reveal an inactive tool's container.
  // ------------------------------------------------------------------
  await page.addStyleTag({ content: '.wh-panel { display: flex !important; }' });
  const forced = await toolState(page);
  // The active tool stays visible...
  expect(forced.feedkeys.width, 'active tool stays visible under a forced display value').toBeGreaterThan(0);
  // ...and every inactive container stays fully hidden (the shell's
  // hidden attribute + display pin beat the panel CSS)...
  for (const tool of TOOLS) {
    if (tool.panel === 'feedkeys') continue;
    for (const section of tool.sections) {
      expect(forced[section].hidden, `${section} must keep the hidden attribute`).toBe(true);
      expect(forced[section].inlineDisplay, `${section} must keep the shell's display pin`).toBe('none');
      expect(forced[section].width, `${section} must not be visible under a forced display value`).toBe(0);
    }
  }
  await page.evaluate(() => {
    for (const el of document.querySelectorAll('style')) {
      if (el.textContent.includes('.wh-panel { display: flex !important; }')) el.remove();
    }
  });

  // ------------------------------------------------------------------
  // AC-1: at 390x844 there is no horizontal page scroll.
  // ------------------------------------------------------------------
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/studio.html?panel=retention');
  await expect(page.locator('[data-testid="sidebar"]')).toBeVisible();
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Data retention');
  await expectNoHorizontalScroll(page);
});

test('issue769 freeform (viewer)', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });

  // Boot the production way for a role 'user' identity: the token rides
  // the URL hash (#access_token=...), /api/auth/config and /api/auth/me
  // are mocked for that user, and the hash token must reach
  // /api/auth/me as a Bearer header.
  const meAuthorizations = [];
  await page.route('**/api/**', (route) => {
    const request = route.request();
    const url = request.url();
    if (url.includes('/api/auth/config')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(AUTH_CONFIG) });
    }
    if (url.includes('/api/auth/me')) {
      const auth = request.headers()['authorization'];
      if (auth) meAuthorizations.push(auth);
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(VIEWER_ME) });
    }
    if (url.includes('/api/sources')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
  });

  // Feed keys for a non-admin: the role-hidden deep link shows Data
  // sources, and the page still renders.
  await page.goto('/studio.html?panel=feedkeys#access_token=' + encodeURIComponent(VIEWER_TOKEN));
  await expect.poll(() => meAuthorizations).toContain('Bearer ' + VIEWER_TOKEN);

  // The page renders for a non-admin: the shell is up, the title reads
  // the tool actually shown (Data sources — Feed keys is role-hidden)...
  await expect(page.locator('[data-testid="sidebar"]')).toBeVisible();
  await expect
    .poll(async () => (await toolState(page)).title)
    .toBe('Studio \u00b7 Data sources');
  // ...Data sources is the one tool shown...
  const sources = page.locator('section.wh-panel[data-panel="sources"]');
  await expect(sources).toBeVisible();
  await expect(sources).not.toHaveAttribute('hidden');
  // ...while every other tool's container stays hidden.  The Feed keys
  // section is role-gated: it leaves the DOM entirely for a non-admin.
  await expect(page.locator('[data-panel="feedkeys"]')).toHaveCount(0);
  const viewerState = await toolState(page);
  for (const tool of TOOLS) {
    for (const section of tool.sections) {
      const st = viewerState[section];
      if (st === null) continue; // the role-removed Feed keys container
      if (tool.panel === 'sources') continue; // the shown tool
      expect(st.hidden, `${section} must carry the hidden attribute for a non-admin`).toBe(true);
      expect(st.width, `${section} must not be visible for a non-admin`).toBe(0);
    }
  }
  // aria-current="page" is on the shown tool's item (Data sources)...
  await expect(page.locator('.aidw-nav-item[data-nav-panel="sources"]')).toHaveAttribute('aria-current', 'page');
  await expect(page.locator('.aidw-nav-item[data-nav-panel="feedkeys"]')).toHaveCount(0);

  // Wait for the boot inits to reach their terminal states, then no
  // admin-only control survives for a non-admin: the role-gated
  // elements are all out of the DOM...
  await expect(page.locator('#sources')).toContainText(/No sources yet/);
  await expect(page.locator('[data-testid="sequences-empty"]')).toHaveText(/No load sequences yet/);
  await expect(page.locator('[data-testid="retention-policies-empty"]')).toHaveText('No retention policies yet.');
  await expect(page.locator('[data-requires-role="admin"]')).toHaveCount(0);
  // ...and the Data sources tool itself is readable (its read-only
  // list rendered) even though its Add form is gone.
  await expect(page.locator('#source-form')).toHaveCount(0);
  await expect(page.locator('#sources')).toBeVisible();

  // Switching tools works for the non-admin too, without a page load.
  await page.evaluate(() => { window.__issue769ViewerMarker = 'alive'; });
  await page.click('.aidw-nav-item[data-nav-panel="sequences"]');
  expect(await page.evaluate(() => window.__issue769ViewerMarker)).toBe('alive');
  await expect(page.locator('.aidw-page-title')).toHaveText('Studio \u00b7 Load sequences');
  // The Load sequences tool shows both of its sections for the
  // non-admin as well.
  await expectOnlyTool(page, TOOLS.find((t) => t.panel === 'sequences'));
  await expectNoDocumentScroll(page);
});
