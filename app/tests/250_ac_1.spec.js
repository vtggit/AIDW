// End-to-end: the Process wizard (Path B) authoring flow in a real browser — against
// MOCKED /api/** responses, no backend. Every /api/** request the page makes is
// intercepted with page.route BEFORE page.goto (the pattern suggestions.spec.js and
// issue767.spec.js use), so the spec never creates data through a live API: it drives
// the REAL UI on /studio.html?panel=wizard against a stateful in-memory mock of the
// wizard's endpoints (process-definitions, process-steps, sequence-flows, generate),
// recording every request (method, path, Authorization header, JSON body) and every
// response (status, shape). Proven:
//   • the wizard's definitions, steps, flows and diagram regions are present and the
//     module bound;
//   • creating a definition sends POST /api/process-definitions with the form's JSON
//     body (the Bearer dev token — the app's dev bootstrap auto-logs in, as the
//     original proof documented) and shows the new definition's card;
//   • each step and flow goes out as a POST with its authored JSON body and renders
//     into its region;
//   • Generate sends POST /api/process-definitions/<id>/generate and renders the
//     server's SVG diagram with its shapes; the download buttons arm.
// Mirrors the conventions of suggestions.spec.js.
const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


const BASE = (process.env.BASE_URL || 'http://localhost:8080').replace(/\/+$/, '');
const TOKEN = 'dev-secret-token:admin';
const MARK = `wz${Date.now()}`; // unique per run so assertions never collide with existing rows
const NOW = '2026-10-11T00:00:00+00:00';

const AUTH_CONFIG = { authEnabled: true, authMode: 'development' };
const ADMIN_ME = { authenticated: true, user: { id: 1, username: 'admin', roles: ['admin'] } };

// The server's diagram for the generated process: start circle, user-task rect, end
// circle — one shape per authored step.
const DIAGRAM_SVG = [
    '<svg xmlns="http://www.w3.org/2000/svg" width="460" height="140" viewBox="0 0 460 140">',
    '  <circle cx="40" cy="70" r="16" fill="#2e7d32" stroke="#1b5e20" stroke-width="2"/>',
    '  <line x1="56" y1="70" x2="160" y2="70" stroke="#37474f" stroke-width="2"/>',
    '  <rect x="160" y="40" width="140" height="60" rx="6" fill="#1565c0" stroke="#0d47a1" stroke-width="2"/>',
    '  <line x1="300" y1="70" x2="394" y2="70" stroke="#37474f" stroke-width="2"/>',
    '  <circle cx="414" cy="70" r="18" fill="none" stroke="#c62828" stroke-width="5"/>',
    '  <text x="230" y="74" font-family="sans-serif" font-size="12" text-anchor="middle" fill="#ffffff">Review</text>',
    '</svg>',
].join('');

async function installRoutes(page) {
    // Stateful wizard store: creates append, lists return the stored rows (the UI filters
    // by process_definition_id client-side, like the real API's global lists).
    const definitions = [];
    const steps = [];
    const flows = [];
    const requests = [];  // every /api request:  { method, path, auth, body }
    const responses = []; // every mocked /api response: { method, path, status, body }

    const record = (request) => {
        let body = null;
        const raw = request.postData();
        if (raw) {
            try { body = JSON.parse(raw); } catch { body = raw; }
        }
        requests.push({
            method: request.method(),
            path: new URL(request.url()).pathname,
            auth: request.headers()['authorization'] || null,
            body,
        });
    };

    const fulfill = (route, status, payload) => {
        const request = route.request();
        responses.push({
            method: request.method(),
            path: new URL(request.url()).pathname,
            status,
            body: payload,
        });
        return route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(payload) });
    };

    const bodyOf = (request) => {
        const raw = request.postData();
        return raw ? JSON.parse(raw) : {};
    };

    let counter = 0;
    const nextId = (prefix) => `${prefix}-${++counter}`;

    await page.route('**/api/**', (route) => {
        const request = route.request();
        const url = new URL(request.url());
        const method = request.method();
        record(request);

        if (url.pathname === '/api/auth/config') return fulfill(route, 200, AUTH_CONFIG);
        if (url.pathname === '/api/auth/me') {
            // The dev backend only answers the development admin token; anything else is
            // an honest 401 (the seeded token above means every call carries it).
            if (request.headers()['authorization'] !== `Bearer ${TOKEN}`)
                return fulfill(route, 401, { detail: 'Not authenticated' });
            return fulfill(route, 200, ADMIN_ME);
        }

        if (url.pathname === '/api/process-definitions') {
            if (method === 'GET') return fulfill(route, 200, definitions);
            const body = bodyOf(request);
            const def = {
                id: nextId('def'), name: body.name, process_key: body.process_key,
                version: '1', status: 'draft', created_at: NOW, updated_at: NOW,
            };
            definitions.push(def);
            return fulfill(route, 201, def);
        }
        const gen = url.pathname.match(/^\/api\/process-definitions\/([^/]+)\/generate$/);
        if (method === 'POST' && gen) {
            const def = definitions.find((d) => d.id === gen[1]);
            if (!def) return fulfill(route, 404, { detail: 'process definition not found' });
            return fulfill(route, 200, {
                process_key: def.process_key,
                bpmn_xml: `<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL" id="${MARK}_bpmn"><bpmn:process id="${def.process_key}" isExecutable="false"/></bpmn:definitions>`,
                svg: DIAGRAM_SVG,
            });
        }
        if (url.pathname === '/api/process-steps') {
            if (method === 'GET') return fulfill(route, 200, steps);
            const body = bodyOf(request);
            const step = {
                id: nextId('step'),
                process_definition_id: body.process_definition_id,
                name: body.name,
                step_key: body.step_key,
                ordinal: body.ordinal,
                step_type: body.step_type,
                service_impl: body.service_impl,
                candidate_groups: body.candidate_groups,
                form_key: body.form_key,
                created_at: NOW,
            };
            steps.push(step);
            return fulfill(route, 201, step);
        }
        if (url.pathname === '/api/sequence-flows') {
            if (method === 'GET') return fulfill(route, 200, flows);
            const body = bodyOf(request);
            const flow = {
                id: nextId('flow'),
                process_definition_id: body.process_definition_id,
                name: body.name,
                flow_key: body.flow_key,
                source_step: body.source_step,
                target_step: body.target_step,
                condition_expression: body.condition_expression,
                is_default: body.is_default,
                created_at: NOW,
                updated_at: NOW,
            };
            flows.push(flow);
            return fulfill(route, 201, flow);
        }
        return fulfill(route, 200, []);

    });

    return { definitions, steps, flows, requests, responses };
}

test('250_ac_1_data_source', async ({ page }) => {
    const mock = await installRoutes(page);
    // The page's own development admin token, seeded before load: it is what the app's
    // dev bootstrap would log in with anyway (warehouse.js _ensureAuth), and it makes the
    // boot deterministic — /api/auth/me answers it before any module reads the auth state
    // (the mocked /api/auth/me answers only for that Bearer header).
    await page.addInitScript((t) => { window.sessionStorage.setItem('aicrm_token', t); }, TOKEN);
    await page.goto(BASE + '/studio.html?panel=wizard');

    // The wizard section rendered and the module bound (containers exist; empties are
    // zero-height, so presence is asserted via attachment and the controls via visibility).
    await expect(page.locator('[data-testid="wizard-definitions"]')).toBeAttached();
    await expect(page.locator('[data-testid="wizard-steps"]')).toBeAttached();
    await expect(page.locator('[data-testid="wizard-flows"]')).toBeAttached();
    await expect(page.locator('[data-testid="wizard-svg"]')).toBeAttached();
    await expect(page.locator('#wizard-create-def-btn')).toBeVisible();
    await expect(page.locator('[data-testid="wizard-generate"]')).toBeVisible();

    // Create a definition and select its card.
    await page.fill('#wizard-def-name', `Demo process ${MARK}`);
    await page.fill('#wizard-def-key', `${MARK}_proc`);
    await page.click('#wizard-create-def-btn');

    // the create request: POST /api/process-definitions, the Bearer dev token, the form's JSON
    const defReq = mock.requests.find((r) => r.method === 'POST' && r.path === '/api/process-definitions');
    expect(defReq).toBeTruthy();
    expect(defReq.auth).toBe(`Bearer ${TOKEN}`);
    expect(defReq.body).toEqual({ name: `Demo process ${MARK}`, process_key: `${MARK}_proc` });
    // the response shape: an entity the card renders (id, name, key, version, status)
    const defResp = mock.responses.find((r) => r.method === 'POST' && r.path === '/api/process-definitions');
    expect(defResp.status).toBe(201);
    expect(defResp.body.id).toBeTruthy();
    expect(defResp.body.name).toBe(`Demo process ${MARK}`);
    expect(defResp.body.process_key).toBe(`${MARK}_proc`);

    const card = page.locator('#wizard-definitions .wizard-card', { hasText: MARK });
    await expect(card).toBeVisible();
    await card.click();
    const defId = mock.definitions[0].id;

    // Three steps: start, user, end — distinct step keys.
    const steps = [
        { name: 'Start', key: `${MARK}_start`, ordinal: '1', type: 'start' },
        { name: 'Review', key: `${MARK}_review`, ordinal: '2', type: 'user' },
        { name: 'Done', key: `${MARK}_end`, ordinal: '3', type: 'end' },
    ];
    for (const s of steps) {
        await page.fill('#wizard-step-name', s.name);
        await page.fill('#wizard-step-key', s.key);
        await page.fill('#wizard-step-ordinal', s.ordinal);
        await page.selectOption('#wizard-step-type', s.type);
        await page.click('#wizard-create-step-btn');
        // the steps list refresh also rebuilds the flow selects — wait for the option
        await expect(page.locator(`#wizard-flow-source option[value="${s.key}"]`)).toBeAttached();
        // each step went out as POST /api/process-steps with its authored JSON body
        const stepReq = mock.requests.find(
            (r) => r.method === 'POST' && r.path === '/api/process-steps' && r.body && r.body.step_key === s.key
        );
        expect(stepReq).toBeTruthy();
        expect(stepReq.auth).toBe(`Bearer ${TOKEN}`);
        expect(stepReq.body).toEqual({
            process_definition_id: defId,
            name: s.name,
            step_key: s.key,
            ordinal: Number(s.ordinal),
            step_type: s.type,
            service_impl: null,
            candidate_groups: null,
            form_key: null,
        });
    }

    // Two flows: start -> user, user -> end.
    const flows = [
        { name: 'to review', key: `${MARK}_f1`, from: `${MARK}_start`, to: `${MARK}_review` },
        { name: 'to done', key: `${MARK}_f2`, from: `${MARK}_review`, to: `${MARK}_end` },
    ];
    for (const f of flows) {
        await page.fill('#wizard-flow-name', f.name);
        await page.fill('#wizard-flow-key', f.key);
        await page.selectOption('#wizard-flow-source', f.from);
        await page.selectOption('#wizard-flow-target', f.to);
        await page.click('#wizard-create-flow-btn');
        await expect(page.locator('#wizard-flows .wizard-row', { hasText: f.key })).toBeVisible();
        // each flow went out as POST /api/sequence-flows with its authored JSON body
        const flowReq = mock.requests.find(
            (r) => r.method === 'POST' && r.path === '/api/sequence-flows' && r.body && r.body.flow_key === f.key
        );
        expect(flowReq).toBeTruthy();
        expect(flowReq.auth).toBe(`Bearer ${TOKEN}`);
        expect(flowReq.body).toEqual({
            process_definition_id: defId,
            name: f.name,
            flow_key: f.key,
            source_step: f.from,
            target_step: f.to,
            condition_expression: null,
            is_default: false,
        });
    }

    // Generate: the server returns {process_key, bpmn_xml, svg}; the SVG lands inline.
    await page.click('[data-testid="wizard-generate"]');

    // the generate request: POST for the selected definition, no JSON body
    const genReq = mock.requests.find((r) => r.method === 'POST' && r.path === `/api/process-definitions/${defId}/generate`);
    expect(genReq).toBeTruthy();
    expect(genReq.auth).toBe(`Bearer ${TOKEN}`);
    expect(genReq.body).toBeNull();
    // the response shape: the staged artifacts the download buttons arm from
    const genResp = mock.responses.find((r) => r.method === 'POST' && r.path === `/api/process-definitions/${defId}/generate`);
    expect(genResp.status).toBe(200);
    expect(genResp.body.process_key).toBe(`${MARK}_proc`);
    expect(genResp.body.bpmn_xml).toContain(`<bpmn:process id="${MARK}_proc"`);
    expect(genResp.body.svg).toContain('<svg');

    const svg = page.locator('[data-testid="wizard-svg"] svg');
    await expect(svg).toBeVisible({ timeout: 15000 });

    // One shape per step (rect/circle/polygon) — at least the three we authored.
    const shapeCount = await svg.locator('rect, circle, polygon').count();
    expect(shapeCount).toBeGreaterThanOrEqual(3);

    // The staged artifacts armed the download buttons.
    await expect(page.locator('#wizard-download-xml')).toBeEnabled();
    await expect(page.locator('#wizard-download-svg')).toBeEnabled();
});
