// Served-app Playwright spec (no backend): the Dashboards main region is a split
// pane (AIDW#773). Every /api/** endpoint the page needs is mocked with page.route
// BEFORE page.goto, so the spec never creates data through a live API — it drives
// only the DOM: the tile grid on the left, and the drill-down detail pane that
// opens to its right. Proven behaviours:
//   • a tile click opens the pane to the RIGHT of the grid (pane left edge at or
//     beyond the grid's right edge), aria-current="true" on the tile, and the
//     document's scroll position unchanged;
//   • the ?item= deeplink opens the same way;
//   • Close (label "Close", no glyph) hides the pane, clears aria-current and gives
//     the grid the full width back;
//   • the data table sits in a card whose header stays in place while #drilldown-
//     body scrolls (200 rows);
//   • at 1440x900 with 24 tiles the document does not scroll — the grid and the
//     pane body scroll on their own;
//   • at 390x844 the pane stacks under the grid at full width with no horizontal
//     page scroll;
//   • a hostile tile title (<img ... onerror>) renders as text in the pane and
//     never executes;
//   • a stale /data response (a slower item, or an item closed before its
//     response lands) never overwrites the pane's content for another item or
//     its state;
//   • numeric values with thousands separators ("1,234") render as grouped
//     digits, and non-numeric values render as text — never dropped.
const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


const BASE = (process.env.BASE_URL || 'http://localhost:8080').replace(/\/+$/, '');
const TOKEN = 'dev-secret-token:admin';

const DASH_ID = 'dash-773';
const BIG_ID = 'big-200';
const XSS_ID = 'xss-tile';
const XSS_TITLE = '<img src=x onerror=window.__pwned=1>';
// tile-03 answers SLOW (superseded-response race), tile-04 carries the value
// battery for _fmt (thousands separators, plain numbers, text).
const SLOW_ID = 'tile-03';
const FMT_ID = 'tile-04';
const SLOW_MS = 800;
const ROWS = 200;
const TILE_COUNT = 24;

function dataFor(id) {
  if (id === BIG_ID) {
    return {
      title: 'Big 200',
      source: 'landed',
      total_rows: 5120,
      refreshed_at: '2026-10-11T06:00:00Z',
      item_type: 'bar',
      dimension: 'region',
      aggregation: 'count',
      measure: 'orders',
      sample_size: 250,
      series: Array.from({ length: ROWS }, (_, i) => ({
        label: 'row-' + String(i + 1).padStart(3, '0'),
        value: ((i * 37) % 97) + 1,
      })),
    };
  }
  if (id === XSS_ID) {
    return {
      title: XSS_TITLE,
      source: 'live',
      item_type: 'kpi',
      aggregation: 'count',
      measure: 'rows',
      sample_size: 10,
      series: [{ label: 'value', value: 7 }],
    };
  }
  if (id === SLOW_ID) {
    // Distinct row count (7) so a superseded response landing late is visible
    // in the table, not just in the title.
    return {
      title: 'Slow 773',
      source: 'live',
      item_type: 'bar',
      dimension: 'region',
      aggregation: 'count',
      measure: 'orders',
      sample_size: 250,
      series: Array.from({ length: 7 }, (_, i) => ({
        label: 'slow-' + String(i + 1),
        value: i + 1,
      })),
    };
  }
  if (id === FMT_ID) {
    return {
      title: 'Thousands',
      source: 'live',
      item_type: 'kpi',
      aggregation: 'count',
      measure: 'rows',
      sample_size: 10,
      series: [
        { label: 'with-separators', value: '1,234' },
        { label: 'plain-number', value: 1234567 },
        { label: 'text-value', value: 'N/A' },
      ],
    };
  }
  return {
    title: 'Tile ' + id,
    source: 'live',
    item_type: 'bar',
    dimension: 'region',
    aggregation: 'count',
    measure: 'orders',
    sample_size: 250,
    series: [
      { label: 'north', value: 4 },
      { label: 'south', value: 9 },
      { label: 'east', value: 2 },
    ],
  };
}

function itemIds() {
  const ids = [BIG_ID, XSS_ID];
  for (let i = 3; i <= TILE_COUNT; i += 1) ids.push('tile-' + String(i).padStart(2, '0'));
  return ids;
}

async function installRoutes(page) {
  // Catch-all registered FIRST so it never shadows the specific mocks below
  // (Playwright checks the most recently registered route first).
  await page.route('**/api/**', (route) =>
    route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));

  await page.route(`${BASE}/api/auth/config`, (route) =>
    route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify({ authEnabled: true, authMode: 'development' }),
    }));

  await page.route(`${BASE}/api/auth/me`, (route) =>
    route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify({
        authenticated: true,
        user: { username: 'admin', sub: 'admin', roles: ['admin'] },
      }),
    }));

  await page.route(`${BASE}/api/dashboards`, (route) =>
    route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify([{ id: DASH_ID, name: 'Operations', grid_columns: 2 }]),
    }));

  await page.route(`${BASE}/api/dashboard-items`, (route) =>
    route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify(itemIds().map((id, i) => ({
        id,
        dashboard_id: DASH_ID,
        title: dataFor(id).title,
        item_type: dataFor(id).item_type,
        position: i + 1,
      }))),
    }));

  await page.route(`${BASE}/api/dashboard-item-layouts`, (route) =>
    route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));

  // Per-item data: one route, the payload chosen from the id in the URL.
  await page.route(`${BASE}/api/dashboard-items/*/data`, (route) => {
    const m = route.request().url().match(/dashboard-items\/([^/]+)\/data/);
    const id = m ? decodeURIComponent(m[1]) : '';
    route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify(dataFor(id)),
    });
  });

  // The slow item: its /data response lands SLOW_MS late — after a faster item
  // has already been opened (superseded) or the pane has been closed.
  await page.route(`${BASE}/api/dashboard-items/${SLOW_ID}/data`, (route) => {
    setTimeout(() => {
      route.fulfill({
        status: 200,
        contentType: 'application/json',
        body: JSON.stringify(dataFor(SLOW_ID)),
      });
    }, SLOW_MS);
  });
}

// Wait until every tile chart has left its "Loading data…" placeholder.
async function waitChartsSettled(page) {
  await expect
    .poll(async () =>
      (await page.locator('[data-testid="chart"] [data-testid="chart-note"]').allTextContents())
        .filter((t) => t.trim().startsWith('Loading')).length,
      { timeout: 15000 })
    .toBe(0);
}

test('issue773 freeform', async ({ page }) => {
  await installRoutes(page);
  await page.addInitScript((t) => { window.sessionStorage.setItem('aicrm_token', t); }, TOKEN);

  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('/');

  // Boot to a terminal state: admin identity + all 24 tiles rendered with filled charts.
  await page.waitForFunction(() => Auth.isAdmin() === true);
  await expect(page.locator('[data-testid="dashboard-item"]')).toHaveCount(TILE_COUNT);
  await waitChartsSettled(page);

  // ── Baseline (pane closed): at 1440x900 the document does not scroll ──
  const baseline = await page.evaluate(() => ({
    scrollY: window.scrollY,
    docScrollHeight: document.documentElement.scrollHeight,
    gridWidth: document.getElementById('dashboards').getBoundingClientRect().width,
    gridScrolls: (() => {
      const g = document.getElementById('dashboards');
      return g.scrollHeight > g.clientHeight;
    })(),
  }));
  expect(baseline.scrollY).toBe(0);
  expect(baseline.docScrollHeight).toBeLessThanOrEqual(900);
  // 24 tiles overflow the grid: it scrolls on its own.
  expect(baseline.gridScrolls).toBe(true);

  // ── Tile click: the pane opens to the RIGHT of the grid ──
  const bigTile = page.locator(`[data-testid="dashboard-item"][data-id="${BIG_ID}"]`);
  await bigTile.click();

  await expect(page.locator('#drilldown')).toBeVisible();
  await expect(
    page.locator('#drilldown-body [data-testid="drilldown-table"] tbody tr')
  ).toHaveCount(ROWS, { timeout: 15000 });

  const openGeom = await page.evaluate(() => {
    const dd = document.getElementById('drilldown').getBoundingClientRect();
    const g = document.getElementById('dashboards').getBoundingClientRect();
    const body = document.getElementById('drilldown-body');
    return {
      paneLeft: dd.left,
      gridRight: g.right,
      gridWidth: g.width,
      scrollY: window.scrollY,
      docScrollHeight: document.documentElement.scrollHeight,
      bodyScrolls: body.scrollHeight > body.clientHeight,
    };
  });
  // The pane sits beside the grid, never overlapping it.
  expect(openGeom.paneLeft).toBeGreaterThanOrEqual(openGeom.gridRight);
  // The document did not move.
  expect(openGeom.scrollY).toBe(baseline.scrollY);
  expect(openGeom.scrollY).toBe(0);
  expect(openGeom.docScrollHeight).toBeLessThanOrEqual(900);
  // The 200-row table overflows the pane body: it scrolls on its own.
  expect(openGeom.bodyScrolls).toBe(true);
  // The opened tile is marked, and the grid gave up the pane's width.
  await expect(bigTile).toHaveAttribute('aria-current', 'true');
  expect(openGeom.gridWidth).toBeLessThan(baseline.gridWidth);

  // The landed provenance line formats its number with separators.
  await expect(page.locator('#drilldown-body .dd-provenance'))
    .toHaveText('5,120 rows · refreshed 2026-10-11T06:00:00Z');

  // ── Sticky header while #drilldown-body scrolls (200 rows) ──
  const sticky = await page.evaluate(() => {
    const body = document.getElementById('drilldown-body');
    const thTop = () =>
      document.querySelector('#drilldown-body .dd-table thead th').getBoundingClientRect().top;
    const bodyTop = () => body.getBoundingClientRect().top;
    body.scrollTop = 1000;
    const a = { th: thTop(), bodyTop: bodyTop(), st: body.scrollTop };
    body.scrollTop = body.scrollHeight;
    const b = { th: thTop(), bodyTop: bodyTop(), st: body.scrollTop };
    body.scrollTop = 0;
    return { a, b };
  });
  // The body really scrolled, and the header stayed pinned at the same place.
  expect(sticky.b.st).toBeGreaterThan(sticky.a.st);
  expect(Math.abs(sticky.b.th - sticky.a.th)).toBeLessThanOrEqual(1);
  // Pinned at the top of the pane body's scrollport (not its natural position).
  expect(sticky.a.th - sticky.a.bodyTop).toBeGreaterThanOrEqual(0);
  expect(sticky.a.th - sticky.a.bodyTop).toBeLessThan(40);

  // ── Close: hides the pane, clears aria-current, grid back to full width ──
  await expect(page.locator('#drilldown-close')).toHaveText('Close');
  await page.locator('#drilldown-close').click();
  await expect(page.locator('#drilldown')).toBeHidden();
  expect(await page.locator('.wh-item[aria-current]').count()).toBe(0);
  const closedWidth = await page.evaluate(() =>
    document.getElementById('dashboards').getBoundingClientRect().width);
  expect(closedWidth).toBeGreaterThanOrEqual(baseline.gridWidth - 2);
  expect(closedWidth).toBeGreaterThan(openGeom.gridWidth + 100);

  // ── Stale response, wrong item: open the slow item, immediately open a
  //    faster one; the slow response lands late and must be dropped ──
  const slowTile = page.locator(`[data-testid="dashboard-item"][data-id="${SLOW_ID}"]`);
  const fmtTile = page.locator(`[data-testid="dashboard-item"][data-id="${FMT_ID}"]`);
  await slowTile.click();
  await fmtTile.click();

  await expect(page.locator('#drilldown')).toBeVisible();
  await expect(page.locator('#drilldown-body h3')).toHaveText('Thousands', { timeout: 15000 });
  await expect(fmtTile).toHaveAttribute('aria-current', 'true');
  expect(await slowTile.getAttribute('aria-current')).toBeNull();

  // Wait past SLOW_MS so the superseded response is guaranteed to have
  // ARRIVED (and been dropped): the pane still shows the current item, with
  // the current item's rows (3), not the stale item's 7.
  await page.waitForTimeout(SLOW_MS + 400);
  await expect(page.locator('#drilldown-body h3')).toHaveText('Thousands');
  await expect(
    page.locator('#drilldown-body [data-testid="drilldown-table"] tbody tr')
  ).toHaveCount(3);
  await expect(fmtTile).toHaveAttribute('aria-current', 'true');

  // ── Stale response after Close: the late response must not refill the
  //    hidden pane's body or resurrect any state ──
  await slowTile.click();
  await page.locator('#drilldown-close').click();
  await expect(page.locator('#drilldown')).toBeHidden();
  expect(await page.locator('.wh-item[aria-current]').count()).toBe(0);
  await page.waitForTimeout(SLOW_MS + 400);
  await expect(page.locator('#drilldown')).toBeHidden();
  expect(
    await page.evaluate(() => document.getElementById('drilldown-body').innerHTML),
  ).toBe('');
  expect(await page.locator('.wh-item[aria-current]').count()).toBe(0);

  // ── _fmt: thousands separators, plain numbers and text all render ──
  await fmtTile.click();
  await expect(page.locator('#drilldown-body h3')).toHaveText('Thousands');
  const fmtRows = page.locator('#drilldown-body [data-testid="drilldown-table"] tbody tr');
  await expect(fmtRows).toHaveCount(3);
  // "1,234" (a string with a thousands separator) is NOT dropped or mangled.
  await expect(fmtRows.nth(0).locator('td').nth(1)).toHaveText('1,234');
  // A plain number is grouped with separators.
  await expect(fmtRows.nth(1).locator('td').nth(1)).toHaveText('1,234,567');
  // A non-numeric value is inserted as text, verbatim.
  await expect(fmtRows.nth(2).locator('td').nth(1)).toHaveText('N/A');
  await page.locator('#drilldown-close').click();
  await expect(page.locator('#drilldown')).toBeHidden();

  // ── Hostile tile title: inserted as text, never executed ──
  const xssTile = page.locator(`[data-testid="dashboard-item"][data-id="${XSS_ID}"]`);
  await xssTile.click();
  await expect(page.locator('#drilldown-body h3')).toHaveText(XSS_TITLE, { timeout: 15000 });
  // No <img> was injected anywhere in the pane; the onerror hook never fired.
  expect(await page.locator('#drilldown-body img').count()).toBe(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();
  // The grid tile shows the same value as text.
  await expect(xssTile.locator('.wh-title')).toHaveText(XSS_TITLE);
  await page.locator('#drilldown-close').click();
  await expect(page.locator('#drilldown')).toBeHidden();

  // ── ?item= deeplink: the pane opens beside the grid, no document scroll ──
  await page.goto('/?item=' + BIG_ID);
  await page.waitForFunction(() => Auth.isAdmin() === true);
  await expect(page.locator('#drilldown')).toBeVisible();
  await expect(
    page.locator('#drilldown-body [data-testid="drilldown-table"] tbody tr')
  ).toHaveCount(ROWS, { timeout: 15000 });
  await waitChartsSettled(page);

  const deepGeom = await page.evaluate(() => {
    const dd = document.getElementById('drilldown').getBoundingClientRect();
    const g = document.getElementById('dashboards').getBoundingClientRect();
    return {
      paneLeft: dd.left,
      gridRight: g.right,
      scrollY: window.scrollY,
      docScrollHeight: document.documentElement.scrollHeight,
    };
  });
  expect(deepGeom.paneLeft).toBeGreaterThanOrEqual(deepGeom.gridRight);
  await expect(bigTile).toHaveAttribute('aria-current', 'true');
  expect(deepGeom.scrollY).toBe(0);
  expect(deepGeom.docScrollHeight).toBeLessThanOrEqual(900);

  // ── 390x844: the pane stacks under the grid at full width, no h-scroll ──
  await page.setViewportSize({ width: 390, height: 844 });
  await expect
    .poll(async () =>
      page.evaluate(() => {
        const dd = document.getElementById('drilldown').getBoundingClientRect();
        const g = document.getElementById('dashboards').getBoundingClientRect();
        return dd.top >= g.bottom - 1;
      }),
      { timeout: 5000 })
    .toBe(true);

  const narrow = await page.evaluate(() => {
    const dd = document.getElementById('drilldown').getBoundingClientRect();
    const g = document.getElementById('dashboards').getBoundingClientRect();
    return { docScrollWidth: document.documentElement.scrollWidth, pane: dd, grid: g };
  });
  expect(narrow.docScrollWidth).toBeLessThanOrEqual(390);
  // Stacked below the grid, at the same (full) width.
  expect(narrow.pane.top).toBeGreaterThanOrEqual(narrow.grid.bottom - 1);
  expect(Math.abs(narrow.pane.width - narrow.grid.width)).toBeLessThanOrEqual(2);
  expect(narrow.pane.width).toBeGreaterThanOrEqual(340);
});
