'use strict';

// Proof for issue #818 — the audit panel's count line and the
// discipline of its request counter:
//   AC-1  count wording: the count line reads "1 event" for one
//         event, "N events" for any other number below 100, and
//         "Latest 100 events" for exactly 100; a failed filter
//         request empties the count line while the error note is
//         shown, and the next choice's answer refills it; the request
//         counter is never reset when the panel loads again — a filter
//         request held open across a reload is dropped once it answers
//         after a newer choice has been answered, and the reload's own
//         first load uses the counter too, so its late answer cannot
//         overwrite a newer choice's
//   Identity  the criteria concern roles, so the proof also runs as a
//         NON-ADMIN (role 'user') after a full reload, booted the
//         production way (the token in the URL hash as #access_token=...,
//         /api/auth/config and /api/auth/me mocked for that user): the
//         admin-only note is shown, no admin-only control survives and
//         no request reaches /api/audit, while the page still renders
//
// Boots /studio.html?panel=audit against mocked /api/** responses (no
// backend), signed in as an admin.  The first (unfiltered) load
// answers with four events — one 'dataset', two 'source', one
// 'pipeline' — delivered oldest first, so every choice below is a real
// entity-type request:
//   dataset  -> answered with exactly 1 event      -> "1 event"
//   source   -> answered with exactly 2 events     -> "2 events"
//   pipeline -> answered with exactly 100 events   -> "Latest 100 events"

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, or an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});
const AUTH_CONFIG = { authEnabled: true, authMode: 'development' };
const ADMIN_ME = { authenticated: true, user: { id: 1, username: 'admin', roles: ['admin'] } };
const USER_ME = { authenticated: true, user: { id: 9, username: 'user', roles: ['user'] } };
const VIEWER_TOKEN = 'viewer-token-818';

const TYPE_ONE = 'dataset'; // answered with exactly 1 event
const TYPE_TWO = 'source'; // answered with exactly 2 events
const TYPE_HUNDRED = 'pipeline'; // answered with exactly 100 events

// One minute apart: event i of the first load is BASE + i minutes.
const BASE = Date.parse('2026-10-14T09:00:00Z');

const makeEvent = (id, type, minute) => ({
  id,
  entity_type: type,
  entity_id: 'ent-' + id,
  action: 'update',
  actor_sub: 'sub-admin-0001',
  actor_username: 'admin',
  actor_email: 'admin@example.com',
  actor_roles: 'admin',
  timestamp: BASE + minute * 60000,
  details: { ref: 'evt-' + id },
});

// The first (unfiltered) load: four events, delivered OLDEST FIRST so
// the client's newest-first sort — not the mock's order — is what
// renders.  Newest first: source, pipeline, source, dataset.
const ALL_LOAD = [
  makeEvent(1, TYPE_ONE, 0),
  makeEvent(2, TYPE_TWO, 1),
  makeEvent(3, TYPE_HUNDRED, 2),
  makeEvent(4, TYPE_TWO, 3),
];

// The answer to entity_type=dataset: exactly one event.
const ONE_EVENT = [makeEvent(101, TYPE_ONE, 0)];

// The answer to entity_type=source: exactly two events.
const TWO_EVENTS = [makeEvent(201, TYPE_TWO, 0), makeEvent(202, TYPE_TWO, 1)];

// The answer to entity_type=pipeline: exactly 100 events, so a capped
// list says it is capped.
const HUNDRED_EVENTS = [];
for (let i = 0; i < 100; i++) {
  HUNDRED_EVENTS.push(makeEvent(300 + i, TYPE_HUNDRED, i));
}

function auditAnswer(url) {
  const entityType = new URL(url).searchParams.get('entity_type');
  if (entityType === null) return ALL_LOAD;
  if (entityType === TYPE_ONE) return ONE_EVENT;
  if (entityType === TYPE_TWO) return TWO_EVENTS;
  if (entityType === TYPE_HUNDRED) return HUNDRED_EVENTS;
  return [];
}

// Mock switches.
let meBody = ADMIN_ME;
let meAuthorization = [];
let auditRequests = [];
let failType = null; // an entity_type whose request answers 500
let holdFilter = null; // an entity_type whose filter request is held...
let releaseFilter = null; // ...until the test resolves it
let holdInitial = false; // the unfiltered (first-load) request is held...
let releaseInitial = null; // ...until the test resolves it

test('issue818 freeform', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });

  // Every /api/** request is mocked (no backend): auth for the signed-in
  // user, /api/audit answering per entity_type (with the fail/hold
  // switches), and every other list an empty array (Studio boot fetches
  // many lists on startup).
  await page.route('**/api/**', async (route) => {
    const request = route.request();
    const url = request.url();
    const pathname = new URL(url).pathname;
    const fulfill = (status, body) =>
      route.fulfill({ status, contentType: 'application/json', body });
    if (pathname === '/api/auth/config') {
      return fulfill(200, JSON.stringify(AUTH_CONFIG));
    }
    if (pathname === '/api/auth/me') {
      const auth = request.headers()['authorization'];
      if (auth) meAuthorization.push(auth);
      return fulfill(200, JSON.stringify(meBody));
    }
    if (pathname === '/api/audit') {
      auditRequests.push(url);
      const entityType = new URL(url).searchParams.get('entity_type');
      if (entityType !== null && entityType === failType) {
        return fulfill(500, JSON.stringify({ detail: 'audit storage unavailable' }));
      }
      if (entityType !== null && entityType === holdFilter) {
        await new Promise((resolve) => {
          releaseFilter = resolve;
        });
      }
      if (entityType === null && holdInitial) {
        await new Promise((resolve) => {
          releaseInitial = resolve;
        });
      }
      return fulfill(200, JSON.stringify(auditAnswer(url)));
    }
    return fulfill(200, '[]');
  });

  await page.goto('/studio.html?panel=audit');

  const section = page.locator('[data-panel="audit"]');
  await expect(section).toBeVisible();
  await expect(section.locator('h2')).toHaveText('Audit history');
  const rows = page.locator('[data-testid="audit-row"]');
  const count = page.locator('[data-testid="audit-count"]');
  const select = page.locator('[data-testid="audit-entity-type-filter"]');

  // the boot made exactly one, unfiltered, request through the API
  // client
  await expect.poll(() => auditRequests.length).toBe(1);
  expect(auditRequests[0], 'the boot request is GET /api/audit?limit=100').toContain(
    '/api/audit?limit=100'
  );
  expect(auditRequests[0]).not.toContain('entity_type');

  // the first load renders the four events, newest first, and the
  // count line says how many are shown
  await expect(rows).toHaveCount(4);
  await expect(count).toHaveText('4 events');

  // ------------------------------------------------------------------
  // AC-1 — count wording: "1 event" for one event, "N events" for any
  // other number below 100, "Latest 100 events" for exactly 100
  // ------------------------------------------------------------------
  await select.selectOption(TYPE_ONE);
  await expect(rows).toHaveCount(1);
  await expect(count, 'a type answered with one event reads "1 event"').toHaveText('1 event');
  expect(
    auditRequests[auditRequests.length - 1],
    'choosing a type asks for GET /api/audit?entity_type=<type>&limit=100'
  ).toContain('entity_type=dataset&limit=100');

  await select.selectOption(TYPE_TWO);
  await expect(rows).toHaveCount(2);
  await expect(count, 'a type answered with two events reads "2 events"').toHaveText('2 events');
  expect(auditRequests[auditRequests.length - 1]).toContain('entity_type=source&limit=100');

  await select.selectOption(TYPE_HUNDRED);
  await expect(rows).toHaveCount(100);
  await expect(count, 'a type answered with 100 events says it is capped').toHaveText(
    'Latest 100 events'
  );
  expect(auditRequests[auditRequests.length - 1]).toContain('entity_type=pipeline&limit=100');

  // ------------------------------------------------------------------
  // AC-1 — failed request: a failed filter request shows the error
  // note in place of the table and empties the count line; the next
  // choice's answer refills it
  // ------------------------------------------------------------------
  failType = TYPE_TWO;
  await select.selectOption(TYPE_TWO); // this request fails
  await expect(section.locator('[data-testid="audit-error"]')).toHaveText(
    'Could not load audit history.'
  );
  await expect(section.locator('[data-testid="audit-table"]')).toHaveCount(0);
  await expect(count, 'while the error note is shown the count line is empty').toHaveText('');

  await select.selectOption(TYPE_ONE); // the next choice answers
  await expect(section.locator('[data-testid="audit-error"]')).toHaveCount(0);
  await expect(rows).toHaveCount(1);
  await expect(count, "the next choice's answer refills the count line").toHaveText('1 event');
  failType = null;

  // ------------------------------------------------------------------
  // AC-1 — no stale answer after a reload: the request counter is
  // never reset when the panel loads again.  A filter request is held
  // open, the panel loads again (its own first load is held too), a
  // new choice is made and answered — then both held answers arrive,
  // and both are dropped.
  // ------------------------------------------------------------------
  holdFilter = TYPE_HUNDRED;
  const pipelineRequests = () =>
    auditRequests.filter((u) => u.includes('entity_type=pipeline')).length;
  const pipelineBefore = pipelineRequests();
  await select.selectOption(TYPE_HUNDRED); // its answer is held
  await expect.poll(pipelineRequests).toBe(pipelineBefore + 1);
  await expect(select, 'the select stays usable while a request is out').toBeEnabled();

  // the panel loads again: its own first load goes out — and is held
  holdInitial = true;
  const unfilteredRequests = () =>
    auditRequests.filter((u) => !u.includes('entity_type')).length;
  const unfilteredBefore = unfilteredRequests();
  await page.evaluate(() => {
    AuditView.init();
  });
  await expect.poll(unfilteredRequests).toBe(unfilteredBefore + 1);

  // a new choice is made and answered
  await select.selectOption(TYPE_ONE);
  await expect(rows).toHaveCount(1);
  await expect(count).toHaveText('1 event');
  expect(
    await page.evaluate(() =>
      Array.from(document.querySelectorAll('td[data-testid="audit-entity-type"]')).map(
        (td) => td.textContent
      )
    ),
    "the new choice's events are shown"
  ).toEqual(['dataset']);

  // the reload's own late first-load answer arrives: dropped
  if (typeof releaseInitial === 'function') releaseInitial();
  await page.waitForTimeout(200);
  await expect(rows, "the reload's own late answer cannot overwrite a newer choice").toHaveCount(1);
  await expect(count, "the reload's own late answer cannot overwrite a newer choice").toHaveText(
    '1 event'
  );

  // then the pre-reload held filter request answers: dropped
  if (typeof releaseFilter === 'function') releaseFilter();
  await page.waitForTimeout(200);
  await expect(rows, 'the held answer to the pre-reload choice is dropped').toHaveCount(1);
  await expect(count, 'the held answer to the pre-reload choice is dropped').toHaveText('1 event');
  expect(
    await page.evaluate(() =>
      Array.from(document.querySelectorAll('td[data-testid="audit-entity-type"]')).map(
        (td) => td.textContent
      )
    ),
    "the new choice's events are still the only ones shown"
  ).toEqual(['dataset']);
  holdFilter = null;
  holdInitial = false;

  // ------------------------------------------------------------------
  // Identity — a NON-ADMIN (role 'user') booted the production way
  // (the token in the URL hash, /api/auth/config and /api/auth/me
  // mocked for that user) sees the administrators-only note, no
  // admin-only control, and no request to /api/audit — while the page
  // still renders
  // ------------------------------------------------------------------
  meBody = USER_ME;
  meAuthorization.length = 0;
  auditRequests.length = 0;
  // A fragment-only URL change would be a same-document navigation and
  // Auth.init() would not re-run; go through about:blank so this boot
  // is a full page load, the production way.
  await page.goto('about:blank');
  await page.goto('/studio.html?panel=audit#access_token=' + encodeURIComponent(VIEWER_TOKEN));
  // the hash token was picked up the production way and sent on /auth/me
  await expect.poll(() => meAuthorization).toContain('Bearer ' + VIEWER_TOKEN);
  // the page still renders (one tool at a time)...
  await expect(page.locator('[data-testid="sidebar"]')).toBeVisible();
  await expect(page.locator('.aidw-page-title')).toHaveText('Studio \u00b7 Audit history');
  await expect(section).toBeVisible();
  // ...with the administrators-only note, no admin-only control...
  await expect(section.locator('[data-testid="audit-admin-only-note"]')).toHaveText(
    'Audit history is available to administrators.'
  );
  await expect(section.locator('[data-requires-role="admin"]')).toHaveCount(0);
  await expect(section.locator('[data-testid="audit-table"]')).toHaveCount(0);
  // ...and no request reached /api/audit
  expect(auditRequests).toHaveLength(0);
});
