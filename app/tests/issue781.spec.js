'use strict';

// Proof for issue #781 — the PII flags tool ([data-panel="pii"]) fits the
// window and its list scrolls on its own.
//
// Boots /studio.html?panel=pii against mocked /api/** responses (no backend,
// no data creation): a stateful mock answers the flag list, the dataset and
// field name maps and the POST /api/pii-flags/<id>/confirm | /dismiss
// decision endpoints, and records every request (method, path, Authorization
// header, JSON body). Proves:
//   * at 1440x900 with 300 mocked flags across 12 datasets: neither the
//     document nor the main .aidw-scroll region scrolls, only #pii-inbox
//     does; a group's sticky header (name + the dataset's pending count)
//     stays at the top of the region while its rows scroll under it, and the
//     top bar (title + #pii-count badge + category chips) stays in view
//   * each group's name and count and the total badge; each category chip's
//     count (All default, then one chip per category present) and the
//     narrowed list, with no request sent by choosing a chip
//   * Confirm and Dismiss each send their request for the right id, the row
//     leaves, the group and total counts update, an emptied group
//     disappears, the list keeps its scroll position, and no page reload
//   * both empty states: nothing pending -> centred "No PII flags to
//     review" + "Flags appear here when discovery finds personal data in a
//     source."; a chip that matches nothing -> "No flags in this category."
//   * a column named <img src=x onerror=window.__pwned=1> renders as text,
//     with window.__pwned undefined
//   * at 390x844 each row stacks its fields and the page has no horizontal
//     scroll
//
// The column labels and the chips are checked by reading each element's own
// text — never an array matcher on a single element's aggregated text.

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


const TOKEN = 'dev-secret-token:admin';
const DS_COUNT = 12;
const PER_DS = 27; // the first eleven datasets carry 27 flags each ...
const HEALTH_PER_DS = 3; // ... and the twelfth carries exactly the three health flags
const TOTAL = (DS_COUNT - 1) * PER_DS + HEALTH_PER_DS; // 300
const CATEGORIES = ['contact', 'direct_identifier', 'financial'];
const HEALTH_DS = DS_COUNT; // the three 'health' flags live in the last dataset
const HEALTH_FLAG_IDS = [0, 1, 2].map((j) => flagId(HEALTH_DS, j));
function perDataset(d) {
  return d === HEALTH_DS ? HEALTH_PER_DS : PER_DS;
}
const XSS_FIELD_INDEX = 1; // the second column of the first dataset carries the hostile name
const XSS_TITLE = '<img src=x onerror=window.__pwned=1>';

function dsId(d) {
  return 'ds-781-' + String(d).padStart(2, '0');
}
function dsName(d) {
  return 'Dataset ' + String(d).padStart(2, '0');
}
function fieldId(d, j) {
  return 'fld-781-' + String(d).padStart(2, '0') + '-' + String(j).padStart(2, '0');
}
function fieldCol(d, j) {
  return 'col_' + d + '_' + j;
}
function flagId(d, j) {
  return 'flag-781-' + String(d).padStart(2, '0') + '-' + String(j).padStart(2, '0');
}

// 300 flags across 12 datasets: 99 contact + 99 direct_identifier + 99
// financial in a global cycle over the first 297, and exactly three
// 'health' flags — all in the last dataset (whose only flags they are) — so
// that category's chip is the one that can run out and its group the one
// that can be emptied.
function makeFlags() {
  const flags = [];
  let i = 0;
  for (let d = 1; d <= DS_COUNT; d += 1) {
    for (let j = 0; j < perDataset(d); j += 1) {
      const isHealth = d === HEALTH_DS;
      flags.push({
        id: flagId(d, j),
        name: 'flag ' + fieldCol(d, j),
        dataset_id: dsId(d),
        discovered_field_id: fieldId(d, j),
        category: isHealth ? 'health' : CATEGORIES[i % CATEGORIES.length],
        detection_tier: 'schema',
        status: 'flagged',
        confidence: 0.5,
        rationale: "name token 'field'",
        fingerprint: 'fp-' + flagId(d, j),
        created_at: '2026-10-11T00:00:00+00:00',
        updated_at: '2026-10-11T00:00:00+00:00',
      });
      i += 1;
    }
  }
  return flags;
}

const DATASETS = [];
for (let d = 1; d <= DS_COUNT; d += 1) {
  DATASETS.push({ id: dsId(d), name: dsName(d), object_type: 'EntitySet', created_at: '2026-10-11T00:00:00+00:00' });
}

const FIELDS = [];
for (let d = 1; d <= DS_COUNT; d += 1) {
  for (let j = 0; j < perDataset(d); j += 1) {
    FIELDS.push({
      id: fieldId(d, j),
      name: d === 1 && j === XSS_FIELD_INDEX ? XSS_TITLE : fieldCol(d, j),
      dataset_id: dsId(d),
      created_at: '2026-10-11T00:00:00+00:00',
    });
  }
}

// Category counts for the full 300-flag set.
const CATEGORY_COUNTS = { contact: 99, direct_identifier: 99, financial: 99, health: 3 };
const CATEGORY_LABEL = { contact: 'contact', direct_identifier: 'direct identifier', financial: 'financial', health: 'health' };
// Chip order: All first, then the categories alphabetically.
const CHIP_ORDER = ['all', 'contact', 'direct_identifier', 'financial', 'health'];

