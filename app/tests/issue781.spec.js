test('issue781 freeform', async ({ page }) => {
  // Mock every /api/** request BEFORE the page boots. The web fonts are
  // aborted too, so the proof needs no external network at all.
  let flags = makeFlags();
  let piiListRequests = 0;
  const requests = []; // every /api request: { method, path, auth, body }
  const responses = []; // every mocked /api response: { method, path, status, body }
  await page.route('**/fonts.googleapis.com/**', (route) => route.abort());
  await page.route('**/fonts.gstatic.com/**', (route) => route.abort());
  await page.route('**/api/**', (route) => {
    const url = route.request().url();
    const path = new URL(url).pathname;
    const method = route.request().method();
    let body = null;
    const raw = route.request().postData();
    if (raw) {
      try { body = JSON.parse(raw); } catch { body = raw; }
    }
    requests.push({ method, path, auth: route.request().headers()['authorization'] || null, body });

    const fulfill = (status, payload) => route.fulfill({
      status,
      contentType: 'application/json',
      body: JSON.stringify(payload),
    });

    if (path === '/api/auth/config') {
      return fulfill(200, { authMode: 'development' });
    }
    if (path === '/api/auth/me') {
      return fulfill(200, { authenticated: true, user: { username: 'admin', sub: 'admin', roles: ['admin'] } });
    }
    if (path === '/api/pii-flags' && method === 'GET') {
      piiListRequests += 1;
      return fulfill(200, flags);
    }
    if (path === '/api/datasets' && method === 'GET') {
      return fulfill(200, DATASETS);
    }
    if (path === '/api/discovered-fields' && method === 'GET') {
      return fulfill(200, FIELDS);
    }
    const m = path.match(/^\/api\/pii-flags\/([^/]+)\/(confirm|dismiss)$/);
    if (m && method === 'POST') {
      const id = decodeURIComponent(m[1]);
      const f = flags.find((x) => x.id === id);
      if (!f) {
        responses.push({ method, path, status: 404, body: { detail: 'pii_flag not found' } });
        return fulfill(404, { detail: 'pii_flag not found' });
      }
      f.status = m[2] === 'confirm' ? 'confirmed' : 'dismissed';
      responses.push({ method, path, status: 200, body: f });
      return fulfill(200, f);
    }
    return fulfill(200, []);
  });
  await page.addInitScript((t) => { window.sessionStorage.setItem('aicrm_token', t); }, TOKEN);
  const bearer = 'Bearer ' + TOKEN;

  // ------------------------------------------------------------------
  // Desktop, 1440x900, 300 flags across 12 datasets.
  // ------------------------------------------------------------------
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('/studio.html?panel=pii');
  await expect(page.locator('[data-testid="pii-flag"]')).toHaveCount(TOTAL);
  await expect(page.locator('[data-testid="pii-group"]')).toHaveCount(DS_COUNT);
  expect(piiListRequests, 'one list request for the whole proof so far').toBe(1);

  // The panel fits: neither the document nor the main .aidw-scroll region
  // scrolls; #pii-inbox is the region that scrolls.
  const fit = await page.evaluate(() => {
    const doc = document.documentElement;
    const region = document.querySelector('[data-testid="main-content"]');
    const inbox = document.getElementById('pii-inbox');
    return {
      doc: doc.scrollHeight - doc.clientHeight,
      body: document.body.scrollHeight - document.body.clientHeight,
      winY: window.scrollY,
      regionDelta: region.scrollHeight - region.clientHeight,
      inboxScrollable: inbox.scrollHeight > inbox.clientHeight,
      inboxHeight: inbox.clientHeight,
    };
  });
  expect(fit.doc, 'document must not scroll').toBeLessThanOrEqual(0);
  expect(fit.body, 'document body must not scroll').toBeLessThanOrEqual(0);
  expect(fit.winY, 'window must not be scrolled').toBe(0);
  expect(fit.regionDelta, 'main .aidw-scroll region must not scroll').toBeLessThanOrEqual(0);
  expect(fit.inboxScrollable, '#pii-inbox must be the scrolling region').toBe(true);
  expect(fit.inboxHeight).toBeGreaterThan(0);

  // The total badge counts every pending flag.
  await expect(page.locator('#pii-count')).toHaveText(String(TOTAL));

  // Every group (not just the first): its own header text carries the
  // dataset name and the dataset's pending count.
  for (let d = 1; d <= DS_COUNT; d += 1) {
    const head = page.locator(`[data-testid="pii-group"][data-id="${dsId(d)}"] [data-testid="pii-group-head"]`);
    expect(await head.locator('.wh-pii-group-name').textContent(), `group ${d} name`).toBe(dsName(d));
    expect(await head.locator('[data-testid="pii-group-count"]').textContent(), `group ${d} count`).toBe(String(perDataset(d)));
    expect(await head.textContent(), `group ${d} header own text`).toContain(dsName(d));
  }

  // Every flag (not just the first) is one compact row at least 52 px tall,
  // keeping data-testid="pii-flag" + data-id, showing the column name and
  // the category, and carrying both action buttons with data-action +
  // data-id. All 300 boxes are read in one in-page pass rather than through
  // per-element box-model round trips.
  const firstRow = page.locator('[data-testid="pii-flag"]').first();
  const rowBoxes = await page.evaluate(() =>
    Array.from(document.querySelectorAll('[data-testid="pii-flag"]')).map((el) => el.getBoundingClientRect().height));
  expect(rowBoxes.length, 'every row was measured').toBe(TOTAL);
  expect(Math.min(...rowBoxes), 'every row must be at least 52 px tall').toBeGreaterThanOrEqual(52);
  expect(await firstRow.getAttribute('data-id')).toBe(flags[0].id);
  const firstField = firstRow.locator('[data-testid="pii-field"]');
  const firstCat = firstRow.locator('[data-testid="pii-category"]');
  await expect(firstField).toHaveCount(1);
  await expect(firstCat).toHaveCount(1);
  expect(await firstField.textContent()).toBe(fieldCol(1, 0));
  expect(await firstCat.textContent()).toBe(CATEGORY_LABEL[CATEGORIES[0]]);
  const confirmBtn = firstRow.locator('[data-action="pii-confirm"]');
  const dismissBtn = firstRow.locator('[data-action="pii-dismiss"]');
  await expect(confirmBtn).toHaveCount(1);
  await expect(dismissBtn).toHaveCount(1);
  expect(await confirmBtn.getAttribute('data-id')).toBe(flags[0].id);
  expect(await dismissBtn.getAttribute('data-id')).toBe(flags[0].id);

  // The category chips: All (the default, pressed) first, then one chip per
  // category present — each chip's own text carries its label and count.
  const chips = page.locator('[data-testid="pii-filters"] .wh-pii-chip');
  expect(await chips.count(), 'five chips: All + one per category present').toBe(5);
  for (let i = 0; i < CHIP_ORDER.length; i += 1) {
    const key = CHIP_ORDER[i];
    const chip = chips.nth(i);
    expect(await chip.getAttribute('data-pii-filter')).toBe(key);
    const expectedText = key === 'all' ? 'All ' + TOTAL : CATEGORY_LABEL[key] + ' ' + CATEGORY_COUNTS[key];
    expect(await chip.textContent(), `chip "${key}" own text`).toBe(expectedText);
    expect(await chip.getAttribute('aria-pressed'), `chip "${key}" pressed state`).toBe(key === 'all' ? 'true' : 'false');
  }
  expect(await page.locator('#pii-count').textContent()).toBe(String(TOTAL));

  // A column named like an image tag renders as text; nothing executes.
  const xssRow = page.locator(`[data-testid="pii-flag"][data-id="${flagId(1, XSS_FIELD_INDEX)}"]`);
  await expect(xssRow.locator('[data-testid="pii-field"]')).toHaveText(XSS_TITLE);
  expect(await xssRow.locator('img').count()).toBe(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();

  // A group's sticky header stays at the top of the region while its rows
  // scroll under it (and the top bar stays in view). One evaluate performs
  // the scroll and reads every box in the same frame.
  const sticky = await page.evaluate((targetId) => {
    const inbox = document.getElementById('pii-inbox');
    const target = document.querySelector(`[data-testid="pii-flag"][data-id="${targetId}"]`);
    const group = target.closest('[data-testid="pii-group"]');
    const head = group.querySelector('[data-testid="pii-group-head"]');
    const firstRow = group.querySelector('[data-testid="pii-flag"]');
    const headOffset = head.getBoundingClientRect().top - inbox.getBoundingClientRect().top + inbox.scrollTop;
    inbox.scrollTop = headOffset + firstRow.getBoundingClientRect().height * 3 + 10;
    const r = (el) => { const b = el.getBoundingClientRect(); return { top: b.top, bottom: b.bottom, y: b.y }; };
    return {
      scrollTop: inbox.scrollTop,
      head: r(head),
      inbox: r(inbox),
      firstRow: r(firstRow),
      topbar: r(document.querySelector('[data-testid="pii-topbar"]')),
      viewportH: window.innerHeight,
    };
  }, flagId(6, 0));
  expect(sticky.scrollTop, '#pii-inbox must actually scroll').toBeGreaterThan(0);
  expect(sticky.head.top, 'the group header must pin to the top of the region')
    .toBeCloseTo(sticky.inbox.top, 0);
  expect(sticky.head.bottom, 'the group header must stay in view').toBeLessThanOrEqual(sticky.viewportH);
  expect(sticky.firstRow.y, 'the group rows must scroll under the pinned header')
    .toBeLessThan(sticky.inbox.top);
  expect(sticky.topbar.top, 'the top bar must stay in view').toBeGreaterThanOrEqual(0);
  expect(sticky.topbar.bottom, 'the top bar must stay in view').toBeLessThanOrEqual(sticky.viewportH);

  // ------------------------------------------------------------------
  // The category chips narrow the list client-side: no request is sent.
  // ------------------------------------------------------------------
  await page.evaluate(() => { document.getElementById('pii-inbox').scrollTop = 0; });
  await page.click('[data-testid="pii-filter-health"]');
  await expect(page.locator('[data-testid="pii-flag"]')).toHaveCount(CATEGORY_COUNTS.health);
  await expect(page.locator('[data-testid="pii-group"]')).toHaveCount(1);
  await expect(page.locator('[data-testid="pii-group"]')).toHaveAttribute('data-id', dsId(HEALTH_DS));
  const healthCats = await page.locator('[data-testid="pii-flag"] [data-testid="pii-category"]').allTextContents();
  expect(healthCats.every((t) => t === 'health')).toBe(true);
  await expect(page.locator('[data-testid="pii-filter-health"]')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('[data-testid="pii-filter-all"]')).toHaveAttribute('aria-pressed', 'false');
  await expect(page.locator('#pii-count')).toHaveText(String(TOTAL)); // the badge counts ALL pending, not the filter
  expect(piiListRequests, 'choosing a chip must not send a request').toBe(1);

  // ------------------------------------------------------------------
  // Acting on a flag: Confirm and Dismiss send their request for the right
  // id, the row leaves, the counts update, an emptied group disappears and
  // the list keeps its scroll position — with no page reload.
  // ------------------------------------------------------------------
  await page.click('[data-testid="pii-filter-all"]');
  await expect(page.locator('[data-testid="pii-flag"]')).toHaveCount(TOTAL);
  expect(piiListRequests, 'choosing a chip must not send a request').toBe(1);
  await page.evaluate(() => { window.__issue781Marker = 'alive'; });

  // Scroll the list to a middle position so a visible row can be acted on,
  // and remember the scroll position.
  const confirmTargetId = flagId(6, 0);
  const scrollBefore = await page.evaluate((targetId) => {
    const inbox = document.getElementById('pii-inbox');
    const target = document.querySelector(`[data-testid="pii-flag"][data-id="${targetId}"]`);
    const delta = target.getBoundingClientRect().top - inbox.getBoundingClientRect().top;
    inbox.scrollTop += delta - 120; // the target row sits 120 px below the region's top
    return inbox.scrollTop;
  }, confirmTargetId);
  expect(scrollBefore, 'the list must be scrolled before acting').toBeGreaterThan(0);

  // Confirm: the request goes out for the right flag id, the row leaves, the
  // group and the total counts update, and the scroll position is kept.
  await page.locator(`[data-testid="pii-flag"][data-id="${confirmTargetId}"] [data-action="pii-confirm"]`).click();
  await expect(page.locator(`[data-testid="pii-flag"][data-id="${confirmTargetId}"]`)).toHaveCount(0);
  const confirmReq = requests.find((r) => r.path === `/api/pii-flags/${confirmTargetId}/confirm`);
  expect(confirmReq, 'confirm request for the right id').toBeTruthy();
  expect(confirmReq.method).toBe('POST');
  expect(confirmReq.auth).toBe(bearer);
  expect(confirmReq.body).toBeNull();
  const confirmResp = responses.find((r) => r.path === `/api/pii-flags/${confirmTargetId}/confirm` && r.status === 200);
  expect(confirmResp.body).toMatchObject({ id: confirmTargetId, status: 'confirmed' });
  await expect(page.locator('#pii-count')).toHaveText(String(TOTAL - 1));
  expect(await page.locator(`[data-testid="pii-group"][data-id="${dsId(6)}"] [data-testid="pii-group-count"]`).textContent())
    .toBe(String(PER_DS - 1));
  expect(await page.evaluate(() => document.getElementById('pii-inbox').scrollTop), 'scroll position kept')
    .toBe(scrollBefore);
  expect(piiListRequests, 'acting on a flag re-fetches the list').toBe(2);

  // The 'health' category: three Dismisses clear it out. Each dismiss sends
  // its request for the right id, the row leaves, the counts update — and
  // when the last one goes, the emptied group disappears and the chip that
  // matches nothing shows its empty state.
  await page.click('[data-testid="pii-filter-health"]');
  await expect(page.locator('[data-testid="pii-flag"]')).toHaveCount(CATEGORY_COUNTS.health);
  expect(piiListRequests, 'choosing a chip must not send a request').toBe(2);
  for (let k = 0; k < HEALTH_FLAG_IDS.length; k += 1) {
    const id = HEALTH_FLAG_IDS[k];
    await page.locator(`[data-testid="pii-flag"][data-id="${id}"] [data-action="pii-dismiss"]`).click();
    await expect(page.locator(`[data-testid="pii-flag"][data-id="${id}"]`)).toHaveCount(0);
    const req = requests.find((r) => r.path === `/api/pii-flags/${id}/dismiss`);
    expect(req, `dismiss request for the right id (${id})`).toBeTruthy();
    expect(req.method).toBe('POST');
    expect(req.auth).toBe(bearer);
    expect(req.body).toBeNull();
    const resp = responses.find((r) => r.path === `/api/pii-flags/${id}/dismiss` && r.status === 200);
    expect(resp.body).toMatchObject({ id, status: 'dismissed' });
    await expect(page.locator('#pii-count')).toHaveText(String(TOTAL - 1 - (k + 1)));
  }

  // The last health flag is gone: the group it lived in is emptied (no
  // rows left under that chip), the group disappears from the region, and
  // the chip that now matches nothing shows its empty state.
  expect(await page.locator('[data-testid="pii-group"]').count()).toBe(0);
  await expect(page.locator('[data-testid="pii-empty-category"]')).toBeVisible();
  await expect(page.locator('[data-testid="pii-empty-category"]')).toHaveText('No flags in this category.');
  const healthChip = page.locator('[data-testid="pii-filter-health"]');
  await expect(healthChip).toHaveAttribute('aria-pressed', 'true');
  expect(await healthChip.textContent(), 'the emptied chip keeps its own (zero) count').toBe('health 0');
  await expect(page.locator('#pii-count')).toHaveText(String(TOTAL - 4));
  expect(await page.evaluate(() => window.__issue781Marker), 'no page reload').toBe('alive');

  // Back to All: the emptied dataset group is gone for good (all of its
  // flags were health), the rest is intact.
  await page.click('[data-testid="pii-filter-all"]');
  await expect(page.locator('[data-testid="pii-flag"]')).toHaveCount(TOTAL - 4);
  await expect(page.locator('[data-testid="pii-group"]')).toHaveCount(DS_COUNT - 1);
  expect(await page.locator(`[data-testid="pii-group"][data-id="${dsId(HEALTH_DS)}"]`).count(),
    'the emptied group must be gone from the unfiltered view too').toBe(0);
  expect(await page.locator(`[data-testid="pii-group"][data-id="${dsId(6)}"] [data-testid="pii-group-count"]`).textContent())
    .toBe(String(PER_DS - 1));

  // ------------------------------------------------------------------
  // Empty state: nothing pending.
  // ------------------------------------------------------------------
  flags = [];
  await page.reload();
  await expect(page.locator('[data-testid="pii-empty"]')).toBeVisible();
  await expect(page.locator('[data-testid="pii-empty"] .wh-pii-empty-title')).toHaveText('No PII flags to review');
  await expect(page.locator('[data-testid="pii-empty"] .wh-pii-empty-copy'))
    .toHaveText('Flags appear here when discovery finds personal data in a source.');
  await expect(page.locator('#pii-count')).toHaveText('0');
  expect(await chips.count()).toBe(1); // only the All chip remains, at zero
  expect(await chips.first().textContent()).toBe('All 0');
  // Centred in the region: horizontally centred, filling the space below
  // the top bar.
  const centre = await page.evaluate(() => {
    const inbox = document.getElementById('pii-inbox');
    const el = document.querySelector('[data-testid="pii-empty"]');
    const i = inbox.getBoundingClientRect();
    const e = el.getBoundingClientRect();
    return {
      iCx: i.left + i.width / 2,
      eCx: e.left + e.width / 2,
      iH: i.height,
      eH: e.height,
      eTop: e.top - i.top,
    };
  });
  expect(Math.abs(centre.eCx - centre.iCx), 'empty state must be centred').toBeLessThan(2);
  expect(centre.eH, 'empty state must fill the region').toBeGreaterThan(centre.iH * 0.5);
  expect(centre.eTop).toBeGreaterThanOrEqual(0);

  // ------------------------------------------------------------------
  // Narrow screens, 390x844: rows stack their fields and there is no
  // horizontal page scroll.
  // ------------------------------------------------------------------
  flags = makeFlags();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await expect(page.locator('[data-testid="pii-flag"]')).toHaveCount(TOTAL);

  // Each row stacks its fields vertically, inside the viewport width. The
  // check goes past the row's direct children: every field cell of EVERY
  // row must stack in order, and the nested content of the actions cell
  // (the two buttons) must stay inside its cell — a nested node that
  // escaped or spilled sideways fails the proof.
  const stack = await page.evaluate(() => {
    const CELL_SELECTOR = '.wh-pii-field, .wh-pii-category, .wh-pii-actions';
    let rows = 0;
    let cells = 0;
    let buttons = 0;
    let stacked = true;
    let nested = true;
    let rowRight = 0;
    for (const row of document.querySelectorAll('[data-testid="pii-flag"]')) {
      rows += 1;
      const rowBox = row.getBoundingClientRect();
      rowRight = Math.max(rowRight, rowBox.right);
      const cellBoxes = Array.from(row.querySelectorAll(CELL_SELECTOR)).map((c) => c.getBoundingClientRect());
      cells += cellBoxes.length;
      if (cellBoxes.length !== 3) stacked = false;
      for (let i = 1; i < cellBoxes.length; i += 1) {
        if (cellBoxes[i].top < cellBoxes[i - 1].bottom - 1) stacked = false;
      }
      const actions = row.querySelector('.wh-pii-actions');
      if (!actions) { nested = false; continue; }
      const actionsBox = actions.getBoundingClientRect();
      for (const btn of actions.querySelectorAll('button[data-action]')) {
        const b = btn.getBoundingClientRect();
        buttons += 1;
        if (b.top < actionsBox.top - 1 || b.bottom > actionsBox.bottom + 1 || b.right > rowBox.right + 1) {
          nested = false;
        }
      }
    }
    return { rows, cells, buttons, stacked, nested, rowRight, viewport: window.innerWidth };
  });
  expect(stack.rows, 'every row is present on the narrow screen').toBe(TOTAL);
  expect(stack.cells, 'every field cell of every row is checked, not just direct children').toBe(TOTAL * 3);
  expect(stack.buttons, 'both nested buttons of every row are checked').toBe(TOTAL * 2);
  expect(stack.stacked, 'each row must stack its fields').toBe(true);
  expect(stack.nested, 'nested cell content must stay inside its cell').toBe(true);
  expect(stack.rowRight).toBeLessThanOrEqual(stack.viewport);

  // No horizontal page scroll.
  const hscroll = await page.evaluate(() => {
    window.scrollTo(100, 0);
    const doc = document.documentElement;
    return {
      x: window.scrollX,
      doc: doc.scrollWidth - doc.clientWidth,
      body: document.body.scrollWidth - document.body.clientWidth,
    };
  });
  expect(hscroll.x, 'no horizontal page scroll').toBe(0);
  expect(hscroll.doc).toBeLessThanOrEqual(0);
  expect(hscroll.body).toBeLessThanOrEqual(0);
});
