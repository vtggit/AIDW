// Proof for issue #816 — in Studio, the Audit history tool
// (section.wh-panel[data-panel="audit"]) fits the window, as Ingestion
// does since #808: the events table scrolls inside its own region under
// the filter row, with the table's header row pinned to the top of that
// region while the rows scroll, and one line per event (the Details cell
// cut with an ellipsis whose title carries the full details text up to
// 2,000 characters, the Time cell not wrapping).  While the tool is
// shown the main region is up to 1,280 px wide, centred; every other
// Studio tool keeps the width it has.  And the entity-type filter asks
// the server: choosing a type requests GET /api/audit?entity_type=<type>
// &limit=100 (the type URL-encoded) and shows the events that answer
// returns, newest first; choosing "all" again requests
// GET /api/audit?limit=100.  The count line reads "N events" for what is
// shown and "Latest 100 events" when the server returned exactly 100;
// while a request is out the select stays usable and only the newest
// choice's answer is shown; a failed request shows the load-failure note
// in place of the table and keeps the filter row.
//
// Boots /studio.html?panel=audit against mocked /api/** responses (no
// backend) signed in as an admin, with 100 mocked events, and proves:
//   AC-1  at 1440x900 with 100 events neither the document nor the main
//         region scrolls; only the table's region scrolls; after it is
//         scrolled to its end the header row is still inside the
//         region's visible area; every row is one line — the event with
//         5,000 characters of details is one line high like the others
//         and its Details cell's title holds the first 2,000 characters;
//         at 1920x1080 the tool is wider than 1,200 px (and no wider
//         than 1,280 px, centred) while another Studio tool is no wider
//         than 960 px; at 900 px the table scrolls sideways inside its
//         region and at 390x844 there is no horizontal page scroll
//   AC-2  choosing a type sends a request carrying that entity_type and
//         shows only the events of its answer with the count line; the
//         type "config & sync" goes out URL-encoded (asserted on the
//         encoded query string and decoded via URLSearchParams);
//         choosing "all" again requests without entity_type; a type
//         answered with exactly 100 events reads "Latest 100 events";
//         two choices made quickly with the first answered last show the
//         second choice's events (the older answer is dropped); a failed
//         filter request shows the failure note in place of the table
//         with the filter row still usable
//   Identity  the criteria concern roles, so the proof also runs as a
//         NON-ADMIN (role 'user') after a full reload, booted the
//         production way (the token in the URL hash as #access_token=...,
//         /api/auth/config and /api/auth/me mocked for that user): the
//         admin-only note is shown, no admin-only control survives and
//         no request reaches /api/audit, while the page still renders

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, or an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

