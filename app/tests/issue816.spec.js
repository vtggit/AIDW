// The 100 events the first (unfiltered) load returns: 70 dataset, 20
// source and 10 'config & sync', delivered OLDEST FIRST so the client's
// newest-first sort — not the mock's order — is what renders.
// Event i = 50 carries 5,000 characters of details ('note: ' + 4,994
// x's); event i = 75's details carry the XSS payload.
const ALL_LOAD = [];
for (let i = 0; i < 100; i++) {
  const type = i % 10 < 7 ? TYPE_A : i % 10 < 9 ? TYPE_B : TYPE_C;
  const details =
    i === 50
      ? { note: 'x'.repeat(4994) }
      : i === 75
        ? { html: XSS_PAYLOAD }
        : { ref: 'evt-' + i };
  ALL_LOAD.push({
    id: i + 1,
    entity_type: type,
    entity_id: 'ent-' + i,
    action: i % 3 === 0 ? 'create' : i % 3 === 1 ? 'update' : 'delete',
    actor_sub: 'sub-admin-0001',
    actor_username: i % 5 === 0 ? null : 'admin',
    actor_email: 'admin@example.com',
    actor_roles: 'admin',
    timestamp: BASE + i * 60000,
    details,
  });
}

