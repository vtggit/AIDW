'use strict';

// Proof for issue #798 — in Studio, the Load sequences panel's chosen
// row, its flow and its runs always describe the same sequence.
//
// Boots studio.html against mocked /api/** responses (no backend) with
// three mocked sequences and proves:
//   AC-1  marked at once: the clicked row carries aria-current="true"
//         before its flow response arrives (the delay is made in the
//         mocked route) and no other row carries it; a flow that fails
//         to load keeps the chosen row marked, removes the previous
//         flow from the detail, shows "Could not load the flow for
//         this sequence." and hides the download, while the chosen
//         sequence's runs still load; a flow that loads after a
//         failure removes the error and shows the flow and the
//         download again; a sequence created while one is chosen keeps
//         the chosen row marked after the list is redrawn (matched by
//         id) with the detail pane unchanged, and a sequence created
//         with none chosen leaves no row marked; the runs block starts
//         with a "Run history" heading for a sequence with runs, for
//         one with none, and when the runs request answers 500, and
//         has no heading before any sequence is chosen; a slower
//         earlier response never overwrites a later choice, for the
//         flow and for the runs; the data-status attribute of a run
//         row and of a run step row keeps a hostile API status value
//         intact (inert text, no markup breakout, attribute not
//         corrupted); and a poll of an executed run that is still in
//         flight when a later row is chosen must not overwrite the
//         later selection's runs
//   Identity  the criteria concern roles, so the proof also runs as a
//         NON-ADMIN (role 'user'): the page is booted the production
//         way (the token in the URL hash as #access_token=...,
//         /api/auth/config and /api/auth/me mocked for that user) in a
//         second pass after a full reload, and the admin-only controls
//         are asserted absent while the page still renders

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

