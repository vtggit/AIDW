// A minimal BPMN projection per sequence, with step names that mark
// which sequence's flow is on screen.
const FLOW_STEPS = {
  [ALPHA_ID]: ['Alpha step 1', 'Alpha step 2', 'Alpha step 3'],
  [BETA_ID]: ['Beta step 1', 'Beta step 2'],
  [GAMMA_ID]: ['Gamma step 1', 'Gamma step 2'],
};
function bpmnFor(id) {
  const steps = FLOW_STEPS[id] || ['Step one', 'Step two'];
  const tasks = steps.map((s) => '<bpmn:serviceTask name="' + s + '"/>').join('');
  return {
    process_key: 'proc_' + id,
    bpmn_xml:
      '<?xml version="1.0" encoding="UTF-8"?>' +
      '<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL" id="def_' + id + '">' +
      '<bpmn:process id="proc_' + id + '" isExecutable="false">' + tasks + '</bpmn:process>' +
      '</bpmn:definitions>',
  };
}

// The executed run: created by Execute, non-terminal when executed
// (so the page polls it) and terminal in its first poll answer —
// which the mocked route holds so a later row choice can happen while
// the poll is in flight.
const NEW_RUN = { id: 'run-exec-1', name: 'Executed run', sequence_id: ALPHA_ID, status: 'running' };
const EXECUTED_RUN = {
  id: 'run-exec-1',
  name: 'Executed run',
  sequence_id: ALPHA_ID,
  status: 'running',
  steps: [{ label: 'Executed step', status: XSS_STEP_STATUS }],
};
const TERMINAL_RUN = {
  id: 'run-exec-1',
  name: 'Executed run',
  sequence_id: ALPHA_ID,
  status: 'completed',
  steps: [{ label: 'Executed step', status: 'completed' }],
};

test('issue798 freeform', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });

  // Every /api/** request mocked for the current identity: the auth
  // endpoints answer for `me`, the sequences endpoints answer with the
  // fixtures above (plus whatever was created), every other list an
  // empty array.  The scenario state lives in these closures and is
  // toggled from the test: `delayAlpha` delays the next Alpha flow
  // request, `holdGamma` holds the next Gamma flow request until it is
  // released, and `runsFail` makes the runs request answer 500.  Every
  // delay is made in the mocked route, never with a fixed wait in the
  // page.
  let me = ADMIN_ME;
  const authHeaders = [];
  const created = [];
  let delayAlpha = 0;
  let holdGamma = false;
  const heldGamma = [];
  let runsFail = false;
  // The executed run's poll: how many poll requests reached the mock
  // and how many were answered (the answer is held in the route).
  let polls = 0;
  let pollsAnswered = 0;

  await page.route('**/api/**', async (route) => {
    const url = route.request().url();
    if (url.includes('/api/auth/config')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(AUTH_CONFIG) });
    }
    if (url.includes('/api/auth/me')) {
      const auth = route.request().headers()['authorization'];
      if (auth) authHeaders.push(auth);
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(me) });
    }
    if (url.includes('/api/load-sequences') && url.includes('/bpmn')) {
      const id = decodeURIComponent(url.split('/api/load-sequences/')[1].split('/')[0]);
      if (id === BETA_ID) {
        return route.fulfill({
          status: 500,
          contentType: 'application/json',
          body: JSON.stringify({ detail: 'bpmn unavailable' }),
        });
      }
      if (id === ALPHA_ID && delayAlpha > 0) {
        delayAlpha -= 1;
        // The delay lives in the mocked route, not in the page.
        await new Promise((resolve) => setTimeout(resolve, 2000));
      }
      if (id === GAMMA_ID && holdGamma) {
        return heldGamma.push(route); // held until the test releases it
      }
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(bpmnFor(id)) });
    }
    if (url.includes('/api/load-sequences')) {
      if (route.request().method() === 'POST') {
        const body = JSON.parse(route.request().postData() || '{}');
        const seq = {
          id: 'seq-new-' + (created.length + 1),
          name: body.name,
          description: 'created load sequence',
        };
        created.push(seq);
        return route.fulfill({ status: 201, contentType: 'application/json', body: JSON.stringify(seq) });
      }
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(SEQUENCES.concat(created)) });
    }
    if (url.includes('/api/sequence-runs')) {
      const method = route.request().method();
      if (method === 'POST' && url.includes('/execute')) {
        return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(EXECUTED_RUN) });
      }
      if (method === 'POST') {
        return route.fulfill({ status: 201, contentType: 'application/json', body: JSON.stringify(NEW_RUN) });
      }
      if (method === 'GET' && url.includes('/api/sequence-runs/')) {
        polls += 1;
        // Hold the answer in the mocked route (never a wait in the
        // page) so the test can choose a later row while this poll is
        // still in flight.
        await new Promise((resolve) => setTimeout(resolve, 1500));
        await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(TERMINAL_RUN) });
        pollsAnswered += 1;
        return;
      }
      if (runsFail) {
        return route.fulfill({
          status: 500,
          contentType: 'application/json',
          body: JSON.stringify({ detail: 'runs unavailable' }),
        });
      }
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(RUNS) });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
  });

  const alphaRow = page.locator('[data-testid="sequence-row"][data-id="' + ALPHA_ID + '"]');
  const betaRow = page.locator('[data-testid="sequence-row"][data-id="' + BETA_ID + '"]');
  const gammaRow = page.locator('[data-testid="sequence-row"][data-id="' + GAMMA_ID + '"]');

  // Read the first element of the runs block: while a sequence is
  // chosen it must be the "Run history" heading.
  const runsBlockStart = () =>
    page.evaluate(() => {
      const block = document.querySelector('[data-testid="sequence-runs"]');
      const first = block && block.firstElementChild;
      return {
        testid: first ? first.getAttribute('data-testid') : null,
        text: first ? first.textContent : '',
      };
    });

  // Report the value an injected onerror would have set (undefined if
  // never set), after settling any breakout <img>: the error event of
  // the injected img is what would run its onerror, so waiting for it
  // makes the check deterministic.
  const pwnedFlag = (flagName) =>
    page.evaluate((name) => {
      const imgs = Array.from(
        document.querySelectorAll('[data-testid="run-status"] img, [data-testid="run-step-row"] img'),
      );
      return Promise.all(
        imgs.map((img) =>
          new Promise((resolve) => {
            if (img.complete) return resolve();
            img.addEventListener('error', () => resolve());
            img.addEventListener('load', () => resolve());
          }),
        ),
      ).then(() => typeof window[name]);
    }, flagName);

  // --------------------------------------------------------------------
  // Admin pass: boot the production way (the token rides the URL hash).
  // --------------------------------------------------------------------
  await page.goto('/studio.html?panel=sequences#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  await expect.poll(() => authHeaders).toContain('Bearer ' + ADMIN_TOKEN);
  await expect(page.locator('[data-testid="sequence-row"]')).toHaveCount(3);

  // Before a sequence is chosen: no row is marked, no heading, the
  // pre-selection note, an empty detail and a hidden download.
  await expect(page.locator('[data-testid="sequence-row"][aria-current="true"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="runs-heading"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="seq-detail-pane"] [data-testid="sequence-runs"]'))
    .toHaveText('Select a load sequence to see its runs.');
  await expect(page.locator('[data-testid="sequence-detail"]')).toBeEmpty();
  await expect(page.locator('[data-testid="bpmn-download"]')).toBeHidden();

  // --------------------------------------------------------------------
  // Creating a sequence with none chosen: after the list is redrawn
  // no row is marked, the new sequence is in the list and the detail
  // pane is unchanged.
  // --------------------------------------------------------------------
  await page.locator('[data-testid="sequence-name-input"]').fill('Created first');
  await page.locator('[data-testid="sequence-create"]').click();
  await expect(page.locator('[data-testid="sequence-row"]')).toHaveCount(4);
  await expect(page.locator('[data-testid="sequence-row"][data-id="seq-new-1"]')).toHaveText('Created first');
  await expect(page.locator('[data-testid="sequence-row"][aria-current="true"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="seq-detail-pane"] [data-testid="sequence-runs"]'))
    .toHaveText('Select a load sequence to see its runs.');
  await expect(page.locator('[data-testid="sequence-detail"]')).toBeEmpty();
  await expect(page.locator('[data-testid="bpmn-download"]')).toBeHidden();

  // --------------------------------------------------------------------
  // Marked at once: with the flow request delayed in the mocked route,
  // the clicked row carries aria-current="true" before the flow
  // arrives, and no other row carries it.
  // --------------------------------------------------------------------
  delayAlpha = 1;
  await alphaRow.click();
  await expect(alphaRow).toHaveAttribute('aria-current', 'true');
  await expect(betaRow).not.toHaveAttribute('aria-current');
  await expect(gammaRow).not.toHaveAttribute('aria-current');
  await expect(page.locator('[data-testid="sequence-row"][data-id="seq-new-1"]')).not.toHaveAttribute('aria-current');
  expect(await page.locator('[data-testid="sequence-row"][aria-current="true"]').count()).toBe(1);
  expect(
    await page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]').count(),
    'the chosen row is marked before its (delayed) flow arrives',
  ).toBe(0);

  // The delayed flow arrives: the row stays marked, the flow, the
  // download and the admin-only Execute button are shown, and the runs
  // block starts with the "Run history" heading above the runs.
  await expect(page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]')).toHaveCount(3);
  await expect(alphaRow).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('[data-testid="bpmn-download"]')).toBeVisible();
  await expect(page.locator('[data-testid="sequence-execute"]')).toBeVisible();
  await expect(page.locator('[data-testid="runs-heading"]')).toHaveText('Run history');
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(2);
  await expect(page.locator('[data-testid="sequence-runs"]')).toContainText('Alpha run 1');
  await expect(page.locator('[data-testid="run-row"][data-id="run-a-1"] [data-testid="run-status"]')).toHaveText(
    'completed',
  );
  let runsStart = await runsBlockStart();
  expect(runsStart.testid, 'a sequence with runs: the block starts with the heading').toBe('runs-heading');
  expect(runsStart.text, 'the heading reads "Run history"').toBe('Run history');

  // --------------------------------------------------------------------
  // A flow that fails to load, chosen after one whose flow loaded:
  // the row stays marked, the earlier flow is gone, the load error is
  // shown, the download is hidden, and the sequence's own runs load.
  // --------------------------------------------------------------------
  await betaRow.click();
  await expect(betaRow).toHaveAttribute('aria-current', 'true');
  await expect(alphaRow).not.toHaveAttribute('aria-current');
  await expect(page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="flow-load-error"]')).toHaveText(
    'Could not load the flow for this sequence.',
  );
  await expect(page.locator('[data-testid="sequence-detail"]')).toContainText(
    'Could not load the flow for this sequence.',
  );
  await expect(page.locator('[data-testid="bpmn-download"]')).toBeHidden();
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(2);
  await expect(page.locator('[data-testid="sequence-runs"]')).toContainText('Beta run 1');
  await expect(page.locator('[data-testid="runs-heading"]')).toHaveText('Run history');

  // --------------------------------------------------------------------
  // A flow that loads after a failure: the error is gone, the flow is
  // shown and the download button is shown again.
  // --------------------------------------------------------------------
  await gammaRow.click();
  await expect(gammaRow).toHaveAttribute('aria-current', 'true');
  await expect(betaRow).not.toHaveAttribute('aria-current');
  await expect(page.locator('[data-testid="flow-load-error"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]')).toHaveCount(2);
  await expect(page.locator('[data-testid="sequence-detail"]')).toContainText('Gamma step 1');
  await expect(page.locator('[data-testid="bpmn-download"]')).toBeVisible();
  // A sequence with no runs: the heading is still there, above the
  // empty note.
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="sequence-runs"]')).toContainText('No runs yet');
  await expect(page.locator('[data-testid="runs-heading"]')).toHaveText('Run history');
  runsStart = await runsBlockStart();
  expect(runsStart.testid, 'a sequence with no runs: the block starts with the heading').toBe('runs-heading');
  expect(runsStart.text, 'the heading reads "Run history"').toBe('Run history');

  // --------------------------------------------------------------------
  // When the runs could not be loaded (the request answers 500), the
  // heading is still there, above the error.
  // --------------------------------------------------------------------
  runsFail = true;
  await alphaRow.click();
  await expect(alphaRow).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]')).toHaveCount(3);
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="sequence-runs"]')).toContainText('Could not load runs.');
  await expect(page.locator('[data-testid="runs-heading"]')).toHaveText('Run history');
  runsStart = await runsBlockStart();
  expect(runsStart.testid, 'failed runs load: the block starts with the heading').toBe('runs-heading');
  expect(runsStart.text, 'the heading reads "Run history"').toBe('Run history');
  runsFail = false;

  // --------------------------------------------------------------------
  // Two rows chosen in quick succession with the first flow response
  // held in the mocked route past the second: the second row is marked
  // and the second sequence's flow and runs are shown; when the first
  // response is let through it must not overwrite the later choice.
  // --------------------------------------------------------------------
  holdGamma = true;
  await gammaRow.click();
  await alphaRow.click();
  await expect(alphaRow).toHaveAttribute('aria-current', 'true');
  await expect(gammaRow).not.toHaveAttribute('aria-current');
  await expect(page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]')).toHaveCount(3);
  await expect(page.locator('[data-testid="sequence-detail"]')).toContainText('Alpha step 1');
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(2);
  await expect(page.locator('[data-testid="sequence-runs"]')).toContainText('Alpha run 1');

  // Now let the earlier selection's held response through: it must be
  // ignored, for the flow and for the runs.
  holdGamma = false;
  await heldGamma.shift().fulfill({
    status: 200,
    contentType: 'application/json',
    body: JSON.stringify(bpmnFor(GAMMA_ID)),
  });
  await page.waitForTimeout(200);
  const late = await page.evaluate(() => {
    const pane = document.querySelector('[data-testid="seq-detail-pane"]');
    const current = document.querySelector('[data-testid="sequence-row"][aria-current="true"]');
    return {
      flowStepCount: pane.querySelectorAll('[data-testid="flow-step"]').length,
      hasLateFlow: (pane.textContent || '').includes('Gamma step 1'),
      runRowCount: pane.querySelectorAll('[data-testid="run-row"]').length,
      hasChosenRuns: (pane.textContent || '').includes('Alpha run 1'),
      currentId: current ? current.dataset.id : null,
    };
  });
  expect(late.flowStepCount, 'the later selection\'s flow is still on screen').toBe(3);
  expect(late.hasLateFlow, 'the earlier selection\'s late flow did not overwrite the detail').toBe(false);
  expect(late.runRowCount, 'the later selection\'s runs are still on screen').toBe(2);
  expect(late.hasChosenRuns, 'the later selection\'s runs are still listed').toBe(true);
  expect(late.currentId, 'aria-current stays on the later selection').toBe(ALPHA_ID);

  // --------------------------------------------------------------------
  // Creating a sequence while one is chosen: after the list is
  // redrawn the chosen row is still marked, matched by id, the new
  // sequence is in the list and the detail pane is unchanged.
  // --------------------------------------------------------------------
  const detailBefore = await page.evaluate(() => {
    const pane = document.querySelector('[data-testid="seq-detail-pane"]');
    return {
      flowStepCount: pane.querySelectorAll('[data-testid="flow-step"]').length,
      hasFlow: (pane.textContent || '').includes('Alpha step 1'),
      flowLoadErrors: pane.querySelectorAll('[data-testid="flow-load-error"]').length,
      downloadHidden: document.querySelector('[data-testid="bpmn-download"]').hidden,
      runRowCount: pane.querySelectorAll('[data-testid="run-row"]').length,
      hasRuns: (pane.textContent || '').includes('Alpha run 1'),
      hasHeading: !!pane.querySelector('[data-testid="runs-heading"]'),
    };
  });
  await page.locator('[data-testid="sequence-name-input"]').fill('Created second');
  await page.locator('[data-testid="sequence-create"]').click();
  await expect(page.locator('[data-testid="sequence-row"]')).toHaveCount(5);
  await expect(page.locator('[data-testid="sequence-row"][data-id="seq-new-2"]')).toHaveText('Created second');
  await expect(alphaRow).toHaveAttribute('aria-current', 'true');
  expect(await page.locator('[data-testid="sequence-row"][aria-current="true"]').count()).toBe(1);
  const detailAfter = await page.evaluate(() => {
    const pane = document.querySelector('[data-testid="seq-detail-pane"]');
    return {
      flowStepCount: pane.querySelectorAll('[data-testid="flow-step"]').length,
      hasFlow: (pane.textContent || '').includes('Alpha step 1'),
      flowLoadErrors: pane.querySelectorAll('[data-testid="flow-load-error"]').length,
      downloadHidden: document.querySelector('[data-testid="bpmn-download"]').hidden,
      runRowCount: pane.querySelectorAll('[data-testid="run-row"]').length,
      hasRuns: (pane.textContent || '').includes('Alpha run 1'),
      hasHeading: !!pane.querySelector('[data-testid="runs-heading"]'),
    };
  });
  expect(detailAfter, 'the detail pane is unchanged by the create redraw').toEqual(detailBefore);

  // --------------------------------------------------------------------
  // Execute (admin) with a hostile step status: the executed run's
  // step row must keep the whole status value in data-status as inert
  // text — no markup breakout, no corrupted attribute.
  // --------------------------------------------------------------------
  await page.locator('[data-testid="sequence-execute"]').click();
  await expect(page.locator('[data-testid="run-step-row"]')).toHaveCount(1);
  await expect(page.locator('[data-testid="run-step-row"]')).toHaveText('Executed step');
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(3);
  await expect(page.locator('[data-testid="run-row"][data-id="run-exec-1"]')).toContainText('Executed run');
  await expect(page.locator('[data-testid="sequence-runs"]')).toContainText('Alpha run 1');
  const stepStatus = await page.evaluate(() => {
    const row = document.querySelector('[data-testid="run-step-row"]');
    return {
      hasImg: !!row.querySelector('img'),
      attr: row.getAttribute('data-status'),
      text: row.textContent,
    };
  });
  expect(stepStatus.hasImg, 'a hostile step status must not create markup').toBe(false);
  expect(stepStatus.attr, 'the step data-status attribute keeps the whole value').toBe(XSS_STEP_STATUS);
  expect(stepStatus.text, 'the step label renders as plain text').toBe('Executed step');
  expect(await pwnedFlag('__pwnedStep'), 'a breakout step status would run its onerror').toBe('undefined');

  // --------------------------------------------------------------------
  // An in-flight poll must not overwrite a later selection's runs:
  // the executed run is not terminal, so the page polls it; the first
  // poll answer is held in the mocked route, and a later row is chosen
  // while the poll is in flight.
  // --------------------------------------------------------------------
  await expect.poll(() => polls).toBe(1);
  await gammaRow.click();
  await expect(gammaRow).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('[data-testid="sequence-runs"]')).toContainText('No runs yet');
  await expect(page.locator('[data-testid="sequence-runs"]')).not.toContainText('Alpha run 1');

  // Let the held poll answer through (terminal, describing the earlier
  // selection's executed run): it must be dropped, not applied.
  await expect.poll(() => pollsAnswered).toBe(1);
  // Settle: let the answered poll be processed in the page. This is a
  // settle after the answered request, not a scenario delay — the
  // in-flight hold lives in the mocked route.
  await page.waitForTimeout(300);
  const afterStalePoll = await page.evaluate(() => {
    const block = document.querySelector('[data-testid="sequence-runs"]');
    const text = block.textContent || '';
    const flow = document.querySelector('[data-testid="sequence-detail"]');
    const current = document.querySelector('[data-testid="sequence-row"][aria-current="true"]');
    return {
      hasEmptyNote: text.includes('No runs yet'),
      hasAlphaRun: text.includes('Alpha run 1'),
      staleRunRows: block.querySelectorAll('[data-testid="run-row"][data-id="run-exec-1"]').length,
      staleStepRows: block.querySelectorAll('[data-testid="run-step-row"]').length,
      runErrors: block.querySelectorAll('[data-testid="runs-error"]').length,
      flowText: flow ? flow.textContent || '' : '',
      currentId: current ? current.dataset.id : null,
    };
  });
  expect(afterStalePoll.hasEmptyNote, 'the later selection keeps its own (empty) runs').toBe(true);
  expect(afterStalePoll.hasAlphaRun, 'the earlier selection\'s runs must not overwrite the later one').toBe(false);
  expect(afterStalePoll.staleRunRows, 'the executed run must not appear in the later selection').toBe(0);
  expect(afterStalePoll.staleStepRows, 'the executed run\'s steps must not appear in the later selection').toBe(0);
  expect(afterStalePoll.runErrors, 'the stale poll must not add a load error').toBe(0);
  expect(afterStalePoll.flowText, 'the later selection\'s flow is still on screen').toContain('Gamma step 1');
  expect(afterStalePoll.currentId, 'aria-current stays on the later selection').toBe(GAMMA_ID);

  // --------------------------------------------------------------------
  // A hostile RUN status value: the second created sequence carries a
  // run whose status tries to break out of the data-status attribute.
  // --------------------------------------------------------------------
  const createdRow = page.locator('[data-testid="sequence-row"][data-id="seq-new-2"]');
  await createdRow.click();
  await expect(createdRow).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(1);
  await expect(page.locator('[data-testid="run-row"][data-id="run-x-1"]')).toContainText('X status run');
  const runStatus = await page.evaluate(() => {
    const span = document.querySelector('[data-testid="run-row"][data-id="run-x-1"] [data-testid="run-status"]');
    return {
      hasImg: !!span.querySelector('img'),
      attr: span.getAttribute('data-status'),
      text: span.textContent,
    };
  });
  expect(runStatus.hasImg, 'a hostile run status must not create markup').toBe(false);
  expect(runStatus.attr, 'the data-status attribute keeps the whole value').toBe(XSS_RUN_STATUS);
  expect(runStatus.text, 'the status renders as inert text').toBe(XSS_RUN_STATUS);
  expect(await pwnedFlag('__pwnedRun'), 'a breakout run status would run its onerror').toBe('undefined');

  // --------------------------------------------------------------------
  // Non-admin pass (role 'user'), after a full reload: booted the
  // production way, the admin-only controls are absent and the page
  // still renders — read-only.
  // --------------------------------------------------------------------
  me = VIEWER_ME;
  created.length = 0;
  await page.goto('about:blank');
  await page.goto('/studio.html?panel=sequences#access_token=' + encodeURIComponent(VIEWER_TOKEN));
  await expect.poll(() => authHeaders).toContain('Bearer ' + VIEWER_TOKEN);

  await expect(page.locator('[data-testid="seq-list-pane"] [data-testid="sequence-name-input"]')).toBeVisible();
  await expect(page.locator('[data-testid="sequence-row"]')).toHaveCount(3);
  await expect(page.locator('[data-testid="sequence-create"]')).toHaveCount(0);
  await expect(page.locator('[data-requires-role="admin"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="sequence-row"][aria-current="true"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="runs-heading"]')).toHaveCount(0);
  await expect(page.locator('[data-testid="seq-detail-pane"] [data-testid="sequence-runs"]'))
    .toHaveText('Select a load sequence to see its runs.');

  // The page still renders and still works read-only: choosing a row
  // loads its flow, the "Run history" heading and its runs — WITHOUT
  // the admin-only Execute control.
  await alphaRow.click();
  await expect(alphaRow).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]')).toHaveCount(3);
  await expect(page.locator('[data-testid="bpmn-download"]')).toBeVisible();
  await expect(page.locator('[data-testid="runs-heading"]')).toHaveText('Run history');
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(2);
  await expect(page.locator('[data-testid="sequence-runs"]')).toContainText('Alpha run 1');
  await expect(page.locator('[data-testid="sequence-execute"]')).toHaveCount(0);
});
