  expect(scrolled.scrollTop, '#inbox must actually scroll').toBeGreaterThan(0);
  expect(scrolled.header.top, 'the sticky header must stay in view').toBeGreaterThanOrEqual(0);
  expect(scrolled.header.bottom, 'the sticky header must stay in view').toBeLessThanOrEqual(scrolled.viewportH);
  expect(scrolled.topbar.top, 'the top bar must stay in view').toBeGreaterThanOrEqual(0);
  expect(scrolled.topbar.bottom, 'the top bar must stay in view').toBeLessThanOrEqual(scrolled.viewportH);
  expect(scrolled.firstRow.y, 'the first row must be scrolled above the viewport').toBeLessThan(0);

  // ------------------------------------------------------------------
  // The confidence chips narrow the list client-side: no request is sent.
  // ------------------------------------------------------------------
  await page.evaluate(() => { document.getElementById('inbox').scrollTop = 0; });
  await page.click('[data-testid="filter-high"]');
  await expect(page.locator('[data-testid="suggestion"]')).toHaveCount(highCount);
  const highTiers = await page.locator('[data-testid="suggestion"] [data-testid="confidence"]').allTextContents();
  expect(highTiers.every((t) => t === 'High')).toBe(true);
  await expect(page.locator('[data-testid="filter-high"]')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('[data-testid="filter-all"]')).toHaveAttribute('aria-pressed', 'false');
  expect(listRequests, 'choosing a chip must not send a request').toBe(1);

  // The Low chip matches nothing.
  await page.click('[data-testid="filter-low"]');
  await expect(page.locator('[data-testid="suggestion"]')).toHaveCount(0);
  await expect(page.locator('#inbox')).toContainText('No suggestions at this confidence.');
  await expect(page.locator('[data-testid="filter-low"]')).toHaveAttribute('aria-pressed', 'true');
  expect(listRequests, 'choosing a chip must not send a request').toBe(1);

  // Back to All.
  await page.click('[data-testid="filter-all"]');
  await expect(page.locator('[data-testid="suggestion"]')).toHaveCount(TOTAL);
  expect(listRequests, 'choosing a chip must not send a request').toBe(1);

  // ------------------------------------------------------------------
  // Accept and Dismiss: the request goes to the right id, the row leaves,
  // the counts update and #inbox keeps its scroll position — no reload.
  // ------------------------------------------------------------------
  await page.evaluate(() => { window.__issue777Marker = 'alive'; });
  // A row is usable only if it is fully inside #inbox AND fully below the
  // sticky column header: the header overlays the top of the scroll region,
  // so a row tucked under it is covered by it and its Accept/Dismiss buttons
  // would not be the elements that receive the click. The header's bottom
  // edge — not #inbox's top edge — is the picker's upper boundary.
  const pickVisibleRow = () =>
    page.evaluate(() => {
      const inbox = document.getElementById('inbox');
      const box = inbox.getBoundingClientRect();
      const head = inbox.querySelector('[data-testid="inbox-header"]');
      const headBottom = head ? head.getBoundingClientRect().bottom : box.top;
      for (const row of inbox.querySelectorAll('[data-testid="suggestion"]')) {
        const r = row.getBoundingClientRect();
        if (r.top >= headBottom + 2 && r.bottom <= box.bottom - 2) return row.getAttribute('data-id');
      }
      return null;
    });

  // Proof of the picker's contract: the picked row is NOT covered by the
  // sticky header — its top edge starts at or below the header's bottom
  // edge, so the row's buttons receive the click.
  const pickedNotCoveredByHeader = (rowId) =>
    page.evaluate((id) => {
      const inbox = document.getElementById('inbox');
      const head = inbox.querySelector('[data-testid="inbox-header"]');
      const row = inbox.querySelector('[data-testid="suggestion"][data-id="' + id + '"]');
      const headBottom = head ? head.getBoundingClientRect().bottom : inbox.getBoundingClientRect().top;
      return row.getBoundingClientRect().top >= headBottom;
    }, rowId);

  // Dismiss a row from the middle of the (scrolled) list.
  await page.evaluate(() => { document.getElementById('inbox').scrollTop = 1500; });
  let gone = new Set();
  let dismissId = await pickVisibleRow();
  expect(dismissId, 'a row must be fully visible at the scroll position').toBeTruthy();
  expect(await pickedNotCoveredByHeader(dismissId),
    'the picked row must not be covered by the sticky header').toBe(true);
  const scrollTopBeforeDismiss = await page.evaluate(() => document.getElementById('inbox').scrollTop);
  await page.locator(`[data-testid="suggestion"][data-id="${dismissId}"] [data-action="dismiss"]`).click();
  await expect(page.locator(`[data-testid="suggestion"][data-id="${dismissId}"]`)).toHaveCount(0);
  expect(mutationRequests, 'Dismiss must POST the right id').toContain('/api/suggestions/' + dismissId + '/dismiss');
  const c1 = countsAfter((gone = new Set([dismissId])));
  await expect(page.locator('#inbox-count')).toHaveText(String(c1.all));
  await expect(page.locator('#filter-high-count')).toHaveText(String(c1.High));
  await expect(page.locator('#filter-medium-count')).toHaveText(String(c1.Medium));
  await expect(page.locator('#filter-low-count')).toHaveText(String(c1.Low));
  expect(await page.evaluate(() => document.getElementById('inbox').scrollTop),
    'the list must keep its scroll position').toBe(scrollTopBeforeDismiss);
  expect(await page.evaluate(() => window.__issue777Marker), 'no page reload').toBe('alive');

  // Accept another row, still from the scrolled list.
  let acceptId = await pickVisibleRow();
  expect(acceptId, 'a row must be fully visible at the scroll position').toBeTruthy();
  expect(await pickedNotCoveredByHeader(acceptId),
    'the picked row must not be covered by the sticky header').toBe(true);
  const scrollTopBeforeAccept = await page.evaluate(() => document.getElementById('inbox').scrollTop);
  await page.locator(`[data-testid="suggestion"][data-id="${acceptId}"] [data-action="accept"]`).click();
  await expect(page.locator(`[data-testid="suggestion"][data-id="${acceptId}"]`)).toHaveCount(0);
  expect(mutationRequests, 'Accept must POST the right id').toContain('/api/suggestions/' + acceptId + '/accept');
  const c2 = countsAfter((gone = new Set([dismissId, acceptId])));
  await expect(page.locator('#inbox-count')).toHaveText(String(c2.all));
  await expect(page.locator('#filter-high-count')).toHaveText(String(c2.High));
  await expect(page.locator('#filter-medium-count')).toHaveText(String(c2.Medium));
  await expect(page.locator('#filter-low-count')).toHaveText(String(c2.Low));
  expect(await page.evaluate(() => document.getElementById('inbox').scrollTop),
    'the list must keep its scroll position').toBe(scrollTopBeforeAccept);
  expect(await page.evaluate(() => window.__issue777Marker), 'no page reload').toBe('alive');

  // ------------------------------------------------------------------
  // Empty state: nothing to review.
  // ------------------------------------------------------------------
  rows = [];
  await page.reload();
  const empty = page.locator('[data-testid="inbox-empty"]');
  await expect(empty).toBeVisible();
  await expect(empty.locator('.wh-sug-empty-title')).toHaveText('No suggestions to review');
  await expect(empty.locator('.wh-sug-empty-copy')).toHaveText('Discover a data source to get suggested dashboard items.');
  const sourcesLink = empty.locator('a[data-testid="open-sources"]');
  await expect(sourcesLink).toHaveText('Open Data sources');
  expect(await sourcesLink.getAttribute('href')).toBe('studio.html?panel=sources');
