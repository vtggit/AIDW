  await page.route('**/fonts.googleapis.com/**', (route) => route.abort());
  await page.route('**/fonts.gstatic.com/**', (route) => route.abort());
  await page.route('**/api/**', (route) => {
    const url = route.request().url();
    const path = new URL(url).pathname;
    if (path === '/api/auth/config') {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ authMode: 'development' }) });
    }
    if (path === '/api/auth/me') {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ authenticated: true, user: { username: 'admin', sub: 'admin', roles: ['admin'] } }) });
    }
    if (path === '/api/suggestions') {
      listRequests += 1;
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(rows) });
    }
    const m = path.match(/^\/api\/suggestions\/([^/]+)\/(accept|dismiss)$/);
    if (m) {
      mutationRequests.push(path);
      const id = decodeURIComponent(m[1]);
      return route.fulfill({
        status: 200,
        contentType: 'application/json',
        body: JSON.stringify({ id, status: m[2] === 'accept' ? 'accepted' : 'dismissed' }),
      });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
  });
