'use strict';

// Proof for issue #777 — the Suggested dashboard items tool ([data-panel="suggestions"])
// fits the window and its list scrolls on its own.
//
// Boots /studio.html?panel=suggestions against mocked /api/** responses (no backend,
// no data creation): a stateful mock answers the inbox list, the accept/dismiss
// mutations and every other endpoint the page needs. Proves:
//   * at 1440x900 with 300 suggestions: the document does not scroll and the main
//     .aidw-scroll region does not scroll either, while #inbox scrolls and its
//     sticky column header stays in place (the top bar stays in view too)
//   * the rows are ordered highest confidence first, each row is at least 52 px
//     tall and keeps its hooks (data-testid="suggestion" + data-id, the
//     data-testid="confidence" chip, Accept/Dismiss with data-action + data-id)
//   * the count badge and each chip's own count; choosing a chip narrows the
//     list WITHOUT sending a request
//   * Accept and Dismiss each send their request for the right id, the row
//     leaves the list, the counts update and #inbox keeps its scroll position,
//     with no page reload
//   * both empty states (nothing to review -> heading, sentence and the
//     "Open Data sources" link to studio.html?panel=sources; a chip that matches
//     nothing -> "No suggestions at this confidence.")
//   * a suggestion titled <img src=x onerror=window.__pwned=1> renders as text
//     (window.__pwned stays undefined)
//   * a score that arrives as a string sorts and tiers like its number, and
//     a prototype-name item_type renders its upper-cased name in the Type
//     cell — never the native function source a plain-object lookup would
//     resolve to
//   * the column header is ONE element holding the five labels — the proof reads
//     that element's text and checks Type, Suggested item, Aggregation,
//     Confidence and Actions appear in that order (no array matcher)
//   * at 390x844 the header row is dropped, each row stacks its fields and there
//     is no horizontal page scroll

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

const TOKEN = 'dev-secret-token:admin';
const TOTAL = 300;
const XSS_INDEX = 120; // rows[XSS_INDEX] carries the hostile title
const XSS_ID = 'sug-' + String(XSS_INDEX + 1).padStart(3, '0');
const XSS_TITLE = '<img src=x onerror=window.__pwned=1>';

// 300 scores, strictly decreasing from 0.99 to 0.41: the top 150 read High
// (>= 0.7), the next 150 Medium (>= 0.4) and none Low — so the Low chip is
// the one that matches nothing.
const scoreOf = (i) => Math.round((0.99 - (i * 0.58) / (TOTAL - 1)) * 1e6) / 1e6;
const TIER_OF = (score) => (score >= 0.7 ? 'High' : score >= 0.4 ? 'Medium' : 'Low');

function makeRows() {
  const types = ['kpi', 'bar', 'line', 'pie', 'table'];
  const aggs = ['sum', 'count', 'avg', 'max', 'min'];
  const rows = [];
  for (let i = 0; i < TOTAL; i += 1) {
    rows.push({
      id: 'sug-' + String(i + 1).padStart(3, '0'),
      name: 'Item ' + (i + 1),
      title: 'Item ' + (i + 1),
      item_type: types[i % types.length],
      aggregation: aggs[i % aggs.length],
      status: 'suggested',
      score: scoreOf(i),
    });
  }
  rows[XSS_INDEX].title = XSS_TITLE;
  rows[XSS_INDEX].name = XSS_TITLE;
  // Hostile-value regressions: a score that arrives as a string must sort
  // AND tier like its number, and a prototype-name item_type must render its
  // upper-cased name, never a native function source.
  rows[0].score = String(rows[0].score);
  rows[5].score = String(rows[5].score);
  rows[1].item_type = 'constructor';
  return rows;
}

