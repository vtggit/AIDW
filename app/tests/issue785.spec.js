'use strict';

// Proof for issue #785 — in Studio, the Load sequences tool fits the
// window as a list pane and a detail pane.
//
// Boots studio.html against mocked /api/** responses (no backend) and
// proves, at 1440x900 with 200 mocked sequences and a chosen sequence
// carrying 100 runs:
//   AC-1  the "Load sequences" section is a list pane (name input +
//         Create button fixed above the rows, rows scrolling on their
//         own) beside a wider detail pane (the chosen sequence's flow
//         diagram, its BPMN download and, under them, its run history),
//         the detail pane scrolling on its own; before a sequence is
//         chosen the detail pane shows "Select a load sequence to see
//         its runs."; choosing a row tints it and carries
//         aria-current="true", and choosing another row moves
//         aria-current and REPLACES the detail content; neither the
//         document nor the main region scrolls; the name input stays in
//         view while the list scrolls; at 900 px and below the panes
//         stack with no horizontal page scroll at 390x844
//   AC-2  the Create button is present for an admin and absent for a
//         non-admin; a sequence named
//         <img src=x onerror=window.__pwned=1> renders as inert text in
//         its row (window.__pwned stays undefined)
//   AC-3  selecting a sequence replaces the current detail pane content
//         rather than appending to it
//   Identity  the criteria concern roles, so the proof also runs as a
//         NON-ADMIN (role 'user'): the page is booted the production
//         way (the token in the URL hash as #access_token=...,
//         /api/auth/config and /api/auth/me mocked for that user) in a
//         second pass after a full reload, and the admin-only controls
//         are asserted absent while the page still renders

const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});

test.setTimeout(60 * 1000); // two full document boots + 200-row list + 100-run detail

const AUTH_CONFIG = { authEnabled: true, authMode: 'development' };
const ADMIN_ME = { authenticated: true, user: { id: 1, username: 'admin', roles: ['admin'] } };
const VIEWER_ME = { authenticated: true, user: { id: 9, username: 'user', roles: ['user'] } };
const ADMIN_TOKEN = 'issue785-admin-token';
const VIEWER_TOKEN = 'issue785-viewer-token';

// A hostile sequence name: must render as inert text, never as markup.
const XSS_NAME = '<img src=x onerror=window.__pwned=1>';
const CHOSEN_ID = 'seq-0001';   // the sequence carrying 100 runs
const OTHER_ID = 'seq-0002';    // the second sequence (3 runs)
const XSS_ID = 'seq-0200';      // the hostile-named sequence

// 200 mocked sequences; the last one carries the hostile name.
const SEQUENCES = [];
for (let i = 1; i <= 200; i++) {
  SEQUENCES.push({
    id: 'seq-' + String(i).padStart(4, '0'),
    name: i === 200 ? XSS_NAME : 'Sequence ' + i,
    description: 'load sequence ' + i,
  });
}

// Run history: 100 runs for the chosen sequence, 3 for the second.
const RUNS = [];
for (let i = 1; i <= 100; i++) {
  RUNS.push({
    id: 'run-alpha-' + i,
    name: 'Alpha run ' + i,
    sequence_id: CHOSEN_ID,
    status: 'completed',
    started_at: '2026-01-01T00:00:00Z',
    finished_at: '2026-01-01T00:01:00Z',
  });
}
for (let i = 1; i <= 3; i++) {
  RUNS.push({
    id: 'run-bravo-' + i,
    name: 'Bravo run ' + i,
    sequence_id: OTHER_ID,
    status: 'completed',
    started_at: '2026-01-02T00:00:00Z',
    finished_at: '2026-01-02T00:01:00Z',
  });
}

// A minimal BPMN projection per sequence, with step names that mark
// which sequence's flow is on screen.
const FLOW_STEPS = {
  [CHOSEN_ID]: ['Alpha step 1', 'Alpha step 2', 'Alpha step 3'],
  [OTHER_ID]: ['Bravo step 1', 'Bravo step 2'],
};
function bpmnFor(id) {
  const steps = FLOW_STEPS[id] || ['Step one', 'Step two'];
  const tasks = steps.map((s) => '<bpmn:serviceTask name="' + s + '"/>').join('');
  return {
    process_key: 'proc_' + id,
    bpmn_xml:
      '<?xml version="1.0" encoding="UTF-8"?>' +
      '<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL" id="def_' + id + '">' +
      '<bpmn:process id="proc_' + id + '" isExecutable="false">' + tasks + '</bpmn:process>' +
      '</bpmn:definitions>',
  };
}

test('issue785 freeform', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });

  // Every /api/** request mocked for the current identity: the auth
  // endpoints answer for `me`, the sequences endpoints answer with the
  // fixtures above, every other list an empty array.
  let me = ADMIN_ME;
  const authHeaders = [];
  await page.route('**/api/**', (route) => {
    const url = route.request().url();
    if (url.includes('/api/auth/config')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(AUTH_CONFIG) });
    }
    if (url.includes('/api/auth/me')) {
      const auth = route.request().headers()['authorization'];
      if (auth) authHeaders.push(auth);
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(me) });
    }
    if (url.includes('/api/load-sequences') && url.includes('/bpmn')) {
      const id = url.split('/api/load-sequences/')[1].split('/')[0];
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(bpmnFor(decodeURIComponent(id))) });
    }
    if (url.includes('/api/load-sequences')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(SEQUENCES) });
    }
    if (url.includes('/api/sequence-runs')) {
      return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(RUNS) });
    }
    return route.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
  });

  // --------------------------------------------------------------------
  // Admin pass: boot the production way (the token rides the URL hash).
  // --------------------------------------------------------------------
  await page.goto('/studio.html?panel=sequences#access_token=' + encodeURIComponent(ADMIN_TOKEN));
  await expect.poll(() => authHeaders).toContain('Bearer ' + ADMIN_TOKEN);

  // The list pane holds the name input, the admin's Create button and
  // one row per sequence.
  const row1 = page.locator('[data-testid="sequence-row"]').first();
  const row2 = page.locator('[data-testid="sequence-row"]').nth(1);
  await expect(page.locator('[data-testid="sequence-row"]')).toHaveCount(200);
  await expect(page.locator('[data-testid="seq-list-pane"] [data-testid="sequence-name-input"]')).toBeVisible();
  const createBtn = page.locator('[data-testid="seq-list-pane"] [data-testid="sequence-create"]');
  await expect(createBtn).toBeVisible();
  await expect(createBtn).toHaveAttribute('data-requires-role', 'admin');

  // Before a sequence is chosen: the detail pane shows the existing
  // note, no flow and no download button yet.
  await expect(page.locator('[data-testid="seq-detail-pane"] [data-testid="sequence-runs"]'))
    .toHaveText('Select a load sequence to see its runs.');
  await expect(page.locator('[data-testid="sequence-detail"]')).toBeEmpty();
  await expect(page.locator('[data-testid="bpmn-download"]')).toBeHidden();

  // --------------------------------------------------------------------
  // Choosing a row: tinted + aria-current, and its flow, download and
  // runs appear in the detail pane — to the RIGHT of the list pane.
  // --------------------------------------------------------------------
  await row1.click();
  await expect(row1).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]')).toHaveCount(3);
  await expect(page.locator('[data-testid="bpmn-download"]')).toBeVisible();
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(100);
  await expect(page.locator('[data-testid="sequence-runs"]')).toContainText('Alpha run 1');

  const layout = await page.evaluate(() => {
    const detailPane = document.querySelector('[data-testid="seq-detail-pane"]');
    const detail = document.querySelector('[data-testid="sequence-detail"]');
    const download = document.querySelector('[data-testid="bpmn-download"]');
    const runs = document.querySelector('[data-testid="sequence-runs"]');
    const listBox = document.querySelector('[data-testid="seq-list-pane"]').getBoundingClientRect();
    const detailBox = detailPane.getBoundingClientRect();
    return {
      inPane: detailPane.contains(detail) && detailPane.contains(download) && detailPane.contains(runs),
      detailLeft: detailBox.left,
      listRight: listBox.right,
      detailWidth: detailBox.width,
      listWidth: listBox.width,
    };
  });
  expect(layout.inPane, 'flow, download and runs all sit in the detail pane').toBe(true);
  expect(layout.detailLeft, 'the detail pane is to the right of the list pane').toBeGreaterThanOrEqual(layout.listRight - 1);
  expect(layout.detailWidth, 'the detail pane is wider than the list pane').toBeGreaterThan(layout.listWidth);

  // --------------------------------------------------------------------
  // Choosing another row: aria-current moves and the detail REPLACES.
  // --------------------------------------------------------------------
  await row2.click();
  await expect(row2).toHaveAttribute('aria-current', 'true');
  await expect(row1).not.toHaveAttribute('aria-current');
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(3);
  const replaced = await page.evaluate(() => {
    const pane = document.querySelector('[data-testid="seq-detail-pane"]');
    const text = pane.textContent || '';
    return {
      detailCount: pane.querySelectorAll('[data-testid="sequence-detail"]').length,
      runRowCount: pane.querySelectorAll('[data-testid="run-row"]').length,
      hasNewFlow: text.includes('Bravo step 1'),
      hasOldFlow: text.includes('Alpha step 1'),
      hasOldRuns: text.includes('Alpha run 1'),
    };
  });
  expect(replaced.detailCount, 'exactly one flow diagram in the detail pane').toBe(1);
  expect(replaced.runRowCount, 'the old 100 runs are gone, the new 3 remain').toBe(3);
  expect(replaced.hasNewFlow, 'the chosen sequence\'s flow is shown').toBe(true);
  expect(replaced.hasOldFlow, 'the previous sequence\'s flow was replaced').toBe(false);
  expect(replaced.hasOldRuns, 'the previous sequence\'s runs were replaced').toBe(false);

  // --------------------------------------------------------------------
  // Defect proof: an in-flight response from an EARLIER row selection
  // must not overwrite the detail of the row chosen afterwards.  The
  // first row's flow response is held (the route is registered after the
  // catch-all, so it wins for that one request; times: 1 so later boots
  // of the same URL fall through to the catch-all)...
  // --------------------------------------------------------------------
  const held = [];
  await page.route(
    '**/api/load-sequences/seq-0001/bpmn',
    (route) => held.push(route),
    { times: 1 },
  );

  await row1.click();
  await expect.poll(() => held.length).toBeGreaterThan(0); // the flow request is in flight
  // ...and a later selection lands while it is still held.
  await row2.click();
  await expect(row2).toHaveAttribute('aria-current', 'true');
  await expect(row1).not.toHaveAttribute('aria-current');
  await expect(page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]')).toHaveCount(2);
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(3);

  // Now let the earlier selection's response through: it must be ignored.
  await held.shift().fulfill({
    status: 200,
    contentType: 'application/json',
    body: JSON.stringify(bpmnFor(CHOSEN_ID)),
  });
  await page.waitForTimeout(200);
  const late = await page.evaluate(() => {
    const pane = document.querySelector('[data-testid="seq-detail-pane"]');
    const current = document.querySelector('[data-testid="sequence-row"][aria-current="true"]');
    return {
      flowStepCount: pane.querySelectorAll('[data-testid="flow-step"]').length,
      hasLateFlow: (pane.textContent || '').includes('Alpha step 1'),
      currentId: current ? current.dataset.id : null,
    };
  });
  expect(late.flowStepCount, 'the later selection\'s flow is still on screen').toBe(2);
  expect(late.hasLateFlow, 'the earlier selection\'s late response did not overwrite the detail').toBe(false);
  expect(late.currentId, 'aria-current stays on the later selection').toBe(OTHER_ID);

  // --------------------------------------------------------------------
  // Scrolling: 200 sequences + 100 runs at 1440x900 — the document and
  // the main region do NOT scroll; the list pane scrolls with the name
  // input still in view; the detail pane scrolls.
  // --------------------------------------------------------------------
  await row1.click();
  await expect(row1).toHaveAttribute('aria-current', 'true');
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(100);

  const scroll = await page.evaluate(() => {
    const scroller = document.scrollingElement;
    const main = document.querySelector('[data-testid="main-content"]');
    const rows = document.querySelector('[data-testid="seq-list-pane"] [data-panel="sequences"]');
    const detailPane = document.querySelector('[data-testid="seq-detail-pane"]');
    const inputBox = document.querySelector('[data-testid="sequence-name-input"]').getBoundingClientRect();
    return {
      doc: scroller.scrollHeight - scroller.clientHeight,
      body: document.body.scrollHeight - document.body.clientHeight,
      winY: window.scrollY,
      main: main.scrollHeight - main.clientHeight,
      rows: rows.scrollHeight - rows.clientHeight,
      detail: detailPane.scrollHeight - detailPane.clientHeight,
      inputTop: inputBox.top,
      inputBottom: inputBox.bottom,
      vh: window.innerHeight,
    };
  });
  expect(scroll.doc, 'the document does not scroll').toBeLessThanOrEqual(0);
  expect(scroll.body, 'the document does not scroll').toBeLessThanOrEqual(0);
  expect(scroll.winY, 'the document is at the top').toBe(0);
  expect(scroll.main, 'the main region does not scroll').toBeLessThanOrEqual(0);
  expect(scroll.rows, 'the list pane scrolls').toBeGreaterThan(0);
  expect(scroll.detail, 'the detail pane scrolls').toBeGreaterThan(0);
  expect(scroll.inputTop, 'the name input stays in view').toBeGreaterThanOrEqual(0);
  expect(scroll.inputBottom, 'the name input stays in view').toBeLessThanOrEqual(scroll.vh);

  // Scroll the list rows down: they move, the name input stays put.
  const afterScroll = await page.evaluate(() => {
    const rows = document.querySelector('[data-testid="seq-list-pane"] [data-panel="sequences"]');
    rows.scrollTop = 600;
    const box = document.querySelector('[data-testid="sequence-name-input"]').getBoundingClientRect();
    return { scrollTop: rows.scrollTop, inputTop: box.top, inputBottom: box.bottom, vh: window.innerHeight };
  });
  expect(afterScroll.scrollTop, 'the rows area actually scrolled').toBeGreaterThan(0);
  expect(afterScroll.inputTop, 'the name input is still in view after scrolling').toBeGreaterThanOrEqual(0);
  expect(afterScroll.inputBottom, 'the name input is still in view after scrolling').toBeLessThanOrEqual(afterScroll.vh);
  await page.evaluate(() => {
    document.querySelector('[data-testid="seq-list-pane"] [data-panel="sequences"]').scrollTop = 0;
  });

  // --------------------------------------------------------------------
  // Defect proofs: hostile list and flow values.
  // --------------------------------------------------------------------
  // renderList survives null holes in the array: it skips them and still
  // renders the real sequences; an all-null list lands on the existing
  // empty note instead of crashing.
  const nullList = await page.evaluate(() => {
    const s = window.Sequences;
    const host = document.createElement('div');
    const hostAllNull = document.createElement('div');
    host.innerHTML = s.renderList([null, { id: 'n-1', name: 'Only row' }, null]);
    hostAllNull.innerHTML = s.renderList([null]);
    const row = host.querySelector('[data-testid="sequence-row"]');
    return {
      rowCount: host.querySelectorAll('[data-testid="sequence-row"]').length,
      rowId: row ? row.dataset.id : null,
      allNullEmpty: hostAllNull.querySelector('[data-testid="sequences-empty"]') !== null,
    };
  });
  expect(nullList.rowCount, 'null holes in the array render no rows').toBe(1);
  expect(nullList.rowId).toBe('n-1');
  expect(nullList.allNullEmpty, 'an all-null list lands on the empty note').toBe(true);

  // renderFlow's parse-error check is the document root: a <parsererror>
  // element inside the user's VALID document is content, not a parse
  // failure, while a genuinely broken document still errors.
  const parserProbe = await page.evaluate(() => {
    const s = window.Sequences;
    const validWithUserParsererror = s.renderFlow(
      '<?xml version="1.0" encoding="UTF-8"?>' +
      '<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL">' +
      '<bpmn:process id="proc-pe">' +
      '<bpmn:serviceTask name="Step beside parsererror"/>' +
      '<parsererror xmlns="http://www.w3.org/1999/xhtml">user content</parsererror>' +
      '</bpmn:process>' +
      '</bpmn:definitions>'
    );
    const broken = s.renderFlow('definitely not xml <');
    const host = document.createElement('div');
    const hostBroken = document.createElement('div');
    host.innerHTML = validWithUserParsererror;
    hostBroken.innerHTML = broken;
    return {
      userPeSteps: host.querySelectorAll('[data-testid="flow-step"]').length,
      userPeError: host.querySelectorAll('[data-testid="flow-error"]').length,
      brokenError: hostBroken.querySelectorAll('[data-testid="flow-error"]').length,
    };
  });
  expect(parserProbe.userPeSteps, 'valid XML with a user <parsererror> element renders its flow').toBe(1);
  expect(parserProbe.userPeError, 'a user <parsererror> element is not a parse failure').toBe(0);
  expect(parserProbe.brokenError, 'a genuinely broken document still reports the error').toBe(1);

  // --------------------------------------------------------------------
  // Safety: the hostile sequence name renders as text, never as markup.
  // --------------------------------------------------------------------
  const xssRow = page.locator('[data-testid="sequence-row"][data-id="' + XSS_ID + '"]');
  await expect(xssRow).toHaveText(XSS_NAME);
  expect(await xssRow.locator('img').count()).toBe(0);
  expect(await page.evaluate(() => window.__pwned)).toBeUndefined();

  // --------------------------------------------------------------------
  // Non-admin pass (role 'user'), after a full reload: booted the
  // production way, the admin-only controls are absent and the page
  // still renders — read-only.
  // --------------------------------------------------------------------
  me = VIEWER_ME;
  await page.goto('about:blank');
  await page.goto('/studio.html?panel=sequences#access_token=' + encodeURIComponent(VIEWER_TOKEN));
  await expect.poll(() => authHeaders).toContain('Bearer ' + VIEWER_TOKEN);

  await expect(page.locator('[data-testid="seq-list-pane"] [data-testid="sequence-name-input"]')).toBeVisible();
  await expect(page.locator('[data-testid="sequence-row"]')).toHaveCount(200);
  await expect(page.locator('[data-testid="sequence-create"]')).toHaveCount(0);

  // Anchor on the terminal states of every other tool's render path
  // before asserting no admin control survives anywhere in the document.
  await expect(page.locator('[data-panel="sequences"]')).toContainText('Sequence 1');
  await expect(page.locator('#sources')).toContainText(/No sources yet/);
  await expect(page.locator('#inbox')).toContainText(/No pending suggestions/);
  await expect(page.locator('[data-testid="retention-policies-empty"]')).toHaveText('No retention policies yet.');
  await expect(page.locator('[data-testid="ingestion-pipelines-empty"]')).toHaveText('No pipelines yet.');
  await expect(page.locator('[data-testid="audit-admin-only-note"]'))
    .toHaveText('Audit history is available to administrators.');
  await expect(page.locator('[data-panel="feedkeys"]')).toHaveCount(0);
  await expect(page.locator('[data-requires-role="admin"]')).toHaveCount(0);

  // The page still renders and still works read-only: the detail pane
  // shows the pre-selection note, and choosing a row loads its flow and
  // runs WITHOUT the admin-only Execute control.
  await expect(page.locator('[data-testid="seq-detail-pane"] [data-testid="sequence-runs"]'))
    .toHaveText('Select a load sequence to see its runs.');
  await page.locator('[data-testid="sequence-row"]').first().click();
  await expect(page.locator('[data-testid="sequence-detail"] [data-testid="flow-step"]')).toHaveCount(3);
  await expect(page.locator('[data-testid="sequence-runs"] [data-testid="run-row"]')).toHaveCount(100);
  await expect(page.locator('[data-testid="sequence-execute"]')).toHaveCount(0);

  // --------------------------------------------------------------------
  // Narrow screens: at 390x844 the panes stack and the page does not
  // scroll sideways.
  // --------------------------------------------------------------------
  await page.setViewportSize({ width: 390, height: 844 });
  const stacked = await page.evaluate(() => {
    const listBox = document.querySelector('[data-testid="seq-list-pane"]').getBoundingClientRect();
    const detailBox = document.querySelector('[data-testid="seq-detail-pane"]').getBoundingClientRect();
    return {
      detailBelowList: detailBox.top >= listBox.bottom - 1,
      scrollX: window.scrollX,
      doc: document.documentElement.scrollWidth - document.documentElement.clientWidth,
      body: document.body.scrollWidth - document.body.clientWidth,
    };
  });
  expect(stacked.detailBelowList, 'at 390px the detail pane stacks under the list pane').toBe(true);
  expect(stacked.scrollX, 'no horizontal page scroll').toBe(0);
  expect(stacked.doc, 'no horizontal page scroll').toBeLessThanOrEqual(0);
  expect(stacked.body, 'no horizontal page scroll').toBeLessThanOrEqual(0);
});
