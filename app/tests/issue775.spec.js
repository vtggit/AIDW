    expect(dismissReq).toBeTruthy();
    expect(dismissReq.method).toBe('POST');
    expect(dismissReq.auth).toBe(bearer);
    expect(dismissReq.body).toBeNull();

    const byId = Object.fromEntries(mock.flags.map((f) => [f.id, f.status]));
