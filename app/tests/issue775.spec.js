// Proof for issue #775 — the repaired frontend proofs for the PII flags review loop and
// the Process wizard run against MOCKED /api/** responses with no backend.
//
// Every /api/** request is stubbed with page.route BEFORE page.goto (the pattern
// suggestions.spec.js / issue767.spec.js / issue700.spec.js use) and recorded — method,
// path, Authorization header, JSON body — so the proof asserts the wire contract instead
// of requiring a live stack. Proven:
//   AC-1  /studio.html?panel=pii renders pending PII flags grouped by dataset (the
//         dataset name, the column and the category); Confirm and Dismiss each send
//         their request for the right flag id and remove that flag from the panel.
//         /studio.html?panel=wizard shows the wizard's definitions, steps, flows and
//         diagram regions; creating a definition sends POST /api/process-definitions
//         and shows the new definition's card; Generate renders the server's SVG
//         diagram with its shapes
//   AC-2  the repaired proofs (app/tests/pii_flags.spec.js, app/tests/250_ac_1.spec.js)
//         stub **/api/** via page.route and assert the expected request method, path,
//         Authorization header, JSON body and response shape — this spec exercises the
//         same flows through the same stubbing and request assertions
//   Identity the criteria concern roles and login, so the proof also runs as a
//         non-admin (role 'user') booted the production way: the token in the URL hash
//         (#access_token=...), /api/auth/config and /api/auth/me mocked for that user,
//         the hash token reaching /api/auth/me as a Bearer header while the page still
//         renders with the admin-only controls absent
const { test, expect } = require('@playwright/test');

// CodeAgent terminal-state hook (frontend_recipe.build_terminal_state_hook)
// CodeAgent#751: once this proof's own assertions pass, nothing on the page may still
// show a loading placeholder. A render path that never reaches its terminal state
// (data, an empty note, an error) is a defect the proof did not ask about. Elements
// under [data-loading-ok] are exempt. Generated by the engine at write time -- edit
// the generator, not this block.
test.afterEach(async ({ page }, testInfo) => {
  if (testInfo.status !== testInfo.expectedStatus || page.isClosed()) return;
  const stuck = await page.evaluate((markers) => Array.from(document.querySelectorAll('body *')).filter((el) => {
    if (el.children.length || el.closest('[data-loading-ok]')) return false;
    const t = (el.textContent || '').trim();
    if (!t || !markers.some((m) => t === m || t.startsWith(m))) return false;
    const r = el.getBoundingClientRect();
    return r.width > 0 && r.height > 0;
  }).map((el) => {
    const p = el.closest('[data-panel]');
    const cls = (el.getAttribute('class') || '').trim().split(/\s+/)[0];
    return (p && p.getAttribute('data-panel')) || (el.tagName.toLowerCase() + (cls ? '.' + cls : ''));
  }), ["Loading data\u2026", "Loading data...", "Loading\u2026", "Loading..."]).catch(() => []);
  test.expect(stuck, `element(s) still showing a loading placeholder after the proof: ${stuck.join(', ')} -- every render path must reach a terminal state (data, an empty note or an error), or declare data-loading-ok`).toEqual([]);
});


